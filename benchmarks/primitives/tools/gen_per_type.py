#!/usr/bin/env python3
"""Generate the mechanically repetitive per-type benchmarks.

Usage (from `benchmarks/primitives`): python3 tools/gen_per_type.py
Writes `src/arith.cairo` and `src/bitwise.cairo`. Expected values are computed here so that every
benchmark doubles as a correctness test.
"""
import os

P = 2**251 + 17 * 2**192 + 1
HERE = os.path.dirname(os.path.abspath(__file__))

UNSIGNED = {
    "u8": (8, 35, 7),
    "u16": (16, 1234, 50),
    "u32": (32, 100_000, 40_000),
    "u64": (64, 5_000_000_000, 3_000_000_000),
    "u128": (128, 2**100 + 12345, 2**27 + 5),
    "u256": (256, 2**200 + 2**100 + 7, 2**40 + 3),
}
SIGNED = {
    "i8": (8, -11, 7),
    "i16": (16, -150, 100),
    "i32": (32, -40_000, 30_000),
    "i64": (64, -3_000_000_000, 2_000_000_000),
    "i128": (128, -(2**100 + 12345), 2**26 + 5),
}
WIDE = {"u8": "u16", "u16": "u32", "u32": "u64", "u64": "u128", "u128": "u256", "u256": "u512",
        "i8": "i16", "i16": "i32", "i32": "i64", "i64": "i128"}


def lit(v, ty):
    if ty == "u512":
        limbs = [(v >> (128 * i)) & (2**128 - 1) for i in range(4)]
        return "u512 { " + ", ".join(f"limb{i}: {hex(l)}" for i, l in enumerate(limbs)) + " }"
    if v < 0:
        return f"-{hex(-v)}_{ty}" if ty != "felt252" else f"-{hex(-v)}"
    return f"{hex(v)}_{ty}" if ty != "felt252" else hex(v)


def tdiv(a, b):
    q = abs(a) // abs(b)
    if (a < 0) != (b < 0):
        q = -q
    return q, a - q * b


def test(group, variant, ty, a, b, body):
    return f"""
    #[test]
    #[inline(never)]
    fn bench_{group}__{variant}() {{
        let a: {ty} = black_box({lit(a, ty)});
        let b: {ty} = black_box({lit(b, ty)});
{body}
    }}
"""


def one(expr, expected):
    return f"        let _ = b;\n        assert!({expr} == {expected});" if "b" not in expr.replace("black_box", "") \
        else f"        assert!({expr} == {expected});"


ARITH_HEADER = """//! GENERATED by `tools/gen_per_type.py` - do not edit by hand.
//!
//! Per-type arithmetic: `arith_<T>` (single-result ops, one `==` assertion), `divrem_<T>`
//! (two results, two assertions) and `cmp_<T>` (boolean results).

use core::num::traits::{
    CheckedAdd, CheckedMul, CheckedSub, OverflowingAdd, OverflowingMul, OverflowingSub,
    SaturatingAdd, SaturatingMul, SaturatingSub, WideMul, WrappingAdd, WrappingMul, WrappingSub,
};

pub fn add<T, +Add<T>>(a: T, b: T) -> T {
    a + b
}
pub fn sub<T, +Sub<T>>(a: T, b: T) -> T {
    a - b
}
pub fn mul<T, +Mul<T>>(a: T, b: T) -> T {
    a * b
}
pub fn div<T, +Div<T>>(a: T, b: T) -> T {
    a / b
}
pub fn rem<T, +Rem<T>>(a: T, b: T) -> T {
    a % b
}
pub fn neg<T, +Neg<T>>(a: T) -> T {
    -a
}
pub fn div_rem<T, +DivRem<T>, +TryInto<T, NonZero<T>>, +Drop<T>>(a: T, b: T) -> (T, T) {
    DivRem::div_rem(a, b.try_into().unwrap())
}
pub fn div_and_rem<T, +Div<T>, +Rem<T>, +Copy<T>, +Drop<T>>(a: T, b: T) -> (T, T) {
    (a / b, a % b)
}
pub fn wide_mul<T, impl W: WideMul<T, T>>(a: T, b: T) -> W::Target {
    a.wide_mul(b)
}
pub fn overflowing_add<T, +OverflowingAdd<T>, +Drop<T>>(a: T, b: T) -> T {
    let (r, _) = a.overflowing_add(b);
    r
}
pub fn overflowing_sub<T, +OverflowingSub<T>, +Drop<T>>(a: T, b: T) -> T {
    let (r, _) = a.overflowing_sub(b);
    r
}
pub fn overflowing_mul<T, +OverflowingMul<T>, +Drop<T>>(a: T, b: T) -> T {
    let (r, _) = a.overflowing_mul(b);
    r
}
pub fn wrapping_add<T, +WrappingAdd<T>>(a: T, b: T) -> T {
    a.wrapping_add(b)
}
pub fn wrapping_sub<T, +WrappingSub<T>>(a: T, b: T) -> T {
    a.wrapping_sub(b)
}
pub fn wrapping_mul<T, +WrappingMul<T>>(a: T, b: T) -> T {
    a.wrapping_mul(b)
}
pub fn checked_add<T, +CheckedAdd<T>>(a: T, b: T) -> T {
    a.checked_add(b).unwrap()
}
pub fn checked_sub<T, +CheckedSub<T>>(a: T, b: T) -> T {
    a.checked_sub(b).unwrap()
}
pub fn checked_mul<T, +CheckedMul<T>>(a: T, b: T) -> T {
    a.checked_mul(b).unwrap()
}
pub fn saturating_add<T, +SaturatingAdd<T>>(a: T, b: T) -> T {
    a.saturating_add(b)
}
pub fn saturating_sub<T, +SaturatingSub<T>>(a: T, b: T) -> T {
    a.saturating_sub(b)
}
pub fn saturating_mul<T, +SaturatingMul<T>>(a: T, b: T) -> T {
    a.saturating_mul(b)
}
/// Baseline of the `cmp_*` groups: consumes the operands, compares nothing.
pub fn always<T, +Drop<T>>(a: T, b: T) -> bool {
    true
}
pub fn eq<T, +PartialEq<T>, +Drop<T>>(a: T, b: T) -> bool {
    a == b
}
pub fn ne<T, +PartialEq<T>, +Drop<T>>(a: T, b: T) -> bool {
    a != b
}
pub fn lt<T, +PartialOrd<T>>(a: T, b: T) -> bool {
    a < b
}
pub fn le<T, +PartialOrd<T>>(a: T, b: T) -> bool {
    a <= b
}
pub fn gt<T, +PartialOrd<T>>(a: T, b: T) -> bool {
    a > b
}
pub fn ge<T, +PartialOrd<T>>(a: T, b: T) -> bool {
    a >= b
}
"""


def gen_arith():
    out = [ARITH_HEADER]
    consts = []
    tests = []
    for ty, (bits, a, b) in {**UNSIGNED, **SIGNED}.items():
        signed = ty.startswith("i")
        q, r = tdiv(a, b)
        # const-divisor helpers
        consts.append(f"""const NZ_{ty.upper()}: NonZero<{ty}> = {hex(b)};
pub fn div_const_{ty}(a: {ty}) -> {ty} {{
    a / {lit(b, ty)}
}}
pub fn rem_const_{ty}(a: {ty}) -> {ty} {{
    a % {lit(b, ty)}
}}
pub fn div_rem_const_{ty}(a: {ty}) -> ({ty}, {ty}) {{
    DivRem::div_rem(a, NZ_{ty.upper()})
}}
pub fn mul_const_{ty}(a: {ty}) -> {ty} {{
    a * {lit(b, ty)}
}}
""")
        g = f"arith_{ty}"
        t = [test(g, "baseline", ty, a, b, one("a", lit(a, ty)))]
        single = [("add", a + b), ("sub", a - b), ("mul", a * b), ("div", q), ("rem", r)]
        for name, exp in single:
            t.append(test(g, name, ty, a, b, one(f"{name}(a, b)", lit(exp, ty))))
        t.append(test(g, "mul_const", ty, a, b, one(f"mul_const_{ty}(a)", lit(a * b, ty))))
        t.append(test(g, "div_const", ty, a, b, one(f"div_const_{ty}(a)", lit(q, ty))))
        t.append(test(g, "rem_const", ty, a, b, one(f"rem_const_{ty}(a)", lit(r, ty))))
        if ty in WIDE:
            t.append(test(g, "wide_mul", ty, a, b, one("wide_mul(a, b)", lit(a * b, WIDE[ty]))))
        for fam in ["overflowing", "wrapping", "checked", "saturating"]:
            for name, exp in [("add", a + b), ("sub", a - b), ("mul", a * b)]:
                if signed and name == "mul":
                    continue
                t.append(test(g, f"{fam}_{name}", ty, a, b, one(f"{fam}_{name}(a, b)", lit(exp, ty))))
        if signed:
            t.append(test(g, "neg", ty, a, b, one("neg(a)", lit(-a, ty))))
            # positive/positive paths (signed ops branch on the signs)
            pq, pr = tdiv(-a, b)
            for name, exp in [("add", -a + b), ("sub", -a - b), ("mul", -a * b), ("div", pq), ("rem", pr)]:
                t.append(test(g, f"{name}_pos", ty, a, b, one(f"{name}(neg_input(a), b)", lit(exp, ty))))
        tests += t

        g = f"divrem_{ty}"
        two = lambda expr: f"        let (q, r) = {expr};\n        assert!(q == {lit(q, ty)});\n        assert!(r == {lit(r, ty)});"
        tests.append(test(g, "baseline", ty, a, b,
                          f"        assert!(a == {lit(a, ty)});\n        assert!(b == {lit(b, ty)});"))
        tests.append(test(g, "div_rem", ty, a, b, two("div_rem(a, b)")))
        tests.append(test(g, "div_and_rem_separately", ty, a, b, two("div_and_rem(a, b)")))
        tests.append(test(g, "div_rem_const", ty, a, b, "        let _ = b;\n" + two(f"div_rem_const_{ty}(a)")))

        g = f"cmp_{ty}"
        tests.append(test(g, "baseline", ty, a, b, "        assert!(always(a, b));"))
        for name, exp in [("eq", a == b), ("ne", a != b), ("lt", a < b), ("le", a <= b), ("gt", a > b), ("ge", a >= b)]:
            tests.append(test(g, name, ty, a, b, f"        assert!({'' if exp else '!'}{name}(a, b));"))

    # felt252
    a, b = 2**200 + 987654321, 2**100 + 12345
    g = "arith_felt252"
    tests.append(test(g, "baseline", "felt252", a, b, one("a", lit(a, "felt252"))))
    for name, exp in [("add", (a + b) % P), ("sub", (a - b) % P), ("mul", (a * b) % P)]:
        tests.append(test(g, name, "felt252", a, b, one(f"{name}(a, b)", lit(exp, "felt252"))))
    tests.append(test(g, "felt252_div", "felt252", a, b, one("felt_div(a, b)", lit(a * pow(b, -1, P) % P, "felt252"))))
    tests.append(test(g, "felt252_div_const", "felt252", a, b, one("felt_div_const(a)", lit(a * pow(b, -1, P) % P, "felt252"))))
    tests.append(test(g, "neg", "felt252", a, b, one("neg(a)", lit((-a) % P, "felt252"))))
    g = "cmp_felt252"
    tests.append(test(g, "baseline", "felt252", a, b, "        assert!(always(a, b));"))
    tests.append(test(g, "eq", "felt252", a, b, "        assert!(!eq(a, b));"))
    tests.append(test(g, "ne", "felt252", a, b, "        assert!(ne(a, b));"))
    consts.append(f"""pub fn felt_div(a: felt252, b: felt252) -> felt252 {{
    core::felt252_div(a, b.try_into().unwrap())
}}
pub fn felt_div_const(a: felt252) -> felt252 {{
    core::felt252_div(a, {lit(b, 'felt252')})
}}
/// Negation used to feed the positive/positive signed paths from the same black-boxed input.
pub fn neg_input<T, +Neg<T>>(a: T) -> T {{
    -a
}}
""")

    # u512 / u256
    a, b = 2**250 + 2**130 + 99, 2**200 + 2**64 + 5
    d = 2**129 + 77
    prod = a * b
    g = "arith_u512"
    body_base = f"        let _ = b;\n        assert!(a == {lit(a, 'u256')});"
    tests.append(test(g, "baseline", "u256", a, b, body_base))
    tests.append(test(g, "u256_wide_mul", "u256", a, b, f"        assert!(wide_mul(a, b) == {lit(prod, 'u512')});"))
    tests.append(test(g, "u256_wide_mul_then_div_rem_by_u256", "u256", a, b,
                      f"        let (q, r) = mul_div_u256(a, b, {lit(d, 'u256')});\n"
                      f"        assert!(q == {lit(prod // d, 'u512')});\n        assert!(r == {lit(prod % d, 'u256')});"))
    tests.append(test(g, "u512_safe_div_rem_by_u256", "u256", a, b,
                      f"        let (q, r) = div_u512(black_box({lit(prod, 'u512')}), b);\n        let _ = a;\n"
                      f"        assert!(q == {lit(prod // b, 'u512')});\n        assert!(r == {lit(prod % b, 'u256')});"))
    consts.append("""pub fn mul_div_u256(a: u256, b: u256, d: u256) -> (core::integer::u512, u256) {
    core::integer::u512_safe_div_rem_by_u256(a.wide_mul(b), d.try_into().unwrap())
}
pub fn div_u512(a: core::integer::u512, d: u256) -> (core::integer::u512, u256) {
    core::integer::u512_safe_div_rem_by_u256(a, d.try_into().unwrap())
}
""")

    out.append("\n".join(consts))
    out.append("#[cfg(test)]\nmod tests {\n    use core::integer::u512;\n    use harness::black_box;\n    use super::*;\n" + "".join(tests) + "}\n")
    with open(os.path.join(HERE, "../src/arith.cairo"), "w") as f:
        f.write("\n".join(out))


BITWISE_HEADER = """//! GENERATED by `tools/gen_per_type.py` - do not edit by hand.
//!
//! Per-type bitwise operators: `bitwise_<T>` groups (same input/assertion shape as `arith_<T>`,
//! so net figures are directly comparable).

use core::traits::{BitAnd, BitNot, BitOr, BitXor};

pub fn and<T, +BitAnd<T>>(a: T, b: T) -> T {
    a & b
}
pub fn or<T, +BitOr<T>>(a: T, b: T) -> T {
    a | b
}
pub fn xor<T, +BitXor<T>>(a: T, b: T) -> T {
    a ^ b
}
pub fn not<T, +BitNot<T>>(a: T) -> T {
    ~a
}
/// `a & b`, `a | b` and `a ^ b` at once: the underlying libfunc returns the three results, does
/// the compiler share the builtin call?
pub fn and_or_xor<T, +BitAnd<T>, +BitOr<T>, +BitXor<T>, +Copy<T>, +Drop<T>>(a: T, b: T) -> (T, T, T) {
    (a & b, a | b, a ^ b)
}
"""


def gen_bitwise():
    tests = []
    for ty, (bits, a, b) in UNSIGNED.items():
        g = f"bitwise_{ty}"
        mask = 2**bits - 1
        tests.append(test(g, "baseline", ty, a, b, one("a", lit(a, ty))))
        for name, exp in [("and", a & b), ("or", a | b), ("xor", a ^ b)]:
            tests.append(test(g, name, ty, a, b, one(f"{name}(a, b)", lit(exp, ty))))
        tests.append(test(g, "not", ty, a, b, one("not(a)", lit(mask ^ a, ty))))
        tests.append(test(g, "and_or_xor_x3_assert", ty, a, b,
                          f"        let (x, y, z) = and_or_xor(a, b);\n        assert!(x == {lit(a & b, ty)});\n"
                          f"        assert!(y == {lit(a | b, ty)});\n        assert!(z == {lit(a ^ b, ty)});"))
    with open(os.path.join(HERE, "../src/bitwise.cairo"), "w") as f:
        f.write(BITWISE_HEADER + "\n#[cfg(test)]\nmod tests {\n    use harness::black_box;\n    use super::*;\n"
                + "".join(tests) + "}\n")


if __name__ == "__main__":
    gen_arith()
    gen_bitwise()
