#!/usr/bin/env python3
"""Generate `src/lookup.cairo` (64-entry pow2 table implemented several ways) and
`src/msb_tree.cairo` (most-significant-bit index as a 64-leaf comparison tree).

Usage (from `benchmarks/primitives`): python3 tools/gen_lookup.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N = 64


def tree(lo, hi, indent):
    pad = "    " * indent
    if lo == hi:
        return f"{pad}{hex(1 << lo)}\n"
    mid = (lo + hi + 1) // 2
    return (f"{pad}if k < {mid} {{\n" + tree(lo, mid - 1, indent + 1) + f"{pad}}} else {{\n"
            + tree(mid, hi, indent + 1) + f"{pad}}}\n")


def msb_tree(lo, hi, indent):
    """Index of the most significant bit, knowing it lies in [lo, hi]."""
    pad = "    " * indent
    if lo == hi:
        return f"{pad}{lo}\n"
    mid = (lo + hi + 1) // 2
    return (f"{pad}if x < {hex(1 << mid)} {{\n" + msb_tree(lo, mid - 1, indent + 1) + f"{pad}}} else {{\n"
            + msb_tree(mid, hi, indent + 1) + f"{pad}}}\n")


def gen_msb_tree():
    src = f"""//! GENERATED by `tools/gen_lookup.py` - do not edit by hand.

/// Index of the most significant bit of a non-zero `u64`: pure comparison tree (6 comparisons
/// against constants, no arithmetic).
pub fn msb_if_tree(x: u64) -> u32 {{
{msb_tree(0, 63, 1)}}}
"""
    with open(os.path.join(HERE, "../src/msb_tree.cairo"), "w") as file:
        file.write(src)


def main():
    gen_msb_tree()
    match_arms = "".join(f"        {i} => {hex(1 << i)},\n" for i in range(N))
    table = ", ".join(hex(1 << i) for i in range(N))
    chain = "    " + " else ".join(f"if k == {i} {{\n        {hex(1 << i)}\n    }}" for i in range(N))
    chain += " else {\n        core::panic_with_felt252('pow2 out of range')\n    }\n"
    src = f"""//! GENERATED by `tools/gen_lookup.py` - do not edit by hand.
//!
//! `2^k` for `k` in `0..64`, as a lookup table vs. computed. Group `lookup_pow2`: every variant
//! performs three lookups (k = 3, 31, 63, black-boxed) and asserts their sum.

use core::num::traits::Pow;

/// `match` on the index: compiled to a jump table.
pub fn pow2_match(k: u32) -> u64 {{
    match k {{
{match_arms}        _ => core::panic_with_felt252('pow2 out of range'),
    }}
}}

const TABLE: [u64; {N}] = [{table}];

/// `const` fixed-size array, indexed through its span (bounds-checked).
pub fn pow2_const_array(k: u32) -> u64 {{
    *TABLE.span()[k]
}}

/// Same table received as a span built once by the caller (amortised `.span()`).
pub fn pow2_span(table: Span<u64>, k: u32) -> u64 {{
    *table[k]
}}

pub fn table_span() -> Span<u64> {{
    TABLE.span()
}}

/// Binary decision tree of `if k < mid` (6 comparisons).
pub fn pow2_if_tree(k: u32) -> u64 {{
{tree(0, N - 1, 1)}}}

/// Linear `if k == 0 {{ .. }} else if k == 1 {{ .. }}` chain (up to 64 comparisons).
pub fn pow2_if_chain(k: u32) -> u64 {{
{chain}}}

/// corelib `Pow` (square-and-multiply, recursive).
pub fn pow2_corelib_pow(k: u32) -> u64 {{
    2_u64.pow(k)
}}

/// Naive loop: k multiplications.
pub fn pow2_loop(k: u32) -> u64 {{
    let mut r: u64 = 1;
    let mut i = k;
    while i != 0 {{
        r *= 2;
        i -= 1;
    }}
    r
}}

/// felt252 dictionary-free trick: 2^k = 2^(k0) * 2^(2 k1) * ... from the 6 bits of k, computed
/// with DivRem by 2 and conditional multiplications in felt252, one final range check.
pub fn pow2_bits_felt(k: u32) -> u64 {{
    let mut r: felt252 = 1;
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x2;
    }}
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x4;
    }}
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x10;
    }}
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x100;
    }}
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x10000;
    }}
    let (k, b) = DivRem::div_rem(k, 2);
    if b == 1 {{
        r *= 0x100000000;
    }}
    assert(k == 0, 'pow2 out of range');
    r.try_into().unwrap()
}}

#[cfg(test)]
mod tests {{
    use harness::black_box;
    use super::*;

    const EXPECTED: u64 = 0x8000000080000008;

    #[test]
    #[inline(never)]
    fn bench_lookup_pow2__baseline() {{
        let (a, b, c): (u32, u32, u32) = (black_box(3), black_box(31), black_box(63));
        assert!(a + b + c == 97);
    }}
"""
    for name, call in [
        ("match_jump_table", "pow2_match({})"),
        ("const_array_span_index", "pow2_const_array({})"),
        ("if_tree_binary", "pow2_if_tree({})"),
        ("if_chain_linear", "pow2_if_chain({})"),
        ("corelib_pow", "pow2_corelib_pow({})"),
        ("loop_mul", "pow2_loop({})"),
        ("bits_felt_mul", "pow2_bits_felt({})"),
    ]:
        src += f"""
    #[test]
    #[inline(never)]
    fn bench_lookup_pow2__{name}() {{
        let (a, b, c): (u32, u32, u32) = (black_box(3), black_box(31), black_box(63));
        assert!({call.format('a')} + {call.format('b')} + {call.format('c')} == EXPECTED);
    }}
"""
    src += """
    #[test]
    #[inline(never)]
    fn bench_lookup_pow2__shared_span_index() {
        let (a, b, c): (u32, u32, u32) = (black_box(3), black_box(31), black_box(63));
        let table = table_span();
        assert!(pow2_span(table, a) + pow2_span(table, b) + pow2_span(table, c) == EXPECTED);
    }

    #[test]
    fn test_all_variants_agree() {
        for k in 0..64_u32 {
            let expected = pow2_match(k);
            assert!(pow2_const_array(k) == expected);
            assert!(pow2_if_tree(k) == expected);
            assert!(pow2_if_chain(k) == expected);
            assert!(pow2_corelib_pow(k) == expected);
            assert!(pow2_loop(k) == expected);
            assert!(pow2_bits_felt(k) == expected);
        }
    }
}
"""
    with open(os.path.join(HERE, "../src/lookup.cairo"), "w") as file:
        file.write(src)


if __name__ == "__main__":
    main()
