#!/usr/bin/env python3
"""Generate `src/conversions.cairo` (usage, from `benchmarks/primitives`: python3 tools/gen_conversions.py)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# source type -> (default value, [(kind, destination type[, specific value])])
ROWS = {
    "u8": (200, [("into", "u16"), ("into", "u32"), ("into", "u64"), ("into", "u128"), ("into", "u256"),
                 ("into", "felt252"), ("into", "i16"), ("into", "i128"), ("try_into", "i8", 100)]),
    "u32": (70000, [("into", "u64"), ("into", "u128"), ("into", "u256"), ("into", "felt252"), ("into", "i64"),
                    ("try_into", "u8", 200), ("try_into", "u16", 60000), ("try_into", "i32")]),
    "u64": (5_000_000_000, [("into", "u128"), ("into", "u256"), ("into", "felt252"), ("into", "i128"),
                            ("try_into", "u8", 200), ("try_into", "u32", 70000), ("try_into", "i64")]),
    "u128": (2**100 + 5, [("into", "u256"), ("into", "felt252"), ("try_into", "u8", 200), ("try_into", "u32", 70000),
                          ("try_into", "u64", 5_000_000_000), ("try_into", "i128")]),
    "u256": (2**200 + 5, [("try_into", "felt252"), ("try_into", "u128", 2**100 + 5),
                          ("try_into", "u64", 5_000_000_000), ("try_into", "u8", 200)]),
    "felt252": (2**200 + 5, [("into", "u256"), ("try_into", "u128", 2**100 + 5), ("try_into", "u64", 5_000_000_000),
                             ("try_into", "u32", 70000), ("try_into", "u8", 200),
                             ("try_into", "i64", -5_000_000_000), ("try_into", "i128", -(2**100 + 5))]),
    "i64": (-5_000_000_000, [("into", "felt252"), ("into", "i128"), ("try_into", "i32", -70000),
                             ("try_into", "i8", -100), ("try_into", "u64", 5_000_000_000),
                             ("try_into", "u128", 5_000_000_000)]),
    "i128": (-(2**100 + 5), [("into", "felt252"), ("try_into", "i64", -5_000_000_000),
                             ("try_into", "u128", 2**100 + 5), ("try_into", "u64", 5_000_000_000)]),
}

HEADER = """//! GENERATED by `tools/gen_conversions.py` - do not edit by hand.
//!
//! Integer conversions: `conv_from_<T>` groups. The baseline asserts the black-boxed source value,
//! variants assert the converted value (in the destination type).

pub fn into<S, D, +Into<S, D>>(v: S) -> D {
    v.into()
}
pub fn try_into<S, D, +TryInto<S, D>>(v: S) -> D {
    v.try_into().unwrap()
}

/// bool -> integer: corelib only offers `bool -> felt252`; integers need a branch or a narrowing.
pub fn bool_to_u64_branch(c: bool) -> u64 {
    if c {
        1
    } else {
        0
    }
}
pub fn bool_to_u64_via_felt(c: bool) -> u64 {
    let f: felt252 = c.into();
    f.try_into().unwrap()
}
pub fn bool_to_felt(c: bool) -> felt252 {
    c.into()
}

#[cfg(test)]
mod tests {
    use harness::black_box;
    use super::{bool_to_felt, bool_to_u64_branch, bool_to_u64_via_felt, into, try_into};
"""

BOOL_TESTS = """
    #[test]
    #[inline(never)]
    fn bench_conv_from_bool__baseline() {
        let c = black_box(true);
        assert!(c);
    }

    #[test]
    #[inline(never)]
    fn bench_conv_from_bool__into_felt252() {
        let c = black_box(true);
        assert!(bool_to_felt(c) == 1);
    }

    #[test]
    #[inline(never)]
    fn bench_conv_from_bool__if_else_u64() {
        let c = black_box(true);
        assert!(bool_to_u64_branch(c) == 1);
    }

    #[test]
    #[inline(never)]
    fn bench_conv_from_bool__into_felt252_try_into_u64() {
        let c = black_box(true);
        assert!(bool_to_u64_via_felt(c) == 1);
    }
"""


def lit(v, ty):
    text = hex(v) if v >= 0 else "-" + hex(-v)
    return text if ty == "felt252" else f"{text}_{ty}"


def main():
    out = [HEADER]
    for src, (val, convs) in ROWS.items():
        group = f"conv_from_{src}"
        out.append(f"""
    #[test]
    #[inline(never)]
    fn bench_{group}__baseline() {{
        let v: {src} = black_box({lit(val, src)});
        assert!(v == {lit(val, src)});
    }}
""")
        for conv in convs:
            kind, dst = conv[0], conv[1]
            v = conv[2] if len(conv) > 2 else val
            out.append(f"""
    #[test]
    #[inline(never)]
    fn bench_{group}__{kind}_{dst}() {{
        let v: {src} = black_box({lit(v, src)});
        let r: {dst} = {kind}(v);
        assert!(r == {lit(v, dst)});
    }}
""")
    out.append(BOOL_TESTS)
    out.append("}\n")
    with open(os.path.join(HERE, "../src/conversions.cairo"), "w") as file:
        file.write("".join(out))


if __name__ == "__main__":
    main()
