#!/usr/bin/env python3
"""Generate the layout x scalar x operation test matrix (Cairo has no test macros).

Usage: python3 gen_tests.py && scarb fmt -p layout   (from benchmarks/layout; rewrites src/*_gen.cairo)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCALARS = {"fixed": "Fixed", "i64": "i64", "felt": "felt252"}
HEADER = "// @generated by gen_tests.py — do not edit by hand.\n"


def vec3():
    layouts = {
        "struct": "Vec3", "array": "Vec3A", "tuple": "Vec3T",
        "span_index": "DVecIdx", "span_box": "DVecBox", "span_loop": "DVecLoop",
    }
    ops = {  # op -> baseline runner
        "construct": "baseline3", "add": "baseline3", "sub": "baseline3", "scale": "baseline3",
        "neg": "baseline3", "cross": "baseline3", "dot": "baseline1", "equals": "equals_baseline",
        "chain": "baseline3",
    }
    out = [HEADER, "use crate::fixed::Fixed;", "use crate::vec3::runners;",
           "use crate::vec3::{DVecBox, DVecIdx, DVecLoop, Vec3, Vec3A, Vec3T};", ""]
    for op, baseline in ops.items():
        for sname, sty in SCALARS.items():
            group = f"vec3_{op}_{sname}"
            out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__baseline() {{", f"    runners::{baseline}::<{sty}>();", "}", ""]
            for lname, lty in layouts.items():
                out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__{lname}() {{",
                        f"    runners::{op}::<{lty}<{sty}>, {sty}>();", "}", ""]
    return "\n".join(out)


