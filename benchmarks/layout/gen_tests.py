def struct_vec3_impl():
    """Source text of the generic named-field impl, used as the template of the variants."""
    with open(os.path.join(HERE, "src", "vec3.cairo")) as file:
        source = file.read()
    start = source.index("pub impl StructVec3<")
    return source[start:source.index("\n}\n", start) + 3]


def vec3_variants():
    """Same impl as `StructVec3`, cloned as generic/concrete x inline policy."""
    template = struct_vec3_impl()
    out = [HEADER, "use crate::fixed::Fixed;", "use crate::vec3::Vec3Ops;", ""]
    policies = {"Always": "#[inline(always)]", "Never": "#[inline(never)]", "Default": None}
    for policy, attribute in policies.items():
        for concrete in (False, True):
            if policy == "Default" and not concrete:
                continue  # that one is `vec3::StructVec3` itself
            name = f"Vec3{'Fixed' if concrete else 'Gen'}{policy}"
            body = template.replace("StructVec3", f"{name}Impl")
            if concrete:
                body = body.replace("Vec3<T>", name).replace("Vec3 {", f"{name} {{")
                head_end = body.index("> of ") + 1
                body = f"pub impl {name}Impl" + body[head_end:]
                body = body.replace(", T>", ", Fixed>").replace(": T", ": Fixed").replace("-> T", "-> Fixed")
                decl = f"pub struct {name} {{\n    pub x: Fixed,\n    pub y: Fixed,\n    pub z: Fixed,\n}}"
            else:
                body = body.replace("Vec3<T>", f"{name}<T>").replace("Vec3 {", f"{name} {{")
                decl = f"pub struct {name}<T> {{\n    pub x: T,\n    pub y: T,\n    pub z: T,\n}}"
            if attribute:
                body = body.replace("    fn ", f"    {attribute}\n    fn ")
                if policy == "Never":  # only the operations: constructor / accessors stay default
                    for accessor in ("new", "x", "y", "z"):
                        body = body.replace(f"    {attribute}\n    fn {accessor}(", f"    fn {accessor}(")
            out += ["#[derive(Copy, Drop)]", decl, "", body, ""]
    return "\n".join(out)


def abstraction():
    variants = {
        "generic_default": "Vec3<Fixed>", "generic_inline_always": "Vec3GenAlways<Fixed>",
        "generic_inline_never": "Vec3GenNever<Fixed>", "concrete_default": "Vec3FixedDefault",
        "concrete_inline_always": "Vec3FixedAlways", "concrete_inline_never": "Vec3FixedNever",
    }
    ops = {"add": "baseline3", "dot": "baseline1", "cross": "baseline3", "chain": "baseline3"}
    out = [HEADER, "use crate::fixed::Fixed;", "use crate::vec3::{Vec3, runners};",
           "use crate::vec3_variants_gen::{", "    Vec3FixedAlways, Vec3FixedDefault, Vec3FixedNever, Vec3GenAlways, Vec3GenNever,", "};", ""]
    for op, baseline in ops.items():
        group = f"abs_vec3_{op}_fixed"
        out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__baseline() {{", f"    runners::{baseline}::<Fixed>();", "}", ""]
        for vname, vty in variants.items():
            out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__{vname}() {{", f"    runners::{op}::<{vty}, Fixed>();", "}", ""]
    return "\n".join(out)


def static_mats():
    """Mat2F / Mat4F: named fields, fully unrolled product."""
    out = [HEADER]
    for n in (2, 4):
        name = f"Mat{n}F"
        idx = [(i, j) for i in range(1, n + 1) for j in range(1, n + 1)]
        fields = "\n".join(f"    pub m{i}{j}: T," for i, j in idx)
        out += ["#[derive(Copy, Drop)]", f"pub struct {name}<T> {{\n{fields}\n}}", ""]
        out += ["#[generate_trait]",
                f"pub impl {name}Impl<T, +Add<T>, +Mul<T>, +Copy<T>, +Drop<T>> of {name}Trait<T> {{",
                f"    fn from_array(data: [T; {n * n}]) -> {name}<T> {{",
                "        let [" + ", ".join(f"m{i}{j}" for i, j in idx) + "] = data;",
                f"        {name} {{ " + ", ".join(f"m{i}{j}" for i, j in idx) + " }", "    }",
                f"    fn to_array(self: {name}<T>) -> [T; {n * n}] {{",
                "        [" + ", ".join(f"self.m{i}{j}" for i, j in idx) + "]", "    }",
                f"    fn mul_mat(self: {name}<T>, rhs: {name}<T>) -> {name}<T> {{",
                "        let (a, b) = (self, rhs);", f"        {name} {{"]
        for i, j in idx:
            terms = " + ".join(f"a.m{i}{k} * b.m{k}{j}" for k in range(1, n + 1))
            out.append(f"            m{i}{j}: {terms},")
        out += ["        }", "    }", "}", ""]
    return "\n".join(out)


def matn():
    """N x N product: fully unrolled static type vs dynamic Span-based loops, N = 2, 3, 4, 6.

    Every entry of the result is asserted (otherwise unused felt252 entries are dead-code
    eliminated in the static variants). Dynamic results are read back with one
    `multi_pop_front::<N*N>()` so that the read-back cost stays negligible.
    """
    out = [HEADER, "use crate::fixed::{Felt252Div, Fixed, input};",
           "use crate::mat3::{DMatIdx, DMatIdxTrait, DMatSeq, DMatSeqTrait, FieldsMat3, Mat3Ops};",
           "use crate::mat6::{Mat6B, Mat6BTrait};", "use crate::static_mats_gen::{Mat2FTrait, Mat4FTrait};", ""]
    for n in (2, 3, 4, 6):
        a = [[(i * 3 + j * 5) % 7 - 3 for j in range(n)] for i in range(n)]
        b = [[(i * 2 + j * 3) % 5 - 2 for j in range(n)] for i in range(n)]
        p = [[sum(a[i][k] * b[k][j] for k in range(n)) for j in range(n)] for i in range(n)]
        cells = [(i, j) for i in range(n) for j in range(n)]
        flat = lambda m: [m[i][j] for i, j in cells]
        names = lambda prefix: [f"{prefix}{i}{j}" for i, j in cells]
        for sname, sty in SCALARS.items():
            group = f"matmul_n{n}_{sname}"
            inputs = [f"    let {name}: {sty} = input({value});" for name, value in
                      list(zip(names("a"), flat(a))) + list(zip(names("b"), flat(b)))]
            lit = lambda v: f"crate::fixed::Scalar::<{sty}>::from_int({v})"

            def check(prefix, matrix):
                lines = [f"    let mut ok = {prefix}00 == {lit(matrix[0][0])};"]
                lines += [f"    ok = ok && {prefix}{i}{j} == {lit(matrix[i][j])};" for i, j in cells[1:]]
                return lines + ["    assert!(ok);"]

            def test(variant, body):
                return ["#[test]", "#[inline(never)]", f"fn bench_{group}__{variant}() {{"] + inputs + body + ["}", ""]

            out += test("baseline", [f"    let _ = [{', '.join(names('b'))}];"] + check("a", a))

            def static_block(prefix, rows, cols):
                items = ", ".join("(" + ", ".join(f"{prefix}{i}{j}" for j in cols) + ")" for i in rows)
                return f"FieldsMat3::<{sty}>::from_rows({items})"

            def unpack_block(source, rows, cols):
                items = ", ".join("(" + ", ".join(f"p{i}{j}" for j in cols) + ")" for i in rows)
                return f"    let ({items}) = {source}.rows();"

            if n == 3:
                build = [f"    let a = {static_block('a', range(3), range(3))};",
                         f"    let b = {static_block('b', range(3), range(3))};",
                         unpack_block("a.mul_mat(b)", range(3), range(3))]
            elif n == 6:
                lo, hi = range(3), range(3, 6)
                mk = lambda x: (f"Mat6B {{ a: {static_block(x, lo, lo)}, b: {static_block(x, lo, hi)}, "
                                f"c: {static_block(x, hi, lo)}, d: {static_block(x, hi, hi)} }}")
                build = [f"    let a = {mk('a')};", f"    let b = {mk('b')};", "    let p = a.mul_mat(b);",
                         unpack_block("p.a", lo, lo), unpack_block("p.b", lo, hi),
                         unpack_block("p.c", hi, lo), unpack_block("p.d", hi, hi)]
            else:
                build = [f"    let a = Mat{n}FTrait::from_array([{', '.join(names('a'))}]);",
                         f"    let b = Mat{n}FTrait::from_array([{', '.join(names('b'))}]);",
                         f"    let [{', '.join(names('p'))}] = a.mul_mat(b).to_array();"]
            out += test("static", build + check("p", p))

            dynamic = [("dyn_index", "DMatIdx", "a.matmul(b)"), ("dyn_seq", "DMatSeq", "a.matmul(b)")]
            if n == 3:
                dynamic.append(("dyn_static_kernel", "DMatSeq", "crate::mat3::matmul_dispatch(a, b)"))
            for variant, ty, call in dynamic:
                build = [f"    let a = {ty} {{ data: array![{', '.join(names('a'))}].span(), rows: {n}, cols: {n} }};",
                         f"    let b = {ty} {{ data: array![{', '.join(names('b'))}].span(), rows: {n}, cols: {n} }};",
                         f"    let mut data = {call}.data;",
                         f"    let [{', '.join(names('p'))}] = (*data.multi_pop_front::<{n * n}>().unwrap()).unbox();"]
                out += test(variant, build + check("p", p))
        # Full-result correctness check on plain integers (not a benchmark).
        out += ["#[test]", f"fn matmul_n{n}_dynamic_full_result() {{"]
        out += [f"    let a: Array<i64> = array![{', '.join(str(v) for v in flat(a))}];",
                f"    let b: Array<i64> = array![{', '.join(str(v) for v in flat(b))}];",
                f"    let p: Array<i64> = array![{', '.join(str(v) for v in flat(p))}];",
                f"    let idx = DMatIdx {{ data: a.span(), rows: {n}, cols: {n} }}.matmul(DMatIdx {{ data: b.span(), rows: {n}, cols: {n} }});",
                f"    let seq = DMatSeq {{ data: a.span(), rows: {n}, cols: {n} }}.matmul(DMatSeq {{ data: b.span(), rows: {n}, cols: {n} }});",
                "    assert!(idx.data == p.span() && seq.data == p.span());", "}", ""]
    return "\n".join(out)


SCALAR_VARIANT = """
#[derive(Copy, Drop)]
pub struct NAME {
    pub raw: i64,
}

pub impl NAMEAdd of Add<NAME> {
    #[inline(always)]
    fn add(lhs: NAME, rhs: NAME) -> NAME {
        NAME { raw: lhs.raw + rhs.raw }
    }
}

pub impl NAMESub of Sub<NAME> {
    #[inline(always)]
    fn sub(lhs: NAME, rhs: NAME) -> NAME {
        NAME { raw: lhs.raw - rhs.raw }
    }
}

pub impl NAMEMul of Mul<NAME> {
    ATTRIBUTE
    fn mul(lhs: NAME, rhs: NAME) -> NAME {
        let wide: i128 = lhs.raw.into() * rhs.raw.into();
        NAME { raw: (wide / ONE_WIDE).try_into().expect('fixed overflow') }
    }
}

pub impl NAMEDiv of Div<NAME> {
    fn div(lhs: NAME, rhs: NAME) -> NAME {
        let wide: i128 = lhs.raw.into() * ONE_WIDE;
        NAME { raw: (wide / rhs.raw.into()).try_into().expect('fixed overflow') }
    }
}

pub impl NAMENeg of Neg<NAME> {
    #[inline(always)]
    fn neg(a: NAME) -> NAME {
        NAME { raw: -a.raw }
    }
}

pub impl NAMEPartialEq of PartialEq<NAME> {
    #[inline(always)]
    fn eq(lhs: @NAME, rhs: @NAME) -> bool {
        *lhs.raw == *rhs.raw
    }
}

pub impl NAMEScalar of Scalar<NAME> {
    #[inline(always)]
    fn from_int(n: i64) -> NAME {
        NAME { raw: n * ONE }
    }
}
"""


def scalar_variants():
    """`Fixed` clones differing only by the inline policy of `Mul` (`Fixed` itself = default)."""
    out = [HEADER, "use crate::fixed::{ONE, ONE_WIDE, Scalar};"]
    for name, attribute in (("FixedMulAlways", "#[inline(always)]"), ("FixedMulNever", "#[inline(never)]")):
        out.append(SCALAR_VARIANT.replace("NAME", name).replace("ATTRIBUTE", attribute))
    return "\n".join(out)


def inline_matrix():
    """Vector-op inline policy x scalar-mul inline policy."""
    vectors = {"vdefault": "Vec3", "valways": "Vec3GenAlways", "vnever": "Vec3GenNever"}
    scalars = {"mdefault": "Fixed", "malways": "FixedMulAlways", "mnever": "FixedMulNever"}
    out = [HEADER, "use crate::fixed::Fixed;", "use crate::mat3::{Mat3C, Mat3F};",
           "use crate::scalar_variants_gen::{FixedMulAlways, FixedMulNever};",
           "use crate::vec3::Vec3;", "use crate::vec3_variants_gen::{Vec3GenAlways, Vec3GenNever};", ""]
    for op, baseline in (("dot", "baseline1"), ("cross", "baseline3"), ("chain", "baseline3")):
        group = f"inline_vec3_{op}"
        out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__baseline() {{", f"    crate::vec3::runners::{baseline}::<Fixed>();", "}", ""]
        for vname, vty in vectors.items():
            for sname, sty in scalars.items():
                out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__{vname}_{sname}() {{",
                        f"    crate::vec3::runners::{op}::<{vty}<{sty}>, {sty}>();", "}", ""]
    for op, baseline in (("mul_vec", "baseline3"), ("mul_mat", "baseline9"), ("inverse", "baseline9")):
        group = f"inline_mat3_{op}"
        out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__baseline() {{", f"    crate::mat3::runners::{baseline}::<Fixed>();", "}", ""]
        for lname, lty in (("fields", "Mat3F"), ("cols", "Mat3C")):
            for sname, sty in scalars.items():
                out += ["#[test]", "#[inline(never)]", f"fn bench_{group}__{lname}_{sname}() {{",
                        f"    crate::mat3::runners::{op}::<{lty}<{sty}>, Vec3<{sty}>, {sty}>();", "}", ""]
    return "\n".join(out)


def write(name, content):
    with open(os.path.join(HERE, "src", name), "w") as file:
        file.write(content)


if __name__ == "__main__":
    write("vec3_gen.cairo", vec3())
    write("mat3_gen.cairo", mat3())
    write("vec3_variants_gen.cairo", vec3_variants())
    write("abstraction_gen.cairo", abstraction())
    write("static_mats_gen.cairo", static_mats())
    write("scalar_variants_gen.cairo", scalar_variants())
    write("inline_gen.cairo", inline_matrix())
    write("matn_gen.cairo", matn())
