//! Output formats: compact deterministic JSON and Cairo test-data modules.

use crate::model::{Case, OpData, SuiteData};
use std::fmt::Write as _;

fn js<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).expect("serialisable")
}

/// JSON with one case per line: small files, line-oriented diffs, stable key order.
pub fn to_json(data: &SuiteData) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    let _ = writeln!(out, "\"suite\": {},", js(&data.suite));
    let _ = writeln!(out, "\"description\": {},", js(&data.description));
    let _ = writeln!(out, "\"format\": {},", js(&data.format));
    let _ = writeln!(out, "\"generator\": {},", js(&data.generator));
    out.push_str("\"ops\": [\n");
    for (i, op) in data.ops.iter().enumerate() {
        let _ = writeln!(out, "{{\"name\": {},", js(&op.name));
        let _ = writeln!(out, " \"doc\": {},", js(&op.doc));
        let _ = writeln!(out, " \"tolerance\": {},", js(&op.tolerance));
        let _ = writeln!(out, " \"inputs\": {},", js(&op.inputs));
        let _ = writeln!(out, " \"outputs\": {},", js(&op.outputs));
        out.push_str(" \"cases\": [\n");
        for (j, case) in op.cases.iter().enumerate() {
            let comma = if j + 1 < op.cases.len() { "," } else { "" };
            let _ = writeln!(out, "  {}{comma}", js(case));
        }
        let comma = if i + 1 < data.ops.len() { "," } else { "" };
        let _ = writeln!(out, " ]}}{comma}");
    }
    out.push_str("]\n}\n");
    out
}

pub fn from_json(text: &str) -> Result<SuiteData, String> {
    serde_json::from_str(text).map_err(|e| e.to_string())
}

/// Restrictions applied by the Cairo emitter.
#[derive(Default)]
pub struct CairoFilter {
    /// Keep only these distributions (`special` included if listed). `None` keeps everything.
    pub dists: Option<Vec<String>>,
    /// Keep only these ops. `None` keeps everything.
    pub ops: Option<Vec<String>>,
    /// Keep at most this many cases per distribution of each op.
    pub max_per_dist: Option<usize>,
}

impl CairoFilter {
    fn cases<'a>(&self, op: &'a OpData) -> Vec<&'a Case> {
        let mut kept: Vec<&Case> = Vec::new();
        let mut current = "";
        let mut count = 0;
        for case in &op.cases {
            if let Some(dists) = &self.dists {
                if !dists.contains(&case.dist) {
                    continue;
                }
            }
            if case.dist != current {
                current = &case.dist;
                count = 0;
            }
            count += 1;
            if self.max_per_dist.is_some_and(|max| count > max) {
                continue;
            }
            kept.push(case);
        }
        kept
    }
}

/// `[0..8) small, [8..16) unit, ...`
fn ranges(cases: &[&Case]) -> String {
    let mut parts = Vec::new();
    let mut start = 0;
    for i in 1..=cases.len() {
        if i == cases.len() || cases[i].dist != cases[start].dist {
            parts.push(format!("[{start}..{i}) {}", cases[start].dist));
            start = i;
        }
    }
    parts.join(", ")
}

/// Writes `text` as comment lines of at most 100 columns (what `scarb fmt` enforces).
fn comment(out: &mut String, prefix: &str, text: &str) {
    const WIDTH: usize = 100;
    if text.is_empty() {
        let _ = writeln!(out, "{prefix}");
        return;
    }
    let mut line = String::from(prefix);
    for word in text.split_whitespace() {
        if line.len() > prefix.len() && line.len() + 1 + word.len() > WIDTH {
            let _ = writeln!(out, "{line}");
            line = String::from(prefix);
        }
        line.push(' ');
        line.push_str(word);
    }
    let _ = writeln!(out, "{line}");
}

/// Cairo module with one `pub fn <op>_cases() -> Span<(inputs.., outputs.., u64)>` per op.
/// Only raw `i64` / `bool` / `u64` data: no dependency on any nalgebra.cairo type.
pub fn to_cairo(data: &SuiteData, filter: &CairoFilter) -> String {
    let mut out = String::new();
    let g = &data.generator;
    let header = [
        format!(
            "Oracle vectors, suite `{}`: {}.",
            data.suite, data.description
        ),
        String::new(),
        format!(
            "GENERATED by tools/oracle ({} {}, upstream nalgebra {}, seed {}, cases {}). Do not \
             edit. Regenerate from tools/oracle with `cargo run --release -- emit-cairo {} --out \
             <this file>`.",
            g.name, g.version, g.nalgebra, g.seed, g.cases, data.suite
        ),
        String::new(),
        "Every scalar is a raw Q32.32 `i64` (value = raw / 2^32). Inputs are exact; expected \
         outputs are `floor(result * 2^32)` of upstream nalgebra evaluated in f64 (or on exact \
         integers where stated). The last tuple element is the suggested tolerance in raw units \
         (ulp), to apply to every output scalar."
            .to_string(),
        "Vectors / points: tuples `(x, y, ..)`. Quaternions: `(w, i, j, k)`. Unit complex: \
         `(re, im)`. Matrices: ROW-major `[[m11, m12, ..], [m21, m22, ..], ..]`. Angles: radians."
            .to_string(),
    ];
    for paragraph in &header {
        comment(&mut out, "//!", paragraph);
    }

    // One blank line after the header, none between the functions: `scarb fmt` (2.19) rejects a
    // blank line after a `#[cairofmt::skip]` item.
    out.push('\n');
    for op in &data.ops {
        if let Some(ops) = &filter.ops {
            if !ops.contains(&op.name) {
                continue;
            }
        }
        let cases = filter.cases(op);
        if cases.is_empty() {
            continue;
        }
        let mut types = Vec::new();
        let mut layout = Vec::new();
        for field in op.inputs.iter().chain(&op.outputs) {
            types.push(field.kind.cairo_type());
            layout.push(format!("{}: {}", field.name, field.layout));
        }
        types.push("u64".into());
        layout.push("tol: ulp".into());
        let tuple = format!("({})", types.join(", "));

        comment(&mut out, "///", &format!("`{}`: {}", op.name, op.doc));
        comment(&mut out, "///", &format!("Layout: ({})", layout.join(", ")));
        comment(&mut out, "///", &format!("Tolerance: {}.", op.tolerance));
        comment(&mut out, "///", &format!("Cases: {}.", ranges(&cases)));
        out.push_str("#[cairofmt::skip]\n");
        let _ = writeln!(out, "pub fn {}_cases() -> Span<{tuple}> {{", op.name);
        let _ = writeln!(out, "    const CASES: [{tuple}; {}] = [", cases.len());
        for case in &cases {
            let mut parts = Vec::new();
            for (field, value) in op.inputs.iter().zip(&case.inputs) {
                parts.push(field.kind.cairo_literal(value));
            }
            for (field, value) in op.outputs.iter().zip(&case.outputs) {
                parts.push(field.kind.cairo_literal(value));
            }
            parts.push(case.tol.to_string());
            let _ = writeln!(out, "        ({}),", parts.join(", "));
        }
        out.push_str("    ];\n    CASES.span()\n}\n");
    }
    out
}
