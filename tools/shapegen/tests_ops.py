def render_family(name: str, groups: list[tuple[int, int]] | None) -> dict[str, File]:
    if name == "transcendental":
        f = File("transcendental", "Generated tests, `transcendental` family (Tier B sample): "
                                   "`angle`, `lp_norm`, `slerp` against Python floats.")
        for s in TRANSCENDENTAL_SAMPLE:
            transcendental(f, s)
        for s in ALL_SHAPES:
            if s.is_column:
                slerp_case(f, s)
        return {"transcendental": f}
    what, gen = FAMILIES[name]
    out = {}
    for lo, hi in groups:
        key = name if (lo, hi) == (1, 6) else f"{name}_r{lo}_{hi}"
        rows = f" Shapes of {lo} to {hi} rows." if (lo, hi) != (1, 6) else ""
        f = File(key, what + rows)
        for s in ALL_SHAPES:
            if lo <= s.r <= hi:
                gen(f, s)
        out[key] = f
    return out


def render(package: str) -> dict[str, str]:
    """{file name under `src/`: text} of one of the `PACKAGES`."""
    files: dict[str, File] = {}
    for name, groups in PACKAGES[package]:
        files.update(render_family(name, groups))
    out = {f"{name}.cairo": f.render() for name, f in files.items()}
    out["helpers.cairo"] = HEADER + HELPERS + EXTRA_HELPERS
    mods = ["helpers", *files]
    if package == BENCHES_IN:
        out["benches.cairo"] = render_benches()
        mods.append("benches")
    families = ", ".join(f"`{n}`" + (f" (rows {', '.join(f'{lo}-{hi}' for lo, hi in g)})"
                                      if g and g != [(1, 6)] else "")
                         for n, g in PACKAGES[package])
    out["lib.cairo"] = (HEADER + "//! Generated tests of the base completion of the static shapes "
                        "(`tools/shapegen/tests_ops.py`,\n//! WP 8.2a): Tier A of "
                        "`tools/shapegen/DESIGN.md` §3.3, one exact case per (shape, family) on "
                        f"the\n//! 36 shapes; families {families}.\n//! Test-only package, not "
                        "published.\n\n"
                        + "".join(f"#[cfg(test)]\nmod {m};\n" for m in sorted(mods)))
    return out


def outputs(tmp: Path) -> dict[Path, Path]:
    """Writes the packages' sources under `tmp/<package>/src`, formatted, and returns
    {committed: generated}."""
    out = {}
    for package in PACKAGES:
        pkg = tmp / package
        src = pkg / "src"
        src.mkdir(parents=True)
        (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
        for name, text in render(package).items():
            (src / name).write_text(text)
            out[ROOT / "crates" / package / "src" / name] = src / name
        subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    return out
