        lines += [load(u, "hv", {**{x: a[x] for x in F}, u.fields[-1]: 0}),
                  load(u, "hp", {**{x: a[x] for x in F}, u.fields[-1]: ONE}),
                  f"assert_raws({S}Trait::from_homogeneous(hv).unwrap(), {col(s, a)});",
                  f"assert!({S}Trait::from_homogeneous(hp).is_none());"]
