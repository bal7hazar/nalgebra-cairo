def div_round(a: int, b: int) -> int:
    """`fixed`'s division of raws: the exact quotient `a / b` (Q32.32) rounded half to even."""
    return round(Fraction(a * ONE, b))


def mul(a: int, b: int) -> int:
    return floor_scale(a * b)


def to_f(raw: int) -> float:
    return raw / ONE


def nonzero_raw(rng: random.Random, lo: int = 30, hi: int = 34) -> int:
    """A raw whose magnitude is in `[2^lo, 2^hi)`, random sign."""
    v = rng.randrange(1 << lo, 1 << hi)
    return v if rng.random() < 0.5 else -v


class File:
    """A generated test file: its tests, the shapes whose trait it calls, extra `use` lines."""

    def __init__(self, name: str, what: str):
        self.name, self.what = name, what
        self.tests: list[str] = []
        self.traits: set[str] = set()
        self.uses: set[str] = set()

    def add(self, name: str, lines: list[str], traits=(), attr: str = ""):
        self.tests.append(f"{attr}#[test]\nfn {name}() {{\n" + "\n".join(lines) + "\n}")
        self.traits.update(traits)

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        names = set(self.traits)
        for s in ALL_SHAPES:
            for n in (s.name, *s.aliases, s.unit_alias or ""):
                if n and re.search(rf"\b{n}\b", body):
                    names.add(n)
            for suffix in ("Trait", "AngleTrait"):
                if re.search(rf"\b{s.name}{suffix}\b", body):
                    names.add(f"{s.name}{suffix}")
            if s.unit_alias:
                for suffix in ("Trait", "AngleTrait"):
                    if re.search(rf"\b{s.unit_alias}{suffix}\b", body):
                        names.add(f"{s.unit_alias}{suffix}")
        for n in ("MatrixMul", "MatrixTrMul", "MatrixIndex", "Unit", "UnitTrait", "Point2",
                  "Point3"):
            if re.search(rf"\b{n}\b", body):
                names.add(n)
        for method, trait in (("mul_mat", "MatrixMul"), ("ad_mul", "MatrixTrMul"),
                              ("get", "MatrixIndex")):
            if re.search(rf"\.{method}\(", body):
                names.add(trait)
        helpers = [h for h in ("fx", "load", "assert_raws", "assert_near", "assert_raws_near")
                   if re.search(rf"\b{h}\(", body)]
        if "UnitTrait" in names:
            names.discard("UnitTrait")
            self.uses.add("use nalgebra::base::unit::UnitTrait;")
        uses = ["use fixed::Fixed;"] + sorted(self.uses)
        uses += [f"use nalgebra::{{{', '.join(sorted(names))}}};" if len(names) > 1 else
                 f"use nalgebra::{next(iter(names))};"] if names else []
        uses.append(f"use crate::helpers::{{{', '.join(helpers)}}};" if len(helpers) > 1 else
                    f"use crate::helpers::{helpers[0]};")
        return f"{HEADER}//! {self.what}\n\n" + "\n".join(uses) + "\n\n" + body + "\n"


def fxs(values) -> str:
    values = list(values)
    if not values:
        return "ArrayTrait::<Fixed>::new().span()"
    return f"array![{', '.join(f'fx({v})' for v in values)}].span()"


