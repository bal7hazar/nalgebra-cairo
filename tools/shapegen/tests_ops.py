def norms(f: File, s: Shape):
    rng = random.Random(f"tests_ops/norms/{s.name}")
    a, b, k = raws(rng, s), raws(rng, s), nonzero_raw(rng)
    F = s.fields
    sq = sum(a[x] ** 2 for x in F)
    n = math.isqrt(sq)
    lines = [load(s, "a", a), load(s, "b", b),
             f"assert!(a.dot(b) == fx({floor_scale(sum(a[x] * b[x] for x in F))}));",
             f"assert!(a.norm_squared() == fx({floor_scale(sq)}));",
             f"assert!(a.magnitude_squared() == fx({floor_scale(sq)}));",
             f"assert!(a.norm() == fx({n}));", f"assert!(a.magnitude() == fx({n}));",
             f"assert!(a.metric_distance(b) == fx({math.isqrt(sum((a[x] - b[x]) ** 2 for x in F))}));",
             f"assert_raws(a.unscale(fx({k})), {col(s, {x: div_round(a[x], k) for x in F})});",
             f"assert_raws(a.normalize(), {col(s, {x: div_round(a[x], n) for x in F})});",
             f"assert_raws(a.try_normalize(fx({n - 1})).unwrap(), "
             f"{col(s, {x: div_round(a[x], n) for x in F})});",
             f"assert!(a.try_normalize(fx({n})).is_none());"]
    cap = n // 2 + 1
    ratio = div_round(cap, n)
    lines += [f"assert_raws(a.cap_magnitude(fx({cap})), {col(s, {x: mul(a[x], ratio) for x in F})});",
              f"assert_raws(a.cap_magnitude(fx({n})), {col(s, a)});"]
    mag = 3 * ONE + 12345
    ratio = div_round(mag, n)
    lines += ["let mut c = a;", f"c.try_set_magnitude(fx({mag}), fx({n - 1}));",
              f"assert_raws(c, {col(s, {x: mul(a[x], ratio) for x in F})});",
              f"c.try_set_magnitude(fx({mag}), fx({64 * ONE}));",
              f"assert_raws(c, {col(s, {x: mul(a[x], ratio) for x in F})});"]
    one = max(sum(abs(a[s.f(i, j)]) for i in range(s.r)) for j in range(s.c))
    lines.append(f"assert!(a.one_norm() == fx({one}));")
    f.add(f"test_{s.module}_norms", lines, [f"{s.name}Trait"])
    f.add(f"test_{s.module}_normalize_zero_panics",
          [f"let z: {s.name}<Fixed> = {s.name}Trait::zeros();", "let _ = z.normalize();"],
          [f"{s.name}Trait"], attr="#[should_panic(expected: 'Fixed: division by zero')]\n")


def componentwise(f: File, s: Shape):
    rng = random.Random(f"tests_ops/componentwise/{s.name}")
    a = raws(rng, s)
    b = {x: nonzero_raw(rng) for x in s.fields}
    c = raws(rng, s)
    alpha, beta, k = rand_raw(rng, 34), rand_raw(rng, 34), rand_raw(rng)
    F = s.fields
    prod = {x: mul(a[x], b[x]) for x in F}
    quot = {x: div_round(a[x], b[x]) for x in F}
    cm = {x: floor_scale(mul(alpha, a[x]) * b[x] + beta * c[x]) for x in F}
    cd = {x: mul(beta, c[x]) + div_round(mul(alpha, a[x]), b[x]) for x in F}
    lines = [load(s, "a", a), load(s, "b", b), load(s, "c", c),
             f"assert_raws(a.component_mul(b), {col(s, prod)});",
             f"assert_raws(a.component_div(b), {col(s, quot)});",
             "let mut m = a;", "m.component_mul_assign(b);", f"assert_raws(m, {col(s, prod)});",
             "let mut d = a;", "d.component_div_assign(b);", f"assert_raws(d, {col(s, quot)});",
             f"assert_raws(a.inf(c), {col(s, {x: min(a[x], c[x]) for x in F})});",
             f"assert_raws(a.sup(c), {col(s, {x: max(a[x], c[x]) for x in F})});",
             "let (lo, hi) = a.inf_sup(c);",
             f"assert_raws(lo, {col(s, {x: min(a[x], c[x]) for x in F})});",
             f"assert_raws(hi, {col(s, {x: max(a[x], c[x]) for x in F})});",
             f"assert_raws(a.add_scalar(fx({k})), {col(s, {x: a[x] + k for x in F})});",
             "let mut p = c;", f"p.cmpy(fx({alpha}), a, b, fx({beta}));",
             f"assert_raws(p, {col(s, cm)});",
             "let mut q = c;", f"q.cdpy(fx({alpha}), a, b, fx({beta}));",
             f"assert_raws(q, {col(s, cd)});"]
    f.add(f"test_{s.module}_componentwise", lines, [f"{s.name}Trait"])
    zero = dict(b)
    zero[F[-1]] = 0
    f.add(f"test_{s.module}_component_div_by_zero_panics",
          [load(s, "a", a), load(s, "b", zero), "let _ = a.component_div(b);"],
          [f"{s.name}Trait"], attr="#[should_panic(expected: 'Fixed: division by zero')]\n")


def extrema(f: File, s: Shape):
    rng = random.Random(f"tests_ops/extrema/{s.name}")
    a = raws(rng, s)
    F = s.fields
    if s.n >= 3:  # ties: the first one (storage order) wins
        top = max(F, key=lambda x: abs(a[x]))
        later = [x for x in F if F.index(x) > F.index(top)]
        if later:
            a[later[-1]] = -a[top]
        lo = min(F, key=lambda x: a[x])
        later = [x for x in F if F.index(x) > F.index(lo)]
        if later:
            a[later[0]] = a[lo]
    vals = [a[x] for x in F]
    first = lambda pred: next(i for i, v in enumerate(vals) if pred(v))  # noqa: E731
    imin, imax = first(lambda v: v == min(vals)), first(lambda v: v == max(vals))
    iamin = first(lambda v: abs(v) == min(map(abs, vals)))
    iamax = first(lambda v: abs(v) == max(map(abs, vals)))
    lines = [load(s, "a", a),
             f"assert!(a.min() == fx({min(vals)}));", f"assert!(a.max() == fx({max(vals)}));",
             f"assert!(a.amin() == fx({min(map(abs, vals))}));",
             f"assert!(a.amax() == fx({max(map(abs, vals))}));",
             f"assert!(a.camin() == fx({min(map(abs, vals))}));",
             f"assert!(a.camax() == fx({max(map(abs, vals))}));",
             f"assert!(a.iamax_full() == ({iamax % s.r}, {iamax // s.r}));",
             f"assert!(a.icamax_full() == ({iamax % s.r}, {iamax // s.r}));"]
    if s.is_column:
        lines += [f"assert!(a.argmin() == ({imin}, fx({vals[imin]})));",
                  f"assert!(a.argmax() == ({imax}, fx({vals[imax]})));",
                  f"assert!(a.imin() == {imin});", f"assert!(a.imax() == {imax});",
                  f"assert!(a.iamin() == {iamin});", f"assert!(a.iamax() == {iamax});",
                  f"assert!(a.icamax() == {iamax});"]
    f.add(f"test_{s.module}_extrema", lines, [f"{s.name}Trait"])


