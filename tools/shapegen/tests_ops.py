def structure(f: File, s: Shape):
    rng = random.Random(f"tests_ops/structure/{s.name}")
    a = raws(rng, s)
    S, F = s.name, s.fields
    t = s.transposed()
    tv = {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
    lines = [load(s, "a", a), f"assert_raws(a.adjoint(), {col(t, tv)});",
             f"assert_raws(a.conjugate_transpose(), {col(t, tv)});",
             f"assert_raws(a.conjugate(), {col(s, a)});"]
    traits = {f"{S}Trait"}
    if s.is_square:
        sym = {s.f(i, j): (a[s.f(i, j)] if i == j else (a[s.f(i, j)] + a[s.f(j, i)]) >> 1)
               for i in range(s.r) for j in range(s.c)}
        lines += [f"assert_raws(a.symmetric_part(), {col(s, sym)});",
                  f"assert_raws(a.hermitian_part(), {col(s, sym)});"]
        if 2 <= s.r <= 5:
            u = Shape(s.r + 1, s.r + 1)
            h = {u.f(i, j): (a[s.f(i, j)] if i < s.r and j < s.r else ONE if i == j else 0)
                 for i in range(u.r) for j in range(u.c)}
            lines.append(f"assert_raws(a.to_homogeneous(), {col(u, h)});")
        idv = {s.f(i, j): ONE if i == j else 0 for i in range(s.r) for j in range(s.c)}
        lines += [f"let o: {S}<Fixed> = One::one();", f"assert_raws(o, {col(s, idv)});",
                  "assert!(o.is_one());", "assert!(!o.is_non_one());", "assert!(!a.is_one());",
                  "assert!(a.is_non_one());"]
        f.uses.add("use core::num::traits::{Bounded, One};")
