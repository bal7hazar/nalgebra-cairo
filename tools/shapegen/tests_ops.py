"""Generated tests of the base completion (WP 8.2a, `completion.py`): the
four packages `crates/shapes_tests_{norms,componentwise,construction,structure}` (`PACKAGES`).

Tier A of `DESIGN.md` §3.3 on the 36 shapes: one exact case per (shape, family), the expected
values coming from a bit-exact integer model of the kernels, so the tests need no oracle run:

* the floor of the exact sum for every fused sum of products (`dot`, `norm_squared`,
  `component_mul`, `cmpy`, `symmetric_part`...);
* `isqrt` of the exact sum of squares for the norms (`norm`, `metric_distance`, the norm inside
  `normalize` / `cap_magnitude`...): `Real::normK` / `wide_sqrt` floor the square root of the
  UNSCALED exact sum, so the raw result is `isqrt(Σ raw²)`;
* the exact quotient rounded half to even (`Fraction`, Python's `round`) for every division
  (`unscale`, `normalize`, `component_div`, `cdpy`, the ratios of `cap_magnitude`), `fixed`'s
  nearest division.

The operations that need `Transcendental` (`angle`, `lp_norm` for `p >= 3`, `slerp`) have no
integer model: they are compared with Python's float evaluation within a tolerance in raw units
(Tier B), on a sample of shapes that covers every kernel size (`TRANSCENDENTAL_SAMPLE`) and on the
six column vectors for `slerp`.

Families and files (`src/<file>.cairo`): `norms`, `componentwise`, `extrema`, `construction`,
`structure` (comparisons, conversions, indexing, homogeneous forms, `Unit<VectorN>`),
`transcendental`, and `benches` (`gas/nalgebra_shapes_tests_norms`). Same test-file rules as
`tests_core.py`: shape values through `load` / `assert_raws` (one monomorphisation per shape), loops
for per-component checks, at most one `#[should_panic]` test per (shape, family).
"""

