HEADER = "// Generated by tools/shapegen/shapegen.py (tests_stats.py): do not edit by hand.\n"
I64_MAX = (1 << 63) - 1


class P06File(File):
    """`tests_ops.File` importing the P06 traits (per-shape and generic) its tests use."""

    GENERIC = {"gemm": "MatrixGemm", "gemm_tr": "MatrixGemmTr", "gemm_ad": "MatrixGemmTr",
               "gemv": "MatrixGemv", "gemv_tr": "MatrixGemvTr", "gemv_ad": "MatrixGemvTr",
               "quadform": "MatrixQuadform", "quadform_with_workspace": "MatrixQuadform",
               "quadform_tr": "MatrixQuadformTr", "quadform_tr_with_workspace": "MatrixQuadformTr",
               "mul_mat": "MatrixMul", "tr_mul": "MatrixTrMul"}

    def __init__(self, name: str, what: str, header: str):
        super().__init__(name, what)
        self.header = header

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        for s in ALL_SHAPES:
            for suffix in ("StatisticsTrait", "BlasTrait"):
                if re.search(rf"\b{s.name}{suffix}\b", body):
                    self.traits.add(f"{s.name}{suffix}")
        for method, trait in self.GENERIC.items():
            if re.search(rf"\.{method}\(", body):
                self.traits.add(trait)
        text = File.render(self)
        return text.replace("// Generated by tools/shapegen/shapegen.py (tests_ops.py): do not "
                            "edit by hand.\n", self.header)


def div_round(a: int, b: int) -> int:
    """`fixed`'s `a / b` on raws: the exact quotient (Q32.32) rounded half to even."""
    return round(Fraction(a * ONE, b))


def fx_eq(expr: str, raw: int) -> str:
    return f"assert!({expr} == fx({raw}));"


# --------------------------------------------------------------------------------------------
# Integer models
# --------------------------------------------------------------------------------------------


def m_sum(xs: list[int]) -> int:
    return sum(xs)


def m_product(xs: list[int]) -> int:
    acc = xs[0]
    for x in xs[1:]:
        acc = floor_scale(acc * x)
    return acc


def m_mean(xs: list[int]) -> int:
    return div_round(sum(xs), len(xs) * ONE)


def m_variance(xs: list[int]) -> int:
    n = len(xs)
    if n == 1:
        return 0
    m = m_mean(xs)
    return div_round(floor_scale(sum((x - m) * (x - m) for x in xs)), n * ONE)


def columns(s: Shape, a: dict) -> list[list[int]]:
    return [[a[s.f(i, j)] for i in range(s.r)] for j in range(s.c)]


def rows(s: Shape, a: dict) -> list[list[int]]:
    return [[a[s.f(i, j)] for j in range(s.c)] for i in range(s.r)]


def near_one(rng: random.Random) -> int:
    """A raw of magnitude in [0.8, 1.25), random sign: 36 factors stay below 3,000."""
    v = rng.randrange(int(0.8 * ONE), int(1.25 * ONE))
    return v if rng.random() < 0.5 else -v


