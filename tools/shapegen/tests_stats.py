def bench_group(fns: list[str], name: str, pre: list[str], expr: str, ety: str, expected: str,
                variants=()):
    pre = pre + [f"let e: {ety} = black_box({expected});"]
    base = [re.sub(r"let (mut )?(\w+):", r"let _\2:", line) if not line.startswith("let e:")
            else line for line in pre]
    fns.append(bench(name, "baseline", base + ["assert!(e == e);"]))
    fns.append(bench(name, "library", pre + [f"let r: {ety} = {expr};", "assert!(r == e);"]))
    for v, alt in variants:
        fns.append(bench(name, v, pre + [f"let r: {ety} = {alt};", "assert!(r == e);"]))


def bb(s: Shape, var: str, a: dict) -> str:
    return f"let {var}: {s.name}<Fixed> = black_box(load({col(s, a)}));"


ALT_ROW_MEAN = """/// `Matrix3::row_mean` with one `Real::div` per quotient instead of the prepared divisor of
/// `Real::div3` (the same bits).
fn alt_div_each_row_mean_matrix3(m: Matrix3<Fixed>) -> RowVector3<Fixed> {
    let n = Real::<Fixed>::from_int(3);
    RowVector3 {
        x: Real::<Fixed>::div(m.m11 + m.m21 + m.m31, n),
        y: Real::<Fixed>::div(m.m12 + m.m22 + m.m32, n),
        z: Real::<Fixed>::div(m.m13 + m.m23 + m.m33, n),
    }
}"""


def render_benches() -> str:
    fns: list[str] = []
    need: set[str] = set()
    rng = random.Random("tests_stats/benches")
    for s, groups in ((Shape(3, 3), ("sum", "product", "mean", "variance", "row_mean",
                                     "column_variance")),
                      (Shape(6, 1), ("mean", "variance")),
                      (Shape(2, 3), ("row_variance_tr",)),
                      (Shape(6, 6), ("sum", "mean", "variance"))):
        need.update({s.name, *traits_of(s, "sum" in groups)})
        a = raws(rng, s, 36)
        p = {k: near_one(rng) for k in s.fields}
        for g in groups:
            src = p if g == "product" else a
            xs = [src[k] for k in s.fields]
            cs, rs = columns(s, src), rows(s, src)
            variants = []
            if g in ("sum", "product", "mean", "variance"):
                v = {"sum": m_sum, "product": m_product, "mean": m_mean,
                     "variance": m_variance}[g](xs)
                ety, expected = "Fixed", f"fx({v})"
            else:
                kind = g.split("_")[1]
                model = {"mean": m_mean, "variance": m_variance}[kind]
                groups_ = rs if g.startswith("column") else cs
                out = Shape(len(groups_), 1) if (g.startswith("column") or g.endswith("_tr")) \
                    else Shape(1, len(groups_))
                need.add(out.name)
                ety = f"{out.name}<Fixed>"
                expected = f"load({span(model(x) for x in groups_)})"
                if g == "row_mean" and s == Shape(3, 3):
                    variants = [("alt_div_each", "alt_div_each_row_mean_matrix3(a)")]
            bench_group(fns, f"{s.module}_{g}", [bb(s, "a", src)], f"a.{g}()", ety, expected,
                        variants)
    names = sorted(need | {"RowVector3", "Matrix3"})
    uses = ["use fixed::Fixed;", "use simba::scalar::Real;", "use nalgebra_testing::black_box;",
            "use nalgebra::{" + ", ".join(names) + "};", "use crate::helpers::{fx, load};"]
    return (f"{HEADER}//! Gas of the statistics (`bench_<group>__<variant>`, net of the "
            f"`baseline`), and the\n//! measured alternative of the prepared divisor "
            f"(`alt_div_each`: one `Real::div` per quotient).\n\n" + "\n".join(uses) + "\n\n"
            + ALT_ROW_MEAN + "\n\n" + "\n\n".join(fns) + "\n")


