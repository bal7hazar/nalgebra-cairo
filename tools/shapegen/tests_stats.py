def traits_of(s: Shape, sum_: bool = False) -> list[str]:
    """The statistics trait, and `VectorNTrait` when `sum` is called on a vector that has it."""
    return [f"{s.name}StatisticsTrait"] + ([f"{s.name}Trait"] if sum_ and s in stats.HAS_SUM
                                           else [])


def statistics(f: File, s: Shape):
    rng = random.Random(f"tests_stats/statistics/{s.name}")
    a = raws(rng, s, 36)
    xs = [a[k] for k in s.fields]
    cs, rs = columns(s, a), rows(s, a)
    lines = [load(s, "a", a), fx_eq("a.sum()", m_sum(xs)), fx_eq("a.mean()", m_mean(xs)),
             fx_eq("a.variance()", m_variance(xs))]
    for kind, model in (("sum", m_sum), ("mean", m_mean), ("variance", m_variance)):
        per_col = span(model(c) for c in cs)
        lines += [f"assert_raws(a.row_{kind}(), {per_col});",
                  f"assert_raws(a.row_{kind}_tr(), {per_col});",
                  f"assert_raws(a.column_{kind}(), {span(model(r) for r in rs)});"]
    f.add(f"test_{s.module}_statistics", lines, traits_of(s, True))


def products(f: File, s: Shape):
    rng = random.Random(f"tests_stats/products/{s.name}")
    a = {k: near_one(rng) for k in s.fields}
    per_col = span(m_product(c) for c in columns(s, a))
    f.add(f"test_{s.module}_products", [
        load(s, "a", a), fx_eq("a.product()", m_product([a[k] for k in s.fields])),
        f"assert_raws(a.row_product(), {per_col});",
        f"assert_raws(a.row_product_tr(), {per_col});",
        f"assert_raws(a.column_product(), {span(m_product(r) for r in rows(s, a))});"],
        traits_of(s))


def panics(files: dict[str, File]):
    """The overflow panics, once per family (nothing wraps silently)."""
    s = Shape(2, 3)
    big = {k: I64_MAX >> 2 for k in s.fields}
    files["statistics"].add("test_matrix2x3_sum_overflow_panics",
                            [load(s, "a", big), "let _ = a.sum();"], traits_of(s),
                            attr="#[should_panic]\n")
    files["statistics"].add("test_matrix2x3_row_mean_overflow_panics",
                            [load(s, "a", {k: 1 << 62 for k in s.fields}),
                             "let _ = a.row_mean();"], traits_of(s),
                            attr="#[should_panic]\n")
    # Differences of 2^16 (raw 2^48, zero mean) square to 2^32: the sum of squares overflows.
    v = {k: (1 << 48) if i % 2 else -(1 << 48) for i, k in enumerate(s.fields)}
    files["statistics"].add("test_matrix2x3_variance_overflow_panics",
                            [load(s, "a", v), "let _ = a.variance();"], traits_of(s),
                            attr="#[should_panic]\n")
    files["products"].add("test_matrix2x3_product_overflow_panics",
                          [load(s, "a", {k: 1 << 45 for k in s.fields}), "let _ = a.product();"],
                          traits_of(s), attr="#[should_panic]\n")


