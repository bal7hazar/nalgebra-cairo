def unpack(var: str, shape: Shape | None) -> tuple[list[str], list[str]]:
    """Destructures an emitted oracle field (`[[i64; C]; R]` row-major, `(i64, ..)` for a vector,
    `i64` for a scalar): `let` lines and the column-major raw names."""
    if shape is None:
        return [], [var]
    if shape.c == 1 or (shape.r == 1 and shape.c == 1):
        names = [f"{var}_{i}" for i in range(shape.r)]
        return [f"let ({', '.join(names)},) = {var};" if shape.r == 1 else
                f"let ({', '.join(names)}) = {var};"], names
    grid = [[f"{var}_{i}_{j}" for j in range(shape.c)] for i in range(shape.r)]
    pat = "[" + ", ".join("[" + ", ".join(r) + "]" for r in grid) + "]"
    return [f"let {pat} = {var};"], [grid[i][j] for j in range(shape.c) for i in range(shape.r)]


def oracle_test(module: str, op: str, fields: list[tuple[str, Shape | None, bool]],
                call: list[str], out: tuple[Shape | None, bool]) -> str:
    """One oracle test: `fields` = (name, shape or None for a scalar, row vector?) of the case's
    inputs in order; `call` the lines computing `r` from the loaded inputs; `out` the expected
    output's shape (None: scalar) and whether it is emitted as a row-vector tuple."""
    names = [n for n, _, _ in fields]
    lines = [f"let mut cases = {module}::{op}_cases();",
             "while let Some(case) = cases.pop_front() {",
             f"let ({', '.join(names)}, expected, tol) = *case;"]
    for name, shape, is_row in fields:
        if shape is None:
            lines.append(f"let {name} = fx({name});")
            continue
        emitted = Shape(shape.c, 1) if is_row else shape
        un, cm = unpack(name, emitted)
        lines += un + [f"let {name}: {shape.name}<Fixed> = load(array![{', '.join(cm)}].span());"]
    lines += call
    shape, is_row = out
    if shape is None:
        lines.append("assert_near(r, expected, tol.into());")
    else:
        emitted = Shape(shape.c, 1) if is_row else shape
        un, cm = unpack("expected", emitted)
        lines += un + [f"assert_raws_near(r, array![{', '.join(cm)}].span(), tol.into());"]
    lines.append("}")
    return f"#[test]\nfn test_{op}_oracle() {{\n" + "\n".join(lines) + "\n}"


STATS_ORACLE = [
    # (op, input shape, method, output: None scalar / (shape, is_row))
    ("matrix2x3_mean", Shape(2, 3), "mean", None),
    ("matrix2x3_variance", Shape(2, 3), "variance", None),
    ("vector5_variance", Shape(5, 1), "variance", None),
    ("matrix6_mean", Shape(6, 6), "mean", None),
    ("matrix6_variance", Shape(6, 6), "variance", None),
    ("matrix2x3_product", Shape(2, 3), "product", None),
    ("matrix3_row_mean", Shape(3, 3), "row_mean", (Shape(1, 3), True)),
    ("matrix3x2_row_variance", Shape(3, 2), "row_variance", (Shape(1, 2), True)),
    ("matrix2x3_column_mean", Shape(2, 3), "column_mean", (Shape(2, 1), False)),
    ("matrix2x3_column_variance", Shape(2, 3), "column_variance", (Shape(2, 1), False)),
    ("matrix4_column_variance", Shape(4, 4), "column_variance", (Shape(4, 1), False)),
]


def render_oracle(what: str, module: str, tests: list[str], traits: set[str]) -> str:
    f = P06File("oracle", what, HEADER)
    f.tests = tests
    f.traits |= traits
    f.uses.add(f"use crate::{module};")
    return f.render()


def stats_oracle() -> str:
    tests, traits = [], set()
    for op, s, method, out in STATS_ORACLE:
        field = ("m", s, False) if s.c > 1 else ("v", s, False)
        tests.append(oracle_test("oracle_statistics", op, [field],
                                 [f"let r = {field[0]}.{method}();"],
                                 out if out else (None, False)))
        traits.update(traits_of(s))
    return render_oracle("Oracle tests of the statistics against upstream nalgebra (suite "
                         "`statistics` of `tools/oracle`, emitted into `oracle_statistics.cairo`).",
                         "oracle_statistics", tests, traits)


