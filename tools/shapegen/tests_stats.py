"""Generated tests of the statistics (WP 8.3-P06, `stats.py`): the package
`crates/shapes_tests_stats` (`PACKAGE`), and the helpers shared with `tests_blas.py`.

Tier A of `DESIGN.md` §3.3 on the 36 shapes: every operation of `{S}StatisticsTrait` is a
composition of exact sums, floored products and correctly rounded quotients, so its result is
modelled EXACTLY on integer raws here (`floor_scale`, `div_round`): one exact case per (shape,
family), `sum` / `mean` / `variance` / `row_*` / `column_*` on one random matrix, the products on
factors near 1 (so that 36 of them fit), and the overflow panics once per family. Tier B: the
oracle suite `statistics` of `tools/oracle` (`oracle_statistics.cairo`, emitted by the oracle and
committed next to the generated files; `oracle.cairo` runs it).

Files (`src/<file>.cairo`): `statistics`, `products`, `oracle`, `benches`
(`gas/nalgebra_shapes_tests_stats`).
"""

