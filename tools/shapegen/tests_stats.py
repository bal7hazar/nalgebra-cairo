def render() -> dict[str, str]:
    files = {
        "statistics": P06File("statistics", "Generated tests, `statistics` family: `sum`, `mean`, "
                              "`variance` and their `row_*` / `row_*_tr` / `column_*` forms on "
                              "the 36 shapes, modelled exactly on integer raws.", HEADER),
        "products": P06File("products", "Generated tests, `products` family: `product`, "
                            "`row_product`, `row_product_tr`, `column_product` on the 36 shapes "
                            "(factors near 1), modelled exactly on integer raws.", HEADER),
    }
    for s in ALL_SHAPES:
        statistics(files["statistics"], s)
        products(files["products"], s)
    panics(files)
    out = {f"{name}.cairo": f.render() for name, f in files.items()}
    out["oracle.cairo"] = stats_oracle()
    out["helpers.cairo"] = HEADER + HELPERS + EXTRA_HELPERS
    out["benches.cairo"] = render_benches()
    out["lib.cairo"] = lib_root("statistics (`stats.py`)", ["benches", "helpers", "oracle",
                                                             "oracle_statistics", *files])
    return out


def lib_root(what: str, mods: list[str]) -> str:
    return (HEADER + f"//! Generated tests of the {what}, WP 8.3-P06: Tier A of\n//! "
            "`tools/shapegen/DESIGN.md` §3.3 (exact integer models on the 36 shapes) and the "
            "oracle\n//! vectors of `tools/oracle` (`oracle_*.cairo`, emitted by the oracle). "
            "Test-only package, not\n//! published.\n\n"
            + "".join(f"#[cfg(test)]\nmod {m};\n" for m in sorted(mods)))


def write_package(tmp: Path, package: str, files: dict[str, str]) -> dict[Path, Path]:
    """Writes the package's sources under `tmp/<package>/src`, formatted, and returns
    {committed: generated}. The oracle files (`oracle_*.cairo`, emitted by `tools/oracle`) are
    passed through from the committed package."""
    pkg = tmp / package
    src = pkg / "src"
    src.mkdir(parents=True)
    (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
    out = {}
    committed = ROOT / "crates" / package / "src"
    for path in sorted(committed.glob("oracle_*.cairo")):
        files.setdefault(path.name, path.read_text())
    for name, text in files.items():
        (src / name).write_text(text)
        out[committed / name] = src / name
    subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    return out


def outputs(tmp: Path) -> dict[Path, Path]:
    return write_package(tmp, PACKAGE, render())
