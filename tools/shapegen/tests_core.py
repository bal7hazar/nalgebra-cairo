"""Generated tests of the static shapes, core families: `crates/shapes_tests_core` (WP 8.1b-3).

Tier A of `DESIGN.md` §3.3, on the 36 shapes: one exact case per (shape, family), the expected
values coming from a bit-exact integer model of the kernels (the floor of the exact sum for every
fused sum of products, `a + floor((b - a) * t)` for `lerp`), so the tests need no oracle run.
They catch field-mapping mistakes of the templates and Sierra-level failures of every
instantiation (the 216 `mul_mat` and 216 `tr_mul` impls included); the numerics of the kernels
themselves are the hand-written tests and oracle vectors of the former shapes (Tier B).

Compile budget (`DESIGN.md` §3.2): shape values are loaded from and compared with their
column-major raws (the `Serde` image) by two generic helpers (`load`, `assert_raws`, one
monomorphisation per shape) instead of struct literals and derived `==` expanded at every
assertion; one `#[should_panic]` test per (shape, family) checks the panic message.

Families and files (`src/<file>.cairo`, each under ~2,000 lines):

* `construction`: `new` (row-major arguments, column-major `Serde`), `zeros`, the aliases (same
  type), `UnitVectorN`; on squares `identity`, `from_diagonal`, `from_diagonal_element`,
  `diagonal`;
* `arithmetic`: `+ - -x += -=`, `scale`, `abs`, and the overflow of `+` (`#[should_panic]`);
* `structure`: `transpose` (twice), `trace`, `abs_diff_eq`, `is_identity`, `lerp`, the `[T; N]`
  conversions, `Matrix1`'s scalar accessors;
* `mul_mat_r<R>` / `tr_mul_r<R>` (by number of rows of the left operand): every conformable
  pair, `*` and `*=` on squares, and one overflow panic per left operand.
"""

import random
import re
import subprocess
from pathlib import Path

from model import ALL_SHAPES, Shape

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "crates" / "shapes_tests_core"
HEADER = "// Generated by tools/shapegen/shapegen.py (tests_core.py): do not edit by hand.\n"

ONE = 1 << 32
I64_MAX = (1 << 63) - 1

FMT_MANIFEST = """[package]
name = "shapegen_tests"
version = "0.1.0"
edition = "2024_07"

[tool.fmt]
sort-module-level-items = true
max-line-length = 100
"""


def floor_scale(x: int) -> int:
    return x >> 32  # Python's >> floors: the kernels' rounding


def rand_raw(rng: random.Random, bits: int = 36) -> int:
    """A raw Q32.32 value of magnitude < 2^(bits-32), with random fraction bits."""
    return rng.randrange(-(1 << bits), 1 << bits)


def raws(rng: random.Random, s: Shape, bits: int = 36) -> dict[str, int]:
    return {k: rand_raw(rng, bits) for k in s.fields}


def span(values) -> str:
    return f"array![{', '.join(str(v) for v in values)}].span()"


def col(s: Shape, v: dict[str, int]) -> str:
    """The column-major raws of a shape value (its `Serde` image), as a `Span<i64>`."""
    return span(v[f] for f in s.fields)


def load(s: Shape, var: str, v: dict[str, int]) -> str:
    return f"let {var}: {s.name}<Fixed> = load({col(s, v)});"


def new_call(s: Shape, v: dict[str, int]) -> str:
    return f"{s.name}Trait::new({', '.join(f'fx({v[k]})' for k in s.row_major)})"


def model_mul(a: Shape, b: Shape, va, vb) -> dict[str, int]:
    o = Shape(a.r, b.c)
    return {o.f(i, j): floor_scale(sum(va[a.f(i, q)] * vb[b.f(q, j)] for q in range(a.c)))
            for i in range(o.r) for j in range(o.c)}


def model_tr_mul(a: Shape, b: Shape, va, vb) -> dict[str, int]:
    o = Shape(a.c, b.c)
    return {o.f(i, j): floor_scale(sum(va[a.f(q, i)] * vb[b.f(q, j)] for q in range(a.r)))
            for i in range(o.r) for j in range(o.c)}


class File:
    def __init__(self, name: str, what: str):
        self.name, self.what = name, what
        self.tests: list[str] = []
        self.methods_on: set[Shape] = set()
        self.extra: set[str] = set()

    def add(self, name: str, lines: list[str], methods_on=(), attr: str = ""):
        self.tests.append(f"{attr}#[test]\nfn {name}() {{\n" + "\n".join(lines) + "\n}")
        self.methods_on.update(methods_on)

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        names = set()
        for s in ALL_SHAPES:
            for n in (s.name, *s.aliases, s.unit_alias or ""):
                if n and re.search(rf"\b{n}\b", body):
                    names.add(n)
            if s in self.methods_on or re.search(rf"\b{s.name}Trait\b", body):
                names.add(f"{s.name}Trait")
        for n in ("MatrixMul", "MatrixTrMul", "Unit"):
            if n in self.extra:
                names.add(n)
        helpers = [h for h in ("fx", "load", "assert_raws") if re.search(rf"\b{h}\(", body)]
        uses = ["use fixed::Fixed;", f"use nalgebra::{{{', '.join(sorted(names))}}};",
                f"use crate::helpers::{{{', '.join(helpers)}}};"]
        return (f"{HEADER}//! {self.what}\n\n" + "\n".join(uses) + "\n\n" + body + "\n")


def construction(f: File, s: Shape):
    rng = random.Random(f"tests_core/construction/{s.name}")
    a, k = raws(rng, s), rand_raw(rng)
    S = s.name
    lines = [f"assert_raws({new_call(s, a)}, {col(s, a)});",
             f"let z: {S}<Fixed> = {S}Trait::zeros();", f"assert_raws(z, {span([0] * s.n)});"]
    if s.is_square:
        n = s.r
        v = Shape(n, 1)
        d = raws(rng, v)
        diag = lambda g: {s.f(i, j): (g(i) if i == j else 0)  # noqa: E731
                          for i in range(n) for j in range(n)}
        lines += [f"let id: {S}<Fixed> = {S}Trait::identity();",
                  f"assert_raws(id, {col(s, diag(lambda i: ONE))});",
                  load(v, "d", d),
                  f"assert_raws({S}Trait::from_diagonal(d), "
                  f"{col(s, diag(lambda i: d[v.f(i, 0)]))});",
                  f"let e: {S}<Fixed> = {S}Trait::from_diagonal_element(fx({k}));",
                  f"assert_raws(e, {col(s, diag(lambda i: k))});",
                  load(s, "a", a),
                  f"assert_raws(a.diagonal(), {col(v, {v.f(i, 0): a[s.f(i, i)] for i in range(n)})});"]
    for alias in s.aliases:  # the upstream aliases are the same type
        lines += [f"let al: {alias}<Fixed> = {new_call(s, a)};", f"let same: {S}<Fixed> = al;",
                  f"assert_raws(same, {col(s, a)});"]
    if s.unit_alias:
        lines += [f"let u: {s.unit_alias}<Fixed> = Unit {{ value: {new_call(s, a)} }};",
                  f"assert_raws(u.value, {col(s, a)});"]
        f.extra.add("Unit")
    f.add(f"test_{s.module}_construction", lines, [s] if s.is_square else [])


def arithmetic(f: File, s: Shape):
    rng = random.Random(f"tests_core/arithmetic/{s.name}")
    a, b, k = raws(rng, s), raws(rng, s), rand_raw(rng)
    fs = s.fields
    f.add(f"test_{s.module}_arithmetic", [
        load(s, "a", a), load(s, "b", b),
        f"assert_raws(a + b, {col(s, {x: a[x] + b[x] for x in fs})});",
        f"assert_raws(a - b, {col(s, {x: a[x] - b[x] for x in fs})});",
        f"assert_raws(-a, {col(s, {x: -a[x] for x in fs})});",
        f"assert_raws(a.scale(fx({k})), {col(s, {x: floor_scale(a[x] * k) for x in fs})});",
        f"assert_raws(a.abs(), {col(s, {x: abs(a[x]) for x in fs})});",
        "let mut c = a;", "c += b;", f"assert_raws(c, {col(s, {x: a[x] + b[x] for x in fs})});",
        "c -= b;", "c -= b;", f"assert_raws(c, {col(s, {x: a[x] - b[x] for x in fs})});"], [s])
    big = {x: 0 for x in fs}
    big[fs[-1]] = I64_MAX
    f.add(f"test_{s.module}_add_overflow_panics", [load(s, "a", big), "let _ = a + a;"],
          attr="#[should_panic(expected: 'i64_add Overflow')]\n")


def structure(f: File, s: Shape):
    rng = random.Random(f"tests_core/structure/{s.name}")
    a = raws(rng, s)
    t = s.transposed()
    tv = {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
    lines = [load(s, "a", a), f"assert_raws(a.transpose(), {col(t, tv)});",
             f"assert_raws(a.transpose().transpose(), {col(s, a)});"]
    methods = {s, t}
    if s.is_square:
        lines.append(f"assert!(a.trace() == fx({sum(a[s.f(i, i)] for i in range(s.r))}));")
    # abs_diff_eq: every component within 3 ulp, then one component 4 ulp away.
    near = {x: a[x] + rng.choice((-3, -1, 0, 2, 3)) for x in s.fields}
    far = dict(near)
    far[s.fields[-1]] = a[s.fields[-1]] + 4
    lines += [load(s, "near", near), load(s, "far", far), "assert!(a.abs_diff_eq(near, 3));",
              "assert!(!a.abs_diff_eq(far, 3));", "assert!(a.abs_diff_eq(far, 4));"]
    if s.is_square:
        ident = {s.f(i, j): (ONE if i == j else 0) + rng.choice((-2, 0, 1, 2))
                 for i in range(s.r) for j in range(s.c)}
        ident[s.fields[-1]] = ONE - 2  # the largest deviation is 2 ulp
        lines += [load(s, "id", ident), "assert!(id.is_identity(2));",
                  "assert!(!id.is_identity(1));", "assert!(!a.is_identity(2));"]
    if s.is_column:
        b = raws(rng, s)
        tt = rng.randrange(0, ONE)
        lerp = {x: a[x] + floor_scale((b[x] - a[x]) * tt) for x in s.fields}
        lines += [load(s, "b", b), f"assert_raws(a.lerp(b, fx({tt})), {col(s, lerp)});",
                  "assert_raws(a.lerp(b, fx(0)), " + col(s, a) + ");",
                  f"assert_raws(a.lerp(b, fx({ONE})), {col(s, b)});"]
    if s.is_vector:
        arr = ", ".join(f"fx({a[x]})" for x in s.fields)
        lines += [f"let v: {s.name}<Fixed> = [{arr}].into();", f"assert_raws(v, {col(s, a)});",
                  f"let arr: [Fixed; {s.n}] = a.into();", f"let back: {s.name}<Fixed> = arr.into();",
                  f"assert_raws(back, {col(s, a)});"]
    if s.n == 1:
        lines += [f"assert!(a.into_scalar() == fx({a['x']}));",
                  f"assert!(a.to_scalar() == fx({a['x']}));", f"assert!(a.as_scalar() == fx({a['x']}));"]
    f.add(f"test_{s.module}_structure", lines, methods)


def products(files: dict[str, File], s: Shape):
    for op in ("mul_mat", "tr_mul"):
        f = files[f"{op}_r{s.r}"]
        f.extra.add("MatrixMul" if op == "mul_mat" else "MatrixTrMul")
        first = None
        for b in ALL_SHAPES:
            if b.r != (s.c if op == "mul_mat" else s.r):
                continue
            first = first or b
            rng = random.Random(f"tests_core/{op}/{s.name}*{b.name}")
            va, vb = raws(rng, s), raws(rng, b)
            o = Shape(s.r, b.c) if op == "mul_mat" else Shape(s.c, b.c)
            vo = model_mul(s, b, va, vb) if op == "mul_mat" else model_tr_mul(s, b, va, vb)
            lines = [load(s, "a", va), load(b, "b", vb), f"let e = {col(o, vo)};",
                     f"assert_raws(a.{op}(b), e);"]
            if op == "mul_mat" and s == b:
                lines += ["assert_raws(a * b, e);", "let mut c = a;", "c *= b;",
                          "assert_raws(c, e);"]
            f.add(f"test_{s.module}_{op}_{b.module}", lines)
        # One overflow per left operand: component (0, 0) of the product is 2^30 * 2^30.
        big_a = {x: 0 for x in s.fields}
        big_b = {x: 0 for x in first.fields}
        big_a[s.f(0, 0)], big_b[first.f(0, 0)] = 1 << 62, 1 << 62  # 2^30 * 2^30 = 2^60 > 2^31
        f.add(f"test_{s.module}_{op}_overflow_panics",
              [load(s, "a", big_a), load(first, "b", big_b), f"let _ = a.{op}(b);"],
              attr="#[should_panic(expected: 'Fixed: overflow')]\n")


HELPERS = """//! Helpers of the generated tests: shape values from and to their column-major raws.

use fixed::Fixed;

/// A `Fixed` from its raw Q32.32 value.
pub fn fx(raw: i64) -> Fixed {
    Fixed { raw }
}

/// The shape value whose column-major raws (its `Serde` image) are `raws`.
#[inline(never)]
pub fn load<S, +Serde<S>, +Drop<S>>(raws: Span<i64>) -> S {
    let mut felts: Array<felt252> = array![];
    for raw in raws {
        felts.append((*raw).into());
    }
    let mut data = felts.span();
    Serde::deserialize(ref data).unwrap()
}

/// Asserts that the column-major raws of `value` (its `Serde` image) are `expected`.
#[inline(never)]
pub fn assert_raws<S, +Serde<S>, +Drop<S>>(value: S, expected: Span<i64>) {
    let mut out: Array<felt252> = array![];
    value.serialize(ref out);
    assert!(out.len() == expected.len());
    let mut i = 0;
    while i < expected.len() {
        let raw: i64 = *expected[i];
        assert!(*out[i] == raw.into(), "component {} differs", i);
        i += 1;
    }
}

#[test]
fn test_load_assert_raws_round_trip() {
    let v: (Fixed, Fixed) = load(array![-1, 0x100000000].span());
    assert!(v == (fx(-1), fx(0x100000000)));
    assert_raws(v, array![-1, 0x100000000].span());
}

#[test]
#[should_panic(expected: "component 1 differs")]
fn test_assert_raws_detects_a_difference() {
    assert_raws((fx(1), fx(2)), array![1, 3].span());
}
"""


def render() -> dict[str, str]:
    """{file name under `src/`: text}."""
    files = {"construction": File("construction", "Generated tests, `construction` family: "
                                                  "constructors, aliases, diagonals."),
             "arithmetic": File("arithmetic", "Generated tests, `arithmetic` family: `+ - -x += "
                                              "-=`, `scale`, `abs`."),
             "structure": File("structure", "Generated tests, `structure` family: `transpose`, "
                                            "`trace`, comparisons, `lerp`, conversions.")}
    for op, what in (("mul_mat", "`mul_mat` (`self * rhs`), `*`, `*=`"),
                     ("tr_mul", "`tr_mul` (`selfᵀ * rhs`)")):
        for r in range(1, 7):
            files[f"{op}_r{r}"] = File(f"{op}_r{r}", f"Generated tests, products: {what} with a "
                                                     f"left operand of {r} row(s).")
    for s in ALL_SHAPES:
        construction(files["construction"], s)
        arithmetic(files["arithmetic"], s)
        structure(files["structure"], s)
        products(files, s)
    out = {f"{name}.cairo": f.render() for name, f in files.items()}
    out["helpers.cairo"] = HEADER + HELPERS
    mods = "".join(f"#[cfg(test)]\nmod {m};\n" for m in sorted(["helpers", *files]))
    out["lib.cairo"] = (HEADER + "//! Generated tests of the static shapes, core families "
                        "(`tools/shapegen/tests_core.py`, WP 8.1b-3):\n//! Tier A of "
                        "`tools/shapegen/DESIGN.md` §3.3, one exact case per (shape, family) on "
                        "the 36 shapes.\n//! Test-only package, not published.\n\n" + mods)
    return out


def outputs(pkg: Path) -> dict[Path, Path]:
    """Writes the package's sources into `pkg/src`, formatted, and returns {committed: generated}."""
    src = pkg / "src"
    src.mkdir(parents=True)
    (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
    out = {}
    for name, text in render().items():
        (src / name).write_text(text)
        out[PACKAGE / "src" / name] = src / name
    subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    return out
