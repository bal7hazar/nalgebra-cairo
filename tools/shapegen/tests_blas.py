def alt_kernel(name: str, S: Shape, A: Shape, B: Shape, tr: bool) -> str:
    """`gemm` / `gemm_tr` of `S` with the other `alpha * sum + beta * c` kernel (`alt_upstream`)
    or written directly on the transposed fields (`alt_direct`), as a free function."""
    other = "upstream" if blas.SCALED_DOT == "wide" else "wide"
    k = A.r if tr else A.c
    fields = []
    for j in range(S.c):
        for i in range(S.r):
            pairs = [((f"a.{A.f(q, i)}" if tr else f"a.{A.f(i, q)}"), f"b.{B.f(q, j)}")
                     for q in range(k)]
            if name.startswith("alt_upstream"):
                acc = "Real::<Fixed>::wide_zero()"
                for x, y in pairs:
                    acc = f"Real::<Fixed>::wide_add_prod({acc}, {x}, {y})"
                val = (f"Real::<Fixed>::sum_prod2(alpha, Real::<Fixed>::wide_rescale({acc}), beta, "
                       f"c.{S.f(i, j)})")
            else:
                flat = ", ".join(f"{x}, {y}" for x, y in pairs)
                val = f"alt_scaled_dot{k}(alpha, {flat}, beta, c.{S.f(i, j)})"
            fields.append(f"{S.f(i, j)}: {val}")
    what = (f"the `{other}` kernel of `alpha * sum + beta * c` (`blas.py` `SCALED_DOT`)"
            if name.startswith("alt_upstream") else "the transposed fields read directly (no "
            "`BlasTranspose`)")
    return (f"/// `{S.name}::{'gemm_tr' if tr else 'gemm'}` with {what}.\n"
            f"fn {name}(alpha: Fixed, a: {A.name}<Fixed>, b: {B.name}<Fixed>, beta: Fixed, "
            f"c: {S.name}<Fixed>) -> {S.name}<Fixed> {{\n{S.name} {{ {', '.join(fields)} }}\n}}")


def alt_scaled_dot(k: int) -> str:
    args = ", ".join(f"a{i}: Fixed, b{i}: Fixed" for i in range(k))
    body = blas.kernel_body(k).replace("R::", "Real::<Fixed>::")
    return (f"#[inline(always)]\nfn alt_scaled_dot{k}(alpha: Fixed, {args}, beta: Fixed, c: Fixed) "
            f"-> Fixed {{\n{body}\n}}")


def render_benches() -> str:
    fns, helpers, need = [], [], set()
    rng = random.Random("tests_blas/benches")
    helpers += [alt_scaled_dot(3), alt_scaled_dot(4)]

    def pre_of(items) -> list[str]:
        return [bb(sh, n, v) if sh else f"let {n}: Fixed = black_box({fx(v)});"
                for n, sh, v in items]

    # gemm / gemm_tr / gemv on a sample; the loser kernels as free functions.
    for S, k in ((Shape(3, 3), 3), (Shape(4, 4), 4), (Shape(6, 6), 6), (Shape(2, 3), 4)):
        A, B, T = Shape(S.r, k), Shape(k, S.c), Shape(k, S.r)
        a, b, t, c = raws(rng, A, BITS), raws(rng, B, BITS), raws(rng, T, BITS), raws(rng, S, BITS)
        alpha, beta = scalars(rng)
        need.update({S.name, A.name, B.name, T.name})
        base = [("alpha", None, alpha), ("a", A, a), ("b", B, b), ("beta", None, beta),
                ("c", S, c)]
        e = m_gemm(S, alpha, a, A, b, B, beta, c)
        variants = []
        if S == Shape(3, 3):
            helpers.append(alt_kernel("alt_upstream_gemm_matrix3", S, A, B, False))
            variants = [("alt_upstream", "alt_upstream_gemm_matrix3(alpha, a, b, beta, c)")]
        bench_group(fns, f"{S.module}_gemm", pre_of(base),
                    "{\nlet mut m = c;\nm.gemm(alpha, a, b, beta);\nm\n}", f"{S.name}<Fixed>",
                    f"load({col(S, e)})", variants)
        if S in (Shape(3, 3), Shape(2, 3)):
            e = m_gemm(S, alpha, t, T, b, B, beta, c, tr=True)
            helpers.append(alt_kernel(f"alt_direct_gemm_tr_{S.module}", S, T, B, True))
            base[1] = ("a", T, t)
            bench_group(fns, f"{S.module}_gemm_tr", pre_of(base),
                        "{\nlet mut m = c;\nm.gemm_tr(alpha, a, b, beta);\nm\n}", f"{S.name}<Fixed>",
                        f"load({col(S, e)})",
                        [("alt_direct", f"alt_direct_gemm_tr_{S.module}(alpha, a, b, beta, c)")])
    for n in (3, 6):
        Y, A = vec(n), Shape(n, n)
        a, x, y = raws(rng, A, BITS), raws(rng, Y, BITS), raws(rng, Y, BITS)
        alpha, beta = scalars(rng)
        need.update({Y.name, A.name, f"{Y.name}BlasTrait", f"{A.name}BlasTrait"})
        base = [("alpha", None, alpha), ("a", A, a), ("x", Y, x), ("beta", None, beta),
                ("y", Y, y)]
        for name, tr in (("gemv", False), ("gemv_tr", True)):
            e = m_gemm(Y, alpha, a, A, x, Y, beta, y, tr=tr)
            bench_group(fns, f"{Y.module}_{name}", pre_of(base),
                        f"{{\nlet mut v = y;\nv.{name}(alpha, a, x, beta);\nv\n}}", f"{Y.name}<Fixed>",
                        f"load({col(Y, e)})")
        e = grid(Y, lambda i, j: scaled(alpha, [(at(A, a, max(i, q), min(i, q)), at(Y, x, q, 0))
                                                for q in range(n)], beta, at(Y, y, i, 0)))
        bench_group(fns, f"{Y.module}_sygemv", pre_of(base),
                    "{\nlet mut v = y;\nv.sygemv(alpha, a, x, beta);\nv\n}", f"{Y.name}<Fixed>",
                    f"load({col(Y, e)})")
        e = grid(A, lambda i, j: scaled(alpha, [(at(Y, x, i, 0), at(Y, y, j, 0))], beta,
                                        at(A, a, i, j)))
        bench_group(fns, f"{A.module}_ger", pre_of(base),
                    "{\nlet mut m = a;\nm.ger(alpha, x, y, beta);\nm\n}", f"{A.name}<Fixed>",
                    f"load({col(A, e)})")
        e = grid(Y, lambda i, j: floor_scale(alpha * at(Y, x, i, 0) + beta * at(Y, y, i, 0)))
        bench_group(fns, f"{Y.module}_axpy", pre_of(base),
                    "{\nlet mut v = y;\nv.axpy(alpha, x, beta);\nv\n}", f"{Y.name}<Fixed>",
                    f"load({col(Y, e)})")
        e = floor_scale(sum(at(A, a, i, j) * at(A, a, j, i) for i in range(n) for j in range(n)))
        bench_group(fns, f"{A.module}_tr_dot", pre_of(base[1:2]), "a.tr_dot(a)", "Fixed", fx(e))
    for d1, d3 in ((3, 3), (2, 3)):
        S, Mm, Rh, Lh = Shape(d1, d1), Shape(d3, d3), Shape(d3, d1), Shape(d1, d3)
        mid, rhs, lhs, c = raws(rng, Mm, 34), raws(rng, Rh, 34), raws(rng, Lh, 34), raws(rng, S, BITS)
        alpha, beta = scalars(rng)
        need.update({S.name, Mm.name, Rh.name, Lh.name})
        w = m_mul(Mm, mid, Rh, rhs)
        e = m_gemm(S, alpha, rhs, Rh, w, Rh, beta, c, tr=True)
        bench_group(fns, f"{S.module}_quadform_{Mm.module}", pre_of(
            [("alpha", None, alpha), ("mid", Mm, mid), ("rhs", Rh, rhs), ("beta", None, beta),
             ("c", S, c)]), "{\nlet mut m = c;\nm.quadform(alpha, mid, rhs, beta);\nm\n}",
            f"{S.name}<Fixed>", f"load({col(S, e)})")
        w = m_mul(Lh, lhs, Mm, mid)
        lt = {Rh.f(j, i): lhs[Lh.f(i, j)] for i in range(d1) for j in range(d3)}
        e = m_gemm(S, alpha, w, Lh, lt, Rh, beta, c)
        bench_group(fns, f"{S.module}_quadform_tr_{Mm.module}", pre_of(
            [("alpha", None, alpha), ("lhs", Lh, lhs), ("mid", Mm, mid), ("beta", None, beta),
             ("c", S, c)]), "{\nlet mut m = c;\nm.quadform_tr(alpha, lhs, mid, beta);\nm\n}",
            f"{S.name}<Fixed>", f"load({col(S, e)})")
    body = "\n\n".join(fns)
    traits = sorted({"Vector3BlasTrait", "Vector6BlasTrait", "Matrix3BlasTrait", "Matrix6BlasTrait"}
                    | {t for t, m in (("MatrixGemm", "gemm"), ("MatrixGemmTr", "gemm_tr"),
                                      ("MatrixGemv", "gemv"), ("MatrixGemvTr", "gemv_tr"),
                                      ("MatrixQuadform", "quadform"),
                                      ("MatrixQuadformTr", "quadform_tr"))
                       if re.search(rf"\.{m}\(", body)})
    names = sorted({n for n in need if not n.endswith("Trait")} | set(traits))
    uses = ["use fixed::Fixed;", "use simba::scalar::Real;", "use nalgebra_testing::black_box;",
            "use nalgebra::{" + ", ".join(names) + "};", "use crate::helpers::{fx, load};"]
    return (f"{HEADER}//! Gas of the BLAS-like kernels (`bench_<group>__<variant>`, net of the "
            f"`baseline`), and the\n//! measured alternatives: `alt_upstream` (the sum floored "
            f"before the product by `alpha`, `blas.py`\n//! `SCALED_DOT`), `alt_direct` (`gemm_tr` "
            f"on the transposed fields, without the free `BlasTranspose`).\n\n"
            + "\n".join(uses) + "\n\n" + "\n\n".join(helpers) + "\n\n" + body + "\n")


