"""Generated tests of the BLAS-like kernels (WP 8.3-P06, `blas.py`): the package
`crates/shapes_tests_blas` (`PACKAGE`).

Tier A of `DESIGN.md` §3.3: every operation is modelled EXACTLY on integer raws
(`scaled_dot`: the exact sum times `alpha` floored once plus `beta * c` floored once; `axpy`: one
floored sum of two products): `dotc` / `tr_dot` / `ger` / `gerc` on the 36 shapes, the symmetric
updates on the squares, `axpy` / `axcpy` / `sygemv` / `hegemv` on the column vectors, `gemv` /
`gemv_tr` / `gemv_ad` on every (vector, matrix) pair, `gemm` / `gemm_tr` on the 216 triples
(`gemm_ad` once per shape), `quadform*` on the 72 pairs, with the workspace they leave; the
identities `gemm(1, a, b, 0) == a.mul_mat(b)` / `gemm_tr(1, a, b, 0) == a.tr_mul(b)` and
`beta == 0` ignoring the previous content; the overflow panic once. Tier B: the oracle suite
`blas` of `tools/oracle` (`oracle_blas.cairo`).

Files (`src/<file>.cairo`): `blas`, `gemv`, `gemm_r1_3` / `gemm_r4_6` (by rows of `self`),
`quadform`, `oracle`, `benches` (`gas/nalgebra_shapes_tests_blas`).
"""

