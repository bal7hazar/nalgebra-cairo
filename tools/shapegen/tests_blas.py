DIMS = range(1, 7)
BITS = 35  # operands below 8 in magnitude: 6 products times alpha stay far below 2^31


def vec(n: int) -> Shape:
    return Shape(n, 1)


def scaled(alpha: int, pairs, beta: int, c: int) -> int:
    """`BlasKernels::scaled_dotK` on raws."""
    return ((sum(a * b for a, b in pairs) * alpha) >> 64) + floor_scale(beta * c)


def at(s: Shape, a: dict, i: int, j: int) -> int:
    return a[s.f(i, j)]


def grid(s: Shape, g) -> dict:
    return {s.f(i, j): g(i, j) for j in range(s.c) for i in range(s.r)}


def scalars(rng: random.Random) -> tuple[int, int]:
    return rand_raw(rng, 34), rand_raw(rng, 34)


def fx(v: int) -> str:
    return f"fx({v})"


