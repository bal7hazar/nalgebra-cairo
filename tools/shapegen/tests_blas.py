def blas_oracle() -> str:
    V, s = vec, None
    specs = [
        ("matrix2x3_tr_dot", [("a", M(2, 3), False), ("b", M(3, 2), False)],
         ["let r = a.tr_dot(b);"], (None, False)),
        ("vector3_axpy", [("a", s, 0), ("x", V(3), 0), ("b", s, 0), ("y", V(3), 0)],
         ["let mut r = y;", "r.axpy(a, x, b);"], (V(3), False)),
        ("vector4_axcpy", [("a", s, 0), ("x", V(4), 0), ("c", s, 0), ("b", s, 0), ("y", V(4), 0)],
         ["let mut r = y;", "r.axcpy(a, x, c, b);"], (V(4), False)),
        ("vector2_gemv", [("alpha", s, 0), ("a", M(2, 4), 0), ("x", V(4), 0), ("beta", s, 0),
                          ("y", V(2), 0)],
         ["let mut r = y;", "r.gemv(alpha, a, x, beta);"], (V(2), False)),
        ("vector2_gemv_tr", [("alpha", s, 0), ("a", M(3, 2), 0), ("x", V(3), 0), ("beta", s, 0),
                             ("y", V(2), 0)],
         ["let mut r = y;", "r.gemv_tr(alpha, a, x, beta);"], (V(2), False)),
        ("vector3_sygemv", [("alpha", s, 0), ("a", M(3, 3), 0), ("x", V(3), 0), ("beta", s, 0),
                            ("y", V(3), 0)],
         ["let mut r = y;", "r.sygemv(alpha, a, x, beta);"], (V(3), False)),
        ("matrix2x3_ger", [("alpha", s, 0), ("x", V(2), 0), ("y", V(3), 0), ("beta", s, 0),
                           ("m", M(2, 3), 0)],
         ["let mut r = m;", "r.ger(alpha, x, y, beta);"], (M(2, 3), False)),
        ("matrix3_syger", [("alpha", s, 0), ("x", V(3), 0), ("y", V(3), 0), ("beta", s, 0),
                           ("m", M(3, 3), 0)],
         ["let mut r = m;", "r.syger(alpha, x, y, beta);"], (M(3, 3), False)),
        ("matrix2x3_gemm", [("alpha", s, 0), ("a", M(2, 4), 0), ("b", M(4, 3), 0),
                            ("beta", s, 0), ("c", M(2, 3), 0)],
         ["let mut r = c;", "r.gemm(alpha, a, b, beta);"], (M(2, 3), False)),
        ("matrix3_gemm_tr", [("alpha", s, 0), ("a", M(2, 3), 0), ("b", M(2, 3), 0),
                             ("beta", s, 0), ("c", M(3, 3), 0)],
         ["let mut r = c;", "r.gemm_tr(alpha, a, b, beta);"], (M(3, 3), False)),
        ("matrix4_gemm", [("alpha", s, 0), ("a", M(4, 4), 0), ("b", M(4, 4), 0), ("beta", s, 0),
                          ("c", M(4, 4), 0)],
         ["let mut r = c;", "r.gemm(alpha, a, b, beta);"], (M(4, 4), False)),
        ("matrix2_quadform", [("alpha", s, 0), ("mid", M(3, 3), 0), ("rhs", M(3, 2), 0),
                              ("beta", s, 0), ("m", M(2, 2), 0)],
         ["let mut r = m;", "r.quadform(alpha, mid, rhs, beta);"], (M(2, 2), False)),
        ("matrix3_quadform_tr", [("alpha", s, 0), ("lhs", M(3, 2), 0), ("mid", M(2, 2), 0),
                                 ("beta", s, 0), ("m", M(3, 3), 0)],
         ["let mut r = m;", "r.quadform_tr(alpha, lhs, mid, beta);"], (M(3, 3), False)),
    ]
    tests, traits = [], set()
    per_shape_methods = ("tr_dot", "axpy", "axcpy", "sygemv", "ger", "syger")
    for op, fields, call, out in specs:
        tests.append(oracle_test("oracle_blas", op, [(n, sh, False) for n, sh, _ in fields],
                                 call, out))
        method = re.search(r"\.(\w+)\(", call[-1]).group(1)
        if method in per_shape_methods:
            receiver = fields[0][1] if method == "tr_dot" else fields[-1][1]
            traits.add(f"{receiver.name}BlasTrait")
    f = P06File("oracle", "Oracle tests of the BLAS-like kernels against upstream nalgebra (suite "
                "`blas` of `tools/oracle`, emitted into `oracle_blas.cairo`).", HEADER)
    f.tests = tests
    f.traits |= traits
    f.uses.add("use crate::oracle_blas;")
    return f.render()


