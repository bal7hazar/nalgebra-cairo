def m_gemm(S: Shape, alpha, a, A: Shape, b, B: Shape, beta, c, tr: bool = False) -> dict:
    k = A.r if tr else A.c
    return grid(S, lambda i, j: scaled(
        alpha, [((at(A, a, q, i) if tr else at(A, a, i, q)), at(B, b, q, j)) for q in range(k)],
        beta, at(S, c, i, j)))


def m_mul(A: Shape, a, B: Shape, b) -> dict:
    o = Shape(A.r, B.c)
    return grid(o, lambda i, j: floor_scale(sum(at(A, a, i, q) * at(B, b, q, j)
                                                for q in range(A.c))))


