def per_shape(f: P06File, s: Shape):
    rng = random.Random(f"tests_blas/per_shape/{s.name}")
    S, Tr, X, Y = s.name, s.transposed(), vec(s.r), vec(s.c)
    a, b = raws(rng, s, BITS), raws(rng, s, BITS)
    t = raws(rng, Tr, BITS)
    x, y = raws(rng, X, BITS), raws(rng, Y, BITS)
    alpha, beta = scalars(rng)
    fs = s.fields
    lines = [load(s, "a", a), load(s, "b", b), load(Tr, "t", t), load(X, "x", x), load(Y, "y", y),
             f"let alpha = {fx(alpha)};", f"let beta = {fx(beta)};",
             f"assert!(a.dotc(b) == {fx(floor_scale(sum(a[k] * b[k] for k in fs)))});",
             f"assert!(a.dotc(b) == a.dot(b));",
             f"assert!(a.tr_dot(t) == "
             f"{fx(floor_scale(sum(at(s, a, i, j) * at(Tr, t, j, i) for i in range(s.r) for j in range(s.c))))});"]
    ger = grid(s, lambda i, j: scaled(alpha, [(at(X, x, i, 0), at(Y, y, j, 0))], beta, at(s, a, i, j)))
    for name in ("ger", "gerc"):
        lines += ["let mut m = a;", f"m.{name}(alpha, x, y, beta);", f"assert_raws(m, {col(s, ger)});"]
    traits = [f"{S}BlasTrait", f"{S}Trait"]
    if s.is_square:
        syger = grid(s, lambda i, j: scaled(alpha, [(at(X, x, i, 0), at(X, x, j, 0))], beta,
                                            at(s, a, i, j)) if i >= j else at(s, a, i, j))
        for name in ("syger", "hegerc", "ger_symm"):
            lines += ["let mut m = a;", f"m.{name}(alpha, x, x, beta);",
                      f"assert_raws(m, {col(s, syger)});"]
    if s.is_column:
        n = s.r
        k1, k2, k3 = rand_raw(rng, 34), rand_raw(rng, 34), rand_raw(rng, 34)
        axpy = grid(s, lambda i, j: floor_scale(k1 * at(s, b, i, 0) + k2 * at(s, a, i, 0)))
        axcpy = grid(s, lambda i, j: scaled(k3, [(k1, at(s, b, i, 0))], k2, at(s, a, i, 0)))
        M = Shape(n, n)
        mm = raws(rng, M, BITS)
        sy = grid(s, lambda i, j: scaled(alpha, [(at(M, mm, max(i, q), min(i, q)), at(s, b, q, 0))
                                                 for q in range(n)], beta, at(s, a, i, 0)))
        lines += [f"let (k1, k2, k3) = ({fx(k1)}, {fx(k2)}, {fx(k3)});",
                  "let mut v = a;", "v.axpy(k1, b, k2);", f"assert_raws(v, {col(s, axpy)});",
                  "let mut v = a;", "v.axcpy(k1, b, k3, k2);", f"assert_raws(v, {col(s, axcpy)});",
                  load(M, "mm", mm)]
        for name in ("sygemv", "hegemv"):
            lines += ["let mut v = a;", f"v.{name}(alpha, mm, b, beta);",
                      f"assert_raws(v, {col(s, sy)});"]
    f.add(f"test_{s.module}_blas", lines, traits)


def gemv(f: P06File, y_dim: int):
    """`gemv` / `gemv_tr` / `gemv_ad` of `Vector{y_dim}` with every matrix shape that fits."""
    Y = vec(y_dim)
    rng = random.Random(f"tests_blas/gemv/{Y.name}")
    y = raws(rng, Y, BITS)
    alpha, beta = scalars(rng)
    lines = [load(Y, "y", y), f"let alpha = {fx(alpha)};", f"let beta = {fx(beta)};"]
    for c in DIMS:
        A, X = Shape(y_dim, c), vec(c)
        a, x = raws(rng, A, BITS), raws(rng, X, BITS)
        e = m_gemm(Y, alpha, a, A, x, X, beta, y)
        lines += [load(A, f"a{c}", a), load(X, f"x{c}", x), "let mut v = y;",
                  f"v.gemv(alpha, a{c}, x{c}, beta);", f"assert_raws(v, {col(Y, e)});"]
        A, X = Shape(c, y_dim), vec(c)
        a, x = raws(rng, A, BITS), raws(rng, X, BITS)
        e = m_gemm(Y, alpha, a, A, x, X, beta, y, tr=True)
        for name in ("gemv_tr", "gemv_ad"):
            lines += [load(A, f"t{c}", a), load(X, f"u{c}", x), "let mut v = y;",
                      f"v.{name}(alpha, t{c}, u{c}, beta);", f"assert_raws(v, {col(Y, e)});"]
    f.add(f"test_{Y.module}_gemv", lines)


def gemm(f: P06File, s: Shape):
    rng = random.Random(f"tests_blas/gemm/{s.name}")
    c = raws(rng, s, BITS)
    alpha, beta = scalars(rng)
    lines = [load(s, "c", c), f"let alpha = {fx(alpha)};", f"let beta = {fx(beta)};"]
    for k in DIMS:
        A, B = Shape(s.r, k), Shape(k, s.c)
        a, b = raws(rng, A, BITS), raws(rng, B, BITS)
        lines += [load(A, f"a{k}", a), load(B, f"b{k}", b), "let mut m = c;",
                  f"m.gemm(alpha, a{k}, b{k}, beta);",
                  f"assert_raws(m, {col(s, m_gemm(s, alpha, a, A, b, B, beta, c))});"]
        A = Shape(k, s.r)
        a = raws(rng, A, BITS)
        names = ("gemm_tr", "gemm_ad") if k == s.c else ("gemm_tr",)
        for name in names:
            lines += [load(A, f"t{k}", a), "let mut m = c;", f"m.{name}(alpha, t{k}, b{k}, beta);",
                      f"assert_raws(m, {col(s, m_gemm(s, alpha, a, A, b, B, beta, c, tr=True))});"]
    f.add(f"test_{s.module}_gemm", lines)


def identities(f: P06File):
    """`gemm(1, a, b, 0)` is `mul_mat`, `gemm_tr(1, a, b, 0)` is `tr_mul`; `beta == 0` ignores the
    previous content; `gemv` is `gemm` on a column."""
    rng = random.Random("tests_blas/identities")
    for s, k in ((Shape(2, 3), 4), (Shape(6, 6), 6), (Shape(3, 1), 5)):
        A, B, T = Shape(s.r, k), Shape(k, s.c), Shape(k, s.r)
        a, b, t, c = raws(rng, A, BITS), raws(rng, B, BITS), raws(rng, T, BITS), raws(rng, s, BITS)
        f.add(f"test_{s.module}_gemm_identities", [
            load(A, "a", a), load(B, "b", b), load(T, "t", t), load(s, "c", c),
            f"let one = {fx(ONE)};", "let zero = fx(0);",
            "let mut m = c;", "m.gemm(one, a, b, zero);", "assert!(m == a.mul_mat(b));",
            "let mut m = c;", "m.gemm_tr(one, t, b, zero);", "assert!(m == t.tr_mul(b));",
            # beta == 0: the previous content is ignored (a zero `self` gives the same result).
            f"let alpha = {fx(rand_raw(rng, 34))};",
            f"let mut m = c;", "m.gemm(alpha, a, b, zero);",
            f"let mut z: {s.name}<Fixed> = load({col(s, {x: 0 for x in s.fields})});",
            "z.gemm(alpha, a, b, zero);", "assert!(m == z);"])
    s = Shape(2, 3)
    big = {x: 1 << 50 for x in s.fields}
    f.add("test_matrix2x3_gemm_overflow_panics", [
        load(s, "c", big), load(Shape(2, 2), "a", {x: 1 << 50 for x in Shape(2, 2).fields}),
        "let mut m = c;", f"m.gemm({fx(ONE)}, a, c, {fx(ONE)});"], attr="#[should_panic]\n")


def quadform(f: P06File, d1: int):
    S = Shape(d1, d1)
    rng = random.Random(f"tests_blas/quadform/{S.name}")
    c = raws(rng, S, BITS)
    alpha, beta = scalars(rng)
    lines = [load(S, "c", c), f"let alpha = {fx(alpha)};", f"let beta = {fx(beta)};"]
    for d3 in DIMS:
        M, Rh = Shape(d3, d3), Shape(d3, d1)
        mid, rhs = raws(rng, M, 34), raws(rng, Rh, 34)
        w = m_mul(M, mid, Rh, rhs)
        e = m_gemm(S, alpha, rhs, Rh, w, Rh, beta, c, tr=True)
        W = vec(d3)
        lines += [load(M, f"mid{d3}", mid), load(Rh, f"rhs{d3}", rhs), "let mut m = c;",
                  f"m.quadform(alpha, mid{d3}, rhs{d3}, beta);", f"assert_raws(m, {col(S, e)});",
                  "let mut m = c;",
                  f"let mut work: {W.name}<Fixed> = load({col(W, {x: 7 for x in W.fields})});",
                  f"m.quadform_with_workspace(ref work, alpha, mid{d3}, rhs{d3}, beta);",
                  f"assert_raws(m, {col(S, e)});",
                  f"assert_raws(work, {span(w[Rh.f(k, d1 - 1)] for k in range(d3))});"]
        Lh = Shape(d1, d3)
        lhs = raws(rng, Lh, 34)
        w = m_mul(Lh, lhs, M, mid)
        lt = {Rh.f(j, i): lhs[Lh.f(i, j)] for i in range(d1) for j in range(d3)}
        e = m_gemm(S, alpha, w, Lh, lt, Rh, beta, c)
        V = vec(d1)
        lines += [load(Lh, f"lhs{d3}", lhs), "let mut m = c;",
                  f"m.quadform_tr(alpha, lhs{d3}, mid{d3}, beta);", f"assert_raws(m, {col(S, e)});",
                  "let mut m = c;",
                  f"let mut work: {V.name}<Fixed> = load({col(V, {x: 7 for x in V.fields})});",
                  f"m.quadform_tr_with_workspace(ref work, alpha, lhs{d3}, mid{d3}, beta);",
                  f"assert_raws(m, {col(S, e)});",
                  f"assert_raws(work, {span(w[Lh.f(i, d3 - 1)] for i in range(d1))});"]
    f.add(f"test_{S.module}_quadform", lines)


