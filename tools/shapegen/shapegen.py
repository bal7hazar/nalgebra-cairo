def render_compare(shapes: list[Shape]) -> str:
    """Bit-identity tests and gas benchmarks, generated shape vs hand-written shape."""
    shapeset = set(shapes)
    uses = {"fixed::Fixed", "nalgebra_testing::black_box", "crate::MatrixMul"}
    fns: list[str] = []
    for s, hname in HANDWRITTEN.items():
        if s not in shapeset:
            continue
        uses.add(f"crate::{s.module}::{{{s.name}, {s.name}Trait}}")
        uses.add(f"nalgebra::base::{hname.lower()}::{{{hname} as H{hname}, "
                 f"{hname}Trait as H{hname}Trait}}")
        fns.append(f"fn to_h_{s.module}(g: {s.name}<Fixed>) -> H{hname}<Fixed> {{\n"
                   f"{hw_literal(s, {f: f'g.{f}' for f in s.fields})}\n}}")
        vec = Shape(s.r, 1) if s.is_square and s.r > 1 else None
        rng = random.Random(f"compare/{s.name}")
        cases = [Case(raws(rng, s), raws(rng, s), rand_raw(rng), raws(rng, vec) if vec else None)
                 for _ in range(3)]
        for op, only in COMPARE_OPS.items():
            if only is not None and s not in only:
                continue
            checks = []
            for c in cases:
                g, h = call(op, s, "g", c, vec, literal=True), call(op, s, "h", c, vec, True)
                out, _ = model(op, s, c, vec)
                checks.append(f"assert!({g if out is None else f'to_h_{out.module}({g})'} == {h});")
            fns.append(test_fn(f"test_{s.module}_{op}_bit_identical", "\n".join(checks)))
            fns.extend(bench_trio(op, s, cases[0], vec))
    fns.extend(render_index_alternatives(shapes, uses))
    fns.extend(render_mul_mat_benches(shapes, uses))
    body = "\n\n".join(fns)
    imports = use_lines(body, shapes, {s for s in HANDWRITTEN if s in shapeset},
                        {"fixed::Fixed", "nalgebra_testing::black_box"})
    return (f"{HEADER}//! Proof of the migration: the generated shapes against the hand-written "
            f"`Vector2/3/6`, `Matrix2/3` of `crates/nalgebra`, on the overlapping surface.\n//!\n"
            f"//! - `test_<shape>_<op>_bit_identical`: equal outputs on three random inputs;\n"
            f"//! - `bench_<shape>_<op>__generated` / `__handwritten`: the gas of each side (same "
            f"inputs, same assertion, one baseline).\n\n{imports}\n\n"
            f"fn fx(raw: i64) -> Fixed {{\n    Fixed {{ raw }}\n}}\n\n" + "\n\n".join(fns) + "\n")


@dataclass
class Case:
    a: dict
    b: dict
    k: int
    v: dict | None


def hw_literal(s: Shape, values: dict[str, str]) -> str:
    """A literal of the crate's shape (flat for every shape since WP 8.1b-2; the block `Vector6`
    the prototype was measured against is gone, `proto/GAS.md` keeps those figures)."""
    H = f"H{HANDWRITTEN[s]}"
    return f"{H} {{ {', '.join(f'{f}: {values[f]}' for f in s.fields)} }}"


def side_new(s: Shape, side: str, v: dict) -> str:
    trait = f"{s.name}Trait" if side == "g" else f"H{HANDWRITTEN[s]}Trait"
    return f"{trait}::new({', '.join(f'fx({v[k]})' for k in s.row_major)})"


def side_lit(s: Shape, side: str, v) -> str:
    if s is None:
        return f"fx({v})"
    vals = {f: f"fx({v[f]})" for f in s.fields}
    return s.lit(vals) if side == "g" else hw_literal(s, vals)


def model(op: str, s: Shape, c: Case, vec):
    """(output shape or None for a scalar, raw value(s)): the integer model of the kernels."""
    a, b, k = c.a, c.b, c.k
    dp = lambda p, q, r, t: floor_scale(p * q - r * t)  # noqa: E731 (diff_prod)
    if op == "new":
        return s, a
    if op == "zeros":
        return s, {f: 0 for f in s.fields}
    if op == "identity":
        return s, {s.f(i, j): ONE if i == j else 0 for i in range(s.r) for j in range(s.c)}
    if op == "add":
        return s, {f: a[f] + b[f] for f in s.fields}
    if op == "sub":
        return s, {f: a[f] - b[f] for f in s.fields}
    if op == "neg":
        return s, {f: -a[f] for f in s.fields}
    if op == "scale":
        return s, {f: floor_scale(a[f] * k) for f in s.fields}
    if op == "transpose":
        t = s.transposed()
        return t, {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
    if op == "mul":
        return s, model_product(s, s, a, b)
    if op == "mul_vec":
        return vec, model_product(s, vec, a, c.v)
    if op == "dot":
        return None, floor_scale(sum(a[f] * b[f] for f in s.fields))
    if op == "norm_squared":
        return None, floor_scale(sum(a[f] * a[f] for f in s.fields))
    if op == "cross":
        return s, {"x": dp(a["y"], b["z"], a["z"], b["y"]), "y": dp(a["z"], b["x"], a["x"], b["z"]),
                   "z": dp(a["x"], b["y"], a["y"], b["x"])}
    if op == "determinant" and s.r == 2:
        return None, dp(a["m11"], a["m22"], a["m12"], a["m21"])
    if op == "determinant" and s.r == 3:
        return None, floor_scale(a["m11"] * dp(a["m22"], a["m33"], a["m23"], a["m32"])
                                 + a["m12"] * dp(a["m23"], a["m31"], a["m21"], a["m33"])
                                 + a["m13"] * dp(a["m21"], a["m32"], a["m22"], a["m31"]))
    raise ValueError(op)


def call(op: str, s: Shape, side: str, c: Case, vec, literal: bool) -> str:
    """The expression of `op` on one side, on literal inputs or on the bench's `a, b, k, v`."""
    trait = f"{s.name}Trait" if side == "g" else f"H{HANDWRITTEN[s]}Trait"
    a = side_new(s, side, c.a) if literal else "a"
    b = side_new(s, side, c.b) if literal else "b"
    k = f"fx({c.k})" if literal else "k"
    v = (side_new(vec, side, c.v) if literal else "v") if vec else None
    if op == "new":
        return a if literal else f"{trait}::new({', '.join(f'r{i}' for i in range(s.n))})"
    return {"zeros": f"{trait}::zeros()", "identity": f"{trait}::identity()",
            "add": f"({a} + {b})", "sub": f"({a} - {b})", "neg": f"(-{a})",
            "scale": f"{a}.scale({k})", "transpose": f"{a}.transpose()", "mul": f"({a} * {b})",
            "mul_vec": f"{a}.mul_vec({v})", "dot": f"{a}.dot({b})", "cross": f"{a}.cross({b})",
            "norm_squared": f"{a}.norm_squared()",
            "determinant": f"{a}.determinant()"}[op]


def unused(lines: list[str]) -> list[str]:
    return [re.sub(r"^let (\w+)", r"let _\1", line) for line in lines]


def bench_trio(op: str, s: Shape, c: Case, vec) -> list[str]:
    """baseline / generated / handwritten on the same black-boxed inputs and expectation."""
    group = f"{s.module}_{op}"
    out_shape, value = model(op, s, c, vec)

    def inputs(side: str) -> list[str]:
        if op == "new":
            return [f"let r{i} = black_box(fx({c.a[f]}));" for i, f in enumerate(s.row_major)]
        if op in ("zeros", "identity"):
            return []
        lines = [f"let a = black_box({side_new(s, side, c.a)});"]
        if op in ("add", "sub", "mul", "dot", "cross"):
            lines.append(f"let b = black_box({side_new(s, side, c.b)});")
        if op == "scale":
            lines.append(f"let k = black_box(fx({c.k}));")
        if op == "mul_vec":
            lines.append(f"let v = black_box({side_new(vec, side, c.v)});")
        return lines

    def expected(side: str) -> str:
        return f"let e = black_box({side_lit(out_shape, side, value)});"

    fns = [f"#[test]\n#[inline(never)]\nfn bench_{group}__baseline() {{\n"
           + "\n".join(unused(inputs("g")) + [expected("g"), "assert!(e == e);"]) + "\n}"]
    for side, variant in (("g", "generated"), ("h", "handwritten")):
        lines = inputs(side) + [expected(side),
                                f"assert!({call(op, s, side, c, vec, False)} == e);"]
        fns.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__{variant}() {{\n"
                   + "\n".join(lines) + "\n}")
    return fns


def render_index_alternatives(shapes: list[Shape], uses: set[str]) -> list[str]:
    """The linear 2-D index (`i + j * R`, row check, one `match`): the loser, kept as evidence."""
    out = []
    for s in (Shape(3, 3), Shape(2, 3)):
        if s not in shapes:
            continue
        uses.add(f"crate::{s.module}::{{{s.name}, {s.name}Trait}}")
        uses.add("crate::errors")
        m = s.module
        out.append(
            f"/// Loser of the 2-D index: linear offset then one `match` (row checked first).\n"
            f"#[inline(always)]\nfn alt_index_linear_{m}(self: @{s.name}<Fixed>, index: "
            f"(usize, usize)) -> Fixed {{\nlet (i, j) = index;\nif i >= {s.r} {{\n"
            f"core::panic_with_felt252(errors::INDEX_OUT_OF_BOUNDS)\n}}\n"
            f"let index = i + j * {s.r};\n{index_linear_body(s)}\n}}")
        rng = random.Random(f"index/{s.name}")
        a = raws(rng, s)
        i, j = s.r - 1, s.c - 1
        lit = cairo_lit(s, a)
        ex = f"fx({a[s.f(i, j)]})"
        out.append(test_fn(f"test_{m}_index2_alt_linear_matches",
                           "\n".join(f"assert!(alt_index_linear_{m}(@{lit}, ({ii}, {jj})) == "
                                     f"{lit}[({ii}, {jj})]);"
                                     for ii in range(s.r) for jj in range(s.c))))
        pre = [f"let a = black_box({lit});", f"let i = black_box({i});",
               f"let j = black_box({j});", f"let e = black_box({ex});"]
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__baseline() {{\n"
                   + "\n".join(pre).replace("let a", "let _a").replace("let i ", "let _i ")
                   .replace("let j ", "let _j ") + "\nassert!(e == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__nested() {{\n"
                   + "\n".join(pre) + "\nassert!(a[(i, j)] == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__alt_linear() {{\n"
                   + "\n".join(pre) + "\nassert!(alt_index_linear_" + m + "(@a, (i, j)) == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index1__baseline() {{\n"
                   + f"let _a = black_box({lit});\nlet _i = black_box({s.n - 1});\n"
                   f"let e = black_box({ex});\nassert!(e == e);\n}}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index1__match() {{\n"
                   + f"let a = black_box({lit});\nlet i = black_box({s.n - 1});\n"
                   f"let e = black_box({ex});\nassert!(a[i] == e);\n}}")
    return out


def render_mul_mat_benches(shapes: list[Shape], uses: set[str]) -> list[str]:
    """`mul_mat` against `*` (square) and a rectangular product, for the gas table; the 6-term
    product through `Fused::sum_prod6` against the same chain written in place (`alt_nested`)."""
    out = []
    a_s, b_s = Shape(1, 6), Shape(6, 1)
    if a_s in shapes and b_s in shapes and Shape(1, 1) in shapes:
        kernel = product_kernel(a_s, b_s, "a", "b", helpers=False).replace("R::", "Real::<Fixed>::")
        out.append(f"/// `RowVector6 * Vector6` with the `Real::Wide` chain written in place (the "
                   f"form of the\n/// hand-written `Matrix6`), against `Fused::sum_prod6`.\n"
                   f"fn alt_nested_row_vector6_mul_vector6(a: RowVector6<Fixed>, b: Vector6<Fixed>)"
                   f" -> Matrix1<Fixed> {{\n{kernel}\n}}")
        rng = random.Random("nested/RowVector6*Vector6")
        va, vb = raws(rng, a_s), raws(rng, b_s)
        vo = model_product(a_s, b_s, va, vb)
        pre = [f"let a = black_box({cairo_lit(a_s, va)});",
               f"let b = black_box({cairo_lit(b_s, vb)});",
               f"let e = black_box({cairo_lit(Shape(1, 1), vo)});"]
        out.append(test_fn("test_row_vector6_mul_vector6_alt_nested_matches",
                           "\n".join(pre) + "\nassert!(alt_nested_row_vector6_mul_vector6(a, b) == "
                           "a.mul_mat(b));\nassert!(a.mul_mat(b) == e);"))
        group = "row_vector6_mul_vector6"
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__baseline() {{\n"
                   + "\n".join(unused(pre[:-1]) + pre[-1:]) + "\nassert!(e == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__fused_helper() {{\n"
                   + "\n".join(pre) + "\nassert!(a.mul_mat(b) == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__alt_nested() {{\n"
                   + "\n".join(pre) + "\nassert!(alt_nested_row_vector6_mul_vector6(a, b) == e);\n}")
    pairs = [(Shape(3, 3), Shape(3, 3)), (Shape(2, 3), Shape(3, 2)), (Shape(3, 2), Shape(2, 3)),
             (Shape(1, 3), Shape(3, 1)), (Shape(3, 1), Shape(1, 3)), (Shape(2, 3), Shape(3, 1))]
    for a_s, b_s in pairs:
        o = Shape(a_s.r, b_s.c)
        if a_s not in shapes or b_s not in shapes or o not in shapes:
            continue
        for x in (a_s, b_s, o):
            uses.add(f"crate::{x.module}::{{{x.name}, {x.name}Trait}}")
        rng = random.Random(f"mulmat/{a_s.name}*{b_s.name}")
        va, vb = raws(rng, a_s), raws(rng, b_s)
        vo = model_product(a_s, b_s, va, vb)
        group = f"{a_s.module}_mul_{b_s.module}"
        pre = [f"let a = black_box({cairo_lit(a_s, va)});",
               f"let b = black_box({cairo_lit(b_s, vb)});",
               f"let e = black_box({cairo_lit(o, vo)});"]
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__baseline() {{\n"
                   + "\n".join(pre).replace("let a", "let _a").replace("let b", "let _b")
                   + "\nassert!(e == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__mul_mat() {{\n"
                   + "\n".join(pre) + "\nassert!(a.mul_mat(b) == e);\n}")
        if a_s == b_s:
            out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__operator() {{\n"
                       + "\n".join(pre) + "\nassert!(a * b == e);\n}")
    return out


