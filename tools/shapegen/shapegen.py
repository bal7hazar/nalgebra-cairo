# --------------------------------------------------------------------------------------------
# Shape model
# --------------------------------------------------------------------------------------------


@dataclass(frozen=True, order=True)
class Shape:
    r: int
    c: int

    @property
    def n(self) -> int:
        return self.r * self.c

    @property
    def is_vector(self) -> bool:
        """One column or one row: components named `x, y, z, w, a, b` like upstream's Deref."""
        return self.r == 1 or self.c == 1

    @property
    def is_square(self) -> bool:
        return self.r == self.c

    @property
    def name(self) -> str:
        """The canonical struct: upstream's aliases of one shape are ONE Cairo type."""
        if self.r == 1 and self.c == 1:
            return "Matrix1"
        if self.c == 1:
            return f"Vector{self.r}"
        if self.r == 1:
            return f"RowVector{self.c}"
        if self.is_square:
            return f"Matrix{self.r}"
        return f"Matrix{self.r}x{self.c}"

    @property
    def aliases(self) -> list[str]:
        """The other upstream names of the shape, as Cairo type aliases."""
        if self.r == 1 and self.c == 1:
            return ["Vector1", "RowVector1"]
        if self.c == 1:
            return [f"Matrix{self.r}x1"]
        if self.r == 1:
            return [f"Matrix1x{self.c}"]
        return []

    @property
    def module(self) -> str:
        return re.sub(r"(?<!^)(?=[A-Z])", "_", self.name).lower()

    @property
    def kind(self) -> str:
        if self.r == 1 and self.c == 1:
            return "1x1 matrix"
        if self.c == 1:
            return f"{self.r}-dimensional column vector"
        if self.r == 1:
            return f"{self.c}-dimensional row vector"
        return f"{self.r}x{self.c} matrix"

    def f(self, i: int, j: int) -> str:
        """Field of the component at row `i`, column `j` (0-based)."""
        if self.c == 1:
            return COORDS[i]
        if self.r == 1:
            return COORDS[j]
        return f"m{i + 1}{j + 1}"

    @property
    def fields(self) -> list[str]:
        """Column-major: the declaration order, hence upstream's `Serde` order."""
        return [self.f(i, j) for j in range(self.c) for i in range(self.r)]

    @property
    def row_major(self) -> list[str]:
        return [self.f(i, j) for i in range(self.r) for j in range(self.c)]

    def transposed(self) -> "Shape":
        return Shape(self.c, self.r)

    def lit(self, values: dict[str, str]) -> str:
        """Struct literal in declaration order."""
        body = ", ".join(f"{k}: {values[k]}" for k in self.fields)
        return f"{self.name} {{ {body} }}"


def shapes_from(spec: str) -> list[Shape]:
    if spec == "all":
        return [Shape(r, c) for r in range(1, 7) for c in range(1, 7)]
    if spec == "proto":
        return PROTO_SHAPES
    out = []
    for token in spec.split(","):
        r, c = token.split("x")
        out.append(Shape(int(r), int(c)))
    return out


# The prototype's shapes: every kind of shape (1x1, square, rectangular, column and row vectors,
# a 6-dimensional vector), closed enough under products that each product family has members,
# and overlapping the hand-written `Vector2/3/6`, `Matrix2/3` for the bit-identity proofs.
PROTO_SHAPES = [
    Shape(1, 1),
    Shape(2, 2),
    Shape(3, 3),
    Shape(2, 3),
    Shape(3, 2),
    Shape(2, 1),
    Shape(3, 1),
    Shape(6, 1),
    Shape(1, 2),
    Shape(1, 3),
]


# --------------------------------------------------------------------------------------------
# Kernels (AGENTS.md rule 4: every sum of products through ONE fused kernel)
# --------------------------------------------------------------------------------------------


def fused_expr(pairs: list[tuple[str, str]]) -> str:
    """`sum a_k * b_k` floored ONCE, as one expression.

    1 term: the scalar product; 2-4 terms: `Real::sum_prodN`; 5+ terms: the `Real::Wide`
    accumulator, nested (the form of the hand-written `Matrix6`).
    """
    n = len(pairs)
    if n == 1:
        a, b = pairs[0]
        return f"{a} * {b}"
    if n <= 4:
        args = ", ".join(f"{a}, {b}" for a, b in pairs)
        return f"R::sum_prod{n}({args})"
    expr = "R::wide_zero()"
    for a, b in pairs:
        expr = f"R::wide_add_prod({expr}, {a}, {b})"
    return f"R::wide_rescale({expr})"


def fused_body(pairs: list[tuple[str, str]], final: str = "wide_rescale") -> str:
    """A single-output fused sum as a function body: 5+ terms as a `let` chain (the form of the
    hand-written `Vector6` / `Matrix3` / `Matrix4` reductions)."""
    n = len(pairs)
    if n <= 4 and final == "wide_rescale":
        return fused_expr(pairs)
    lines = []
    (a0, b0), rest = pairs[0], pairs[1:]
    lines.append(f"let w = R::wide_add_prod(R::wide_zero(), {a0}, {b0});")
    for a, b in rest[:-1]:
        lines.append(f"let w = R::wide_add_prod(w, {a}, {b});")
    a, b = rest[-1]
    lines.append(f"R::{final}(R::wide_add_prod(w, {a}, {b}))")
    return "\n".join(lines)


def squares_body(xs: list[str]) -> str:
    n = len(xs)
    if n == 1:
        return f"{xs[0]} * {xs[0]}"
    if n <= 4:
        return f"R::norm_squared{n}({', '.join(xs)})"
    return fused_body([(x, x) for x in xs])


def product_inline(out: Shape) -> bool:
    """Inlining rule of the hand-written products, reproduced so that gas is unchanged:
    `#[inline(always)]` for vector outputs of at most 4 components (`Matrix2/3/4::mul_vec`),
    default inlining for matrix outputs (`Matrix2/3/4/6 * Matrix`) and `Matrix6::mul_vec`."""
    return out.is_vector and out.n <= 4


# --------------------------------------------------------------------------------------------
# Code model: a shape file is a struct, one `#[generate_trait]` impl, and top-level items
# --------------------------------------------------------------------------------------------


@dataclass
class Method:
    name: str
    code: str  # doc comment + attributes + fn, un-indented


@dataclass
class ShapeFile:
    shape: Shape
    methods: list[Method]
    items: list[str]
    uses: set[str]


def doc(text: str) -> str:
    return "\n".join(f"/// {line}" if line else "///" for line in text.strip().split("\n"))


def method(name: str, docs: str, sig: str, body: str, inline: bool = True) -> Method:
    attr = "#[inline(always)]\n" if inline else ""
    return Method(name, f"{doc(docs)}\n{attr}fn {sig} {{\n{body}\n}}")


def upstream(shape: Shape) -> str:
    return shape.aliases[0] if shape.r == 1 and shape.c == 1 else shape.name


# --- families --------------------------------------------------------------------------------


def family_construction(s: Shape, shapes: set[Shape], out: ShapeFile):
    S = s.name
    args = ", ".join(f"{p}: T" for p in s.row_major)
    order = "the given components" if s.is_vector else "the given components, in ROW-major order"
    out.methods.append(method(
        "new",
        f"The {s.kind} with {order}. Upstream: `{upstream(s)}::new`.",
        f"new({args}) -> {S}<T>",
        f"{S} {{ {', '.join(s.fields)} }}",
    ))
    out.methods.append(method(
        "zeros", f"The zero {s.kind}. Upstream: `zeros`.",
        f"zeros() -> {S}<T>", s.lit({k: "R::ZERO" for k in s.fields})))
    for name, note in (("from_element", "Upstream: `from_element`."),
                       ("repeat", "Alias of `from_element`. Upstream: `repeat`.")):
        out.methods.append(method(
            name, f"The {s.kind} whose components all equal `elem`. {note}",
            f"{name}(elem: T) -> {S}<T>", s.lit({k: "elem" for k in s.fields})))
    if s.is_square:
        ident = {s.f(i, j): ("R::ONE" if i == j else "R::ZERO")
                 for i in range(s.r) for j in range(s.c)}
        out.methods.append(method(
            "identity", f"The identity matrix. Upstream: `{upstream(s)}::identity`.",
            f"identity() -> {S}<T>", s.lit(ident)))


def family_arithmetic(s: Shape, shapes: set[Shape], out: ShapeFile):
    S = s.name
    out.uses.add("core::ops::{AddAssign, SubAssign}")
    for trait, op, verb in (("Add", "+", "add"), ("Sub", "-", "sub")):
        out.items.append(
            f"/// `lhs {op} rhs`, component-wise. Exact; panics on overflow. Upstream: `{trait}`.\n"
            f"pub impl {S}{trait}<T, +{trait}<T>, +Copy<T>, +Drop<T>> of {trait}<{S}<T>> {{\n"
            f"#[inline(always)]\nfn {verb}(lhs: {S}<T>, rhs: {S}<T>) -> {S}<T> {{\n"
            f"{s.lit({k: f'lhs.{k} {op} rhs.{k}' for k in s.fields})}\n}}\n}}")
        out.items.append(
            f"/// `self {op}= rhs`. Exact; panics on overflow. Upstream: `{trait}Assign`.\n"
            f"pub impl {S}{trait}Assign<T, +{trait}<T>, +Copy<T>, +Drop<T>> of "
            f"{trait}Assign<{S}<T>, {S}<T>> {{\n"
            f"#[inline(always)]\nfn {verb}_assign(ref self: {S}<T>, rhs: {S}<T>) {{\n"
            f"self = self {op} rhs;\n}}\n}}")
    out.items.append(
        f"/// `-a`, component-wise. Exact; panics on overflow (`-MIN`). Upstream: `Neg`.\n"
        f"pub impl {S}Neg<T, +Neg<T>, +Copy<T>, +Drop<T>> of Neg<{S}<T>> {{\n"
        f"#[inline(always)]\nfn neg(a: {S}<T>) -> {S}<T> {{\n"
        f"{s.lit({k: f'-a.{k}' for k in s.fields})}\n}}\n}}")
    out.methods.append(method(
        "scale",
        "`self * k`, each component floored once. Panics on overflow. Upstream: `scale` "
        "(`self * k`).",
        f"scale(self: {S}<T>, k: T) -> {S}<T>", s.lit({k: f"self.{k} * k" for k in s.fields})))


def family_transpose(s: Shape, shapes: set[Shape], out: ShapeFile):
    t = s.transposed()
    if t not in shapes:
        return
    if t != s:
        out.uses.add(f"super::{t.module}::{t.name}")
    values = {t.f(j, i): f"self.{s.f(i, j)}" for i in range(s.r) for j in range(s.c)}
    out.methods.append(method(
        "transpose", f"The transpose, a `{t.name}`. Exact. Upstream: `transpose`.",
        f"transpose(self: {s.name}<T>) -> {t.name}<T>", t.lit(values)))


def product_kernel(a: Shape, b: Shape, lhs: str, rhs: str) -> str:
    o = Shape(a.r, b.c)
    values = {}
    for i in range(o.r):
        for j in range(o.c):
            pairs = [(f"{lhs}.{a.f(i, k)}", f"{rhs}.{b.f(k, j)}") for k in range(a.c)]
            values[o.f(i, j)] = fused_expr(pairs)
    return o.lit(values)


def kernel_note(k: int) -> str:
    if k == 1:
        return "one floored product per component"
    if k <= 4:
        return f"one `sum_prod{k}` per component (one rounding each)"
    return f"the {k} products of each component accumulated in `Real::Wide`, rescaled once"


def family_products(s: Shape, shapes: set[Shape], out: ShapeFile):
    A = s.name
    for b in sorted(shapes):
        o = Shape(s.r, b.c)
        if b.r != s.c or o not in shapes:
            continue
        B, O = b.name, o.name
        for t in (b, o):
            if t != s:
                out.uses.add(f"super::{t.module}::{t.name}")
        out.uses.add("super::matrix_mul::MatrixMul")
        inline = "#[inline(always)]\n" if product_inline(o) else ""
        bounds = "T, impl R: Real<T>, +Mul<T>, +Copy<T>, +Drop<T>, +Drop<R::Wide>"
        if s == b == o:
            out.uses.add("core::ops::MulAssign")
            out.items.append(
                f"/// `a * b` (matrix product): {kernel_note(s.c)}. Panics on overflow. "
                f"Upstream: `Mul`.\n"
                f"pub impl {A}Mul<{bounds}> of Mul<{A}<T>> {{\n{inline}"
                f"fn mul(lhs: {A}<T>, rhs: {A}<T>) -> {A}<T> {{\n"
                f"{product_kernel(s, s, 'lhs', 'rhs')}\n}}\n}}")
            out.items.append(
                f"/// `a *= b` (matrix product, `a = a * b`). Upstream: `MulAssign`.\n"
                f"pub impl {A}MulAssign<{bounds}> of MulAssign<{A}<T>, {A}<T>> {{\n"
                f"#[inline(always)]\nfn mul_assign(ref self: {A}<T>, rhs: {A}<T>) {{\n"
                f"self = self * rhs;\n}}\n}}")
            out.items.append(
                f"/// `self * rhs` through `MatrixMul`: the `*` operator, for code generic over "
                f"the shapes.\npub impl {A}Mul{B}<{bounds}> of MatrixMul<{A}<T>, {B}<T>> {{\n"
                f"type Output = {O}<T>;\n#[inline(always)]\n"
                f"fn mul_mat(self: {A}<T>, rhs: {B}<T>) -> {O}<T> {{\nself * rhs\n}}\n}}")
            continue
        out.items.append(
            f"/// `self * rhs`, a `{O}`: {kernel_note(s.c)}. Panics on overflow. Upstream: "
            f"`Mul<{upstream(b)}> for {upstream(s)}`.\n"
            f"pub impl {A}Mul{B}<{bounds}> of MatrixMul<{A}<T>, {B}<T>> {{\n"
            f"type Output = {O}<T>;\n{inline}"
            f"fn mul_mat(self: {A}<T>, rhs: {B}<T>) -> {O}<T> {{\n"
            f"{product_kernel(s, b, 'self', 'rhs')}\n}}\n}}")
        if s.is_square and b.c == 1 and b.r > 1:
            out.methods.append(method(
                "mul_vec",
                f"`self * v` ({kernel_note(s.c)}): the pre-8.1 name of "
                f"`mul_mat` for a vector, same kernel. Panics on overflow. Upstream: `self * v`.",
                f"mul_vec(self: {A}<T>, v: {B}<T>) -> {O}<T>",
                "MatrixMul::mul_mat(self, v)"))


def family_reductions(s: Shape, shapes: set[Shape], out: ShapeFile):
    S = s.name
    pairs = [(f"self.{k}", f"rhs.{k}") for k in s.fields]
    note = ("one floored product" if s.n == 1 else
            f"`Real::sum_prod{s.n}`" if s.n <= 4 else "the `Real::Wide` accumulator")
    out.methods.append(method(
        "dot",
        f"Dot product (sum of the component-wise products), fused ({note}): the exact sum is "
        f"floored once. Only the result must fit: panics on overflow. Upstream: `dot`.",
        f"dot(self: {S}<T>, rhs: {S}<T>) -> T", fused_body(pairs)))
    xs = [f"self.{k}" for k in s.fields]
    what = "Squared Euclidean norm" if s.is_vector else "Squared Frobenius norm"
    out.methods.append(method(
        "norm_squared",
        f"{what}: the exact sum of squares floored once. Panics on overflow. Upstream: "
        f"`norm_squared`.",
        f"norm_squared(self: {S}<T>) -> T", squares_body(xs)))


def index_linear_body(s: Shape) -> str:
    arms = "\n".join(f"{n} => *self.{k}," for n, k in enumerate(s.fields))
    return f"match index {{\n{arms}\n_ => core::panic_with_felt252(errors::INDEX_OUT_OF_BOUNDS),\n}}"


def index_nested_body(s: Shape, snapshot: bool = True) -> str:
    star = "*" if snapshot else ""
    oob = "_ => core::panic_with_felt252(errors::INDEX_OUT_OF_BOUNDS),"
    cols = []
    for j in range(s.c):
        rows = "\n".join(f"{i} => {star}self.{s.f(i, j)}," for i in range(s.r))
        cols.append(f"{j} => match i {{\n{rows}\n{oob}\n}},")
    return f"let (i, j) = index;\nmatch j {{\n" + "\n".join(cols) + f"\n{oob}\n}}"


def family_index(s: Shape, shapes: set[Shape], out: ShapeFile):
    S = s.name
    out.uses.add("super::errors")
    out.items.append(
        f"/// `m[i]`: the `i`-th component in column-major order (the storage order), like "
        f"upstream. Panics with `'Matrix index out of bounds'` when `i >= {s.n}`. Upstream: "
        f"`Index<usize>`.\n"
        f"pub impl {S}IndexLinear<T, +Copy<T>, +Drop<T>> of core::ops::IndexView<{S}<T>, usize> "
        f"{{\ntype Target = T;\n#[inline(always)]\n"
        f"fn index(self: @{S}<T>, index: usize) -> T {{\n{index_linear_body(s)}\n}}\n}}")
    out.items.append(
        f"/// `m[(i, j)]`: the component at row `i`, column `j` (0-based). Panics with `'Matrix "
        f"index out of bounds'` when `i >= {s.r}` or `j >= {s.c}`. Upstream: "
        f"`Index<(usize, usize)>`.\n///\n/// A `match` on the column then on the row: the "
        f"linear form (`i + j * {s.r}` then one `match`, with a row check) is dearer "
        f"(`bench_*_index2__alt_linear`).\n"
        f"pub impl {S}Index<T, +Copy<T>, +Drop<T>> of "
        f"core::ops::IndexView<{S}<T>, (usize, usize)> {{\ntype Target = T;\n"
        f"#[inline(always)]\n"
        f"fn index(self: @{S}<T>, index: (usize, usize)) -> T {{\n{index_nested_body(s)}\n}}\n}}")


FAMILIES = (family_construction, family_arithmetic, family_transpose, family_products,
            family_reductions)
LIB_FAMILIES = FAMILIES + (family_index,)


# --- specialisations -------------------------------------------------------------------------


def read_specialisations(s: Shape) -> list[Method]:
    """`specialisations/<module>.cairo`: `// @method <name>` sections, spliced verbatim."""
    path = SPECS / f"{s.module}.cairo"
    if not path.is_file():
        return []
    text = path.read_text()
    parts = re.split(r"^// @method (\w+)\n", text, flags=re.M)
    return [Method(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]


# --- rendering -------------------------------------------------------------------------------


IMPL_BOUNDS = """T,
    impl R: Real<T>,
    +Copy<T>,
    +Drop<T>,
    +Drop<R::Wide>,
    +Add<T>,
    +Sub<T>,
    +Mul<T>,
    +Neg<T>,
    +PartialEq<T>,
    +PartialOrd<T>,"""


def render_shape(s: Shape, shapes: set[Shape]) -> str:
    out = ShapeFile(s, [], [], {"simba::scalar::Real"})
    for fam in LIB_FAMILIES:
        fam(s, shapes, out)
    for spec in read_specialisations(s):
        names = [m.name for m in out.methods]
        if spec.name in names:
            out.methods[names.index(spec.name)] = spec
        else:
            out.methods.append(spec)
    S = s.name
    aliases = "".join(f"\n/// Upstream alias `{a}`: the same type as `{S}`.\n"
                      f"pub type {a}<T> = {S}<T>;\n" for a in s.aliases)
    if s.is_vector:
        layout = "Components are named like upstream's `Deref` targets (`x, y, z, w, a, b`)."
    else:
        layout = ("`mRC` is the component at row `R`, column `C`. Fields are declared in "
                  "column-major order, so `Serde` matches upstream's storage order, while `new` "
                  "takes its arguments in row-major order like upstream.")
    fields = "\n".join(f"pub {k}: T," for k in s.fields)
    methods = "\n\n".join(m.code for m in out.methods)
    uses = "\n".join(f"use {u};" for u in sorted(out.uses))
    items = "\n\n".join(out.items)
    return f"""{HEADER}//! `{S}`: a statically sized {s.kind} (upstream `nalgebra::{upstream(s)}`).
//!
//! Every sum of products goes through a fused `Real` kernel: one rounding (floor) and one
//! overflow check per output scalar. Operators live in this module, so they need no import; the
//! other operations are methods of `{S}Trait`, products between shapes are `MatrixMul::mul_mat`.

{uses}

/// A {s.kind}. {layout}
#[derive(Copy, Drop, PartialEq, Serde, Default, Debug, Hash)]
pub struct {S}<T> {{
{fields}
}}
{aliases}
/// Methods of `{S}<T>` for any `Real` scalar.
#[generate_trait]
pub impl {S}Impl<
    {IMPL_BOUNDS}
> of {S}Trait<T> {{
{methods}
}}

{items}
"""


def render_matrix_mul() -> str:
    return f"""{HEADER}//! `MatrixMul`: the product of two matrices of any conformable shapes.
//!
//! Upstream multiplies any `Matrix<R1, C1>` by any `Matrix<C1, C2>` with `*`. Cairo's `Mul` is
//! homogeneous (`fn mul(lhs: T, rhs: T) -> T`), so `*` only covers the square products
//! (`Matrix3 * Matrix3`); every conformable product, square ones included, is
//! `lhs.mul_mat(rhs)`, the output shape being the impl's associated `Output`.

/// `lhs * rhs` for conformable shapes (`Matrix2x3 * Matrix3x4 -> Matrix2x4`). Every component of
/// the result is ONE fused sum of products (one floor rounding, one overflow check). Upstream:
/// `Mul<Matrix<C1, C2>> for Matrix<R1, C1>`.
pub trait MatrixMul<Lhs, Rhs> {{
    /// The shape of `lhs * rhs`.
    type Output;
    /// `self * rhs`.
    fn mul_mat(self: Lhs, rhs: Rhs) -> Self::Output;
}}
"""


def render_errors() -> str:
    return f"""{HEADER}//! Panic messages of the generated shapes (stable API).

/// Out-of-range `Index` (upstream: `"Matrix index out of bounds."`).
pub const INDEX_OUT_OF_BOUNDS: felt252 = 'Matrix index out of bounds';
"""


def render_lib(shapes: list[Shape], compare: bool) -> str:
    mods = ["errors", "matrix_mul"] + [s.module for s in shapes]
    lines = [HEADER.rstrip(), "//! WP 8.1a prototype of the generated static shapes "
             "(`tools/shapegen/DESIGN.md`).", ""]
    for m in sorted(mods):
        lines.append(f"pub mod {m};")
    if compare:
        lines += ["#[cfg(test)]", "mod compare;"]
    lines += ["#[cfg(test)]", "mod tests;"]
    lines.append("")
    lines.append("pub use matrix_mul::MatrixMul;")
    for s in shapes:
        names = sorted([s.name, *s.aliases, f"{s.name}Trait"])
        lines.append(f"pub use {s.module}::{{{', '.join(names)}}};")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------------------------
# Generated tests: exact expectations from a bit-exact integer model of the kernels
# --------------------------------------------------------------------------------------------


def floor_scale(x: int) -> int:
    return x >> 32  # Python's >> is a floor division: the kernels' rounding


def rand_raw(rng: random.Random, bits: int = 36) -> int:
    """A raw Q32.32 value of magnitude < 2^(bits-32), with random fraction bits."""
    return rng.randrange(-(1 << bits), 1 << bits)


def raws(rng: random.Random, s: Shape, bits: int = 36) -> dict[str, int]:
    return {k: rand_raw(rng, bits) for k in s.fields}


def cairo_new(s: Shape, v: dict[str, int]) -> str:
    return f"{s.name}Trait::new({', '.join(f'fx({v[k]})' for k in s.row_major)})"


def cairo_lit(s: Shape, v: dict[str, int]) -> str:
    return s.lit({k: f"fx({v[k]})" for k in s.fields})


def model_product(a: Shape, b: Shape, va, vb) -> dict[str, int]:
    o = Shape(a.r, b.c)
    return {o.f(i, j): floor_scale(sum(va[a.f(i, k)] * vb[b.f(k, j)] for k in range(a.c)))
            for i in range(o.r) for j in range(o.c)}


def test_fn(name: str, body: str) -> str:
    return f"#[test]\nfn {name}() {{\n{body}\n}}"


def render_tests(shapes: list[Shape]) -> dict[str, str]:
    """One file per family, every shape of the set: tests/<family>.cairo."""
    shapeset = set(shapes)
    files: dict[str, list[str]] = {}
    uses: dict[str, set[Shape]] = {}

    def add(family: str, methods_on: list[Shape], name: str, body: str):
        """`methods_on`: the shapes whose trait methods the body calls with method syntax."""
        files.setdefault(family, []).append(test_fn(name, body))
        uses.setdefault(family, set()).update(methods_on)

    for s in shapes:
        rng = random.Random(f"shapegen/{s.name}")
        a, b = raws(rng, s), raws(rng, s)
        k = rand_raw(rng)
        m = s.module
        # construction: `new` is row-major, `Serde` column-major.
        body = [f"let m = {cairo_new(s, a)};", f"assert!(m == {cairo_lit(s, a)});",
                "let mut out: Array<felt252> = array![];", "m.serialize(ref out);",
                f"let raws: Array<i64> = array![{', '.join(str(a[f]) for f in s.fields)}];",
                f"assert!(out.len() == {s.n});", "let mut i = 0;",
                "while i < raws.len() {", "    let raw: i64 = *raws[i];",
                "    assert!(*out[i] == raw.into());", "    i += 1;", "}",
                f"let z: {s.name}<Fixed> = {s.name}Trait::zeros();",
                f"assert!(z == {cairo_lit(s, {f: 0 for f in s.fields})});",
                f"let e: {s.name}<Fixed> = {s.name}Trait::from_element(fx({k}));",
                f"assert!(e == {s.name}Trait::repeat(fx({k})));",
                f"assert!(e == {cairo_lit(s, {f: k for f in s.fields})});"]
        if s.is_square:
            ident = {s.f(i, j): (ONE if i == j else 0) for i in range(s.r) for j in range(s.c)}
            body.append(f"let id: {s.name}<Fixed> = {s.name}Trait::identity();")
            body.append(f"assert!(id == {cairo_lit(s, ident)});")
        add("construction", [], f"test_{m}_new_zeros_from_element", "\n".join(body))
        # arithmetic
        add_ = {f: a[f] + b[f] for f in s.fields}
        sub_ = {f: a[f] - b[f] for f in s.fields}
        neg_ = {f: -a[f] for f in s.fields}
        sc = {f: floor_scale(a[f] * k) for f in s.fields}
        add("arithmetic", [s], f"test_{m}_add_sub_neg_scale", "\n".join([
            f"let a = {cairo_lit(s, a)};", f"let b = {cairo_lit(s, b)};",
            f"assert!(a + b == {cairo_lit(s, add_)});",
            f"assert!(a - b == {cairo_lit(s, sub_)});",
            f"assert!(-a == {cairo_lit(s, neg_)});",
            f"assert!(a.scale(fx({k})) == {cairo_lit(s, sc)});",
            "let mut c = a;", "c += b;", "c -= b;", "assert!(c == a);"]))
        big = {f: 0 for f in s.fields}
        big[s.fields[-1]] = I64_MAX
        add("arithmetic", [], f"test_{m}_add_overflow_panics",
            f"let a = {cairo_lit(s, big)};\nlet _ = a + a;")
        files["arithmetic"][-1] = "#[should_panic]\n" + files["arithmetic"][-1]
        # transpose
        t = s.transposed()
        if t in shapeset:
            tv = {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
            add("transpose", [s, t], f"test_{m}_transpose",
                f"let a = {cairo_lit(s, a)};\nassert!(a.transpose() == {cairo_lit(t, tv)});\n"
                f"assert!(a.transpose().transpose() == a);")
        # reductions (exact floor of the exact sums)
        dot = floor_scale(sum(a[f] * b[f] for f in s.fields))
        n2 = floor_scale(sum(a[f] * a[f] for f in s.fields))
        add("reductions", [s], f"test_{m}_dot_norm_squared", "\n".join([
            f"let a = {cairo_lit(s, a)};", f"let b = {cairo_lit(s, b)};",
            f"assert!(a.dot(b) == fx({dot}));", f"assert!(a.norm_squared() == fx({n2}));",
            f"assert!(b.dot(a) == fx({dot}));"]))
        # index
        lin = "\n".join(f"assert!(a[{i}] == fx({a[f]}));" for i, f in enumerate(s.fields))
        two = "\n".join(f"assert!(a[({i}, {j})] == fx({a[s.f(i, j)]}));"
                        for i in range(s.r) for j in range(s.c))
        add("index", [], f"test_{m}_index", f"let a = {cairo_lit(s, a)};\n{lin}\n{two}")
        add("index", [], f"test_{m}_index_linear_out_of_bounds_panics",
            f"let a = {cairo_lit(s, a)};\nlet _ = a[{s.n}];")
        files["index"][-1] = ("#[should_panic(expected: 'Matrix index out of bounds')]\n"
                              + files["index"][-1])
        add("index", [], f"test_{m}_index_row_out_of_bounds_panics",
            f"let a = {cairo_lit(s, a)};\nlet _ = a[({s.r}, 0)];")
        files["index"][-1] = ("#[should_panic(expected: 'Matrix index out of bounds')]\n"
                              + files["index"][-1])
        # products, every conformable pair of the set
        for b_shape in sorted(shapeset):
            o = Shape(s.r, b_shape.c)
            if b_shape.r != s.c or o not in shapeset:
                continue
            rng2 = random.Random(f"shapegen/{s.name}*{b_shape.name}")
            va, vb = raws(rng2, s), raws(rng2, b_shape)
            vo = model_product(s, b_shape, va, vb)
            body = [f"let a = {cairo_lit(s, va)};", f"let b = {cairo_lit(b_shape, vb)};",
                    f"let e = {cairo_lit(o, vo)};", "assert!(a.mul_mat(b) == e);"]
            if s == b_shape:
                body.append("assert!(a * b == e);")
                body.append("let mut c = a;\nc *= b;\nassert!(c == e);")
            if s.is_square and b_shape.c == 1 and b_shape.r > 1:
                body.append("assert!(a.mul_vec(b) == e);")
            add("products", [s] if "mul_vec" in body[-1] else [],
                f"test_{m}_mul_{b_shape.module}", "\n".join(body))
    out = {}
    for family, fns in files.items():
        imports = use_lines("\n\n".join(fns), shapes, uses[family], {"fixed::Fixed"})
        out[family] = (f"{HEADER}//! Generated tests of the `{family}` family: exact expectations "
                       f"from the integer model of the kernels (floor once per output scalar)."
                       f"\n\n{imports}\n\nfn fx(raw: i64) -> Fixed {{\n    Fixed {{ raw }}\n}}\n\n"
                       + "\n\n".join(fns) + "\n")
    return out


def use_lines(body: str, shapes: list[Shape], methods_on: set[Shape], extra: set[str]) -> str:
    """The `use` lines a generated test module needs, and no more (no unused-import warning):
    a struct when its name appears, its trait when named or when its methods are called."""
    uses = set(extra)
    if re.search(r"\bmul_mat\b", body):
        uses.add("crate::MatrixMul")
    if re.search(r"\berrors::", body):
        uses.add("crate::errors")
    for s in shapes:
        names = [n for n in (s.name,) if re.search(rf"\b{n}\b", body)]
        if s in methods_on or re.search(rf"\b{s.name}Trait\b", body):
            names.append(f"{s.name}Trait")
        if names:
            uses.add(f"crate::{s.module}::{{{', '.join(names)}}}" if len(names) > 1
                     else f"crate::{s.module}::{names[0]}")
    for hname in HANDWRITTEN.values():
        names = [f"{n} as H{n}" for n in (hname, f"{hname}Trait")
                 if re.search(rf"\bH{n}\b", body)]
        if names:
            uses.add(f"nalgebra::base::{hname.lower()}::{{{', '.join(names)}}}")
    return "\n".join(f"use {u};" for u in sorted(uses))


def render_tests_root(families: list[str]) -> str:
    return HEADER + "".join(f"mod {f};\n" for f in sorted(families))


# --------------------------------------------------------------------------------------------
# Comparison with the hand-written shapes of `crates/nalgebra` (bit identity and gas)
# --------------------------------------------------------------------------------------------


HANDWRITTEN = {
    Shape(2, 1): "Vector2",
    Shape(3, 1): "Vector3",
    Shape(6, 1): "Vector6",
    Shape(2, 2): "Matrix2",
    Shape(3, 3): "Matrix3",
}

# (op, arity, returns a shape?) of the overlapping surface, and the shapes that have it.
COMPARE_OPS = {
    "new": None, "zeros": None, "identity": {Shape(2, 2), Shape(3, 3)},
    "add": None, "sub": None, "neg": None, "scale": None,
    "transpose": {Shape(2, 2), Shape(3, 3)},
    "mul": {Shape(2, 2), Shape(3, 3)}, "mul_vec": {Shape(2, 2), Shape(3, 3)},
    "dot": {Shape(2, 1), Shape(3, 1), Shape(6, 1)},
    "norm_squared": None,
    "cross": {Shape(3, 1)},
    "determinant": {Shape(2, 2), Shape(3, 3)},
}


def render_compare(shapes: list[Shape]) -> str:
    """Bit-identity tests and gas benchmarks, generated shape vs hand-written shape."""
    shapeset = set(shapes)
    uses = {"fixed::Fixed", "nalgebra_testing::black_box", "crate::MatrixMul"}
    fns: list[str] = []
    for s, hname in HANDWRITTEN.items():
        if s not in shapeset:
            continue
        uses.add(f"crate::{s.module}::{{{s.name}, {s.name}Trait}}")
        uses.add(f"nalgebra::base::{hname.lower()}::{{{hname} as H{hname}, "
                 f"{hname}Trait as H{hname}Trait}}")
        fns.append(f"fn to_h_{s.module}(g: {s.name}<Fixed>) -> H{hname}<Fixed> {{\n"
                   f"{hw_literal(s, {f: f'g.{f}' for f in s.fields})}\n}}")
        vec = Shape(s.r, 1) if s.is_square and s.r > 1 else None
        rng = random.Random(f"compare/{s.name}")
        cases = [Case(raws(rng, s), raws(rng, s), rand_raw(rng), raws(rng, vec) if vec else None)
                 for _ in range(3)]
        for op, only in COMPARE_OPS.items():
            if only is not None and s not in only:
                continue
            checks = []
            for c in cases:
                g, h = call(op, s, "g", c, vec, literal=True), call(op, s, "h", c, vec, True)
                out, _ = model(op, s, c, vec)
                checks.append(f"assert!({g if out is None else f'to_h_{out.module}({g})'} == {h});")
            fns.append(test_fn(f"test_{s.module}_{op}_bit_identical", "\n".join(checks)))
            fns.extend(bench_trio(op, s, cases[0], vec))
    fns.extend(render_index_alternatives(shapes, uses))
    fns.extend(render_mul_mat_benches(shapes, uses))
    body = "\n\n".join(fns)
    imports = use_lines(body, shapes, {s for s in HANDWRITTEN if s in shapeset},
                        {"fixed::Fixed", "nalgebra_testing::black_box"})
    return (f"{HEADER}//! Proof of the migration: the generated shapes against the hand-written "
            f"`Vector2/3/6`, `Matrix2/3` of `crates/nalgebra`, on the overlapping surface.\n//!\n"
            f"//! - `test_<shape>_<op>_bit_identical`: equal outputs on three random inputs;\n"
            f"//! - `bench_<shape>_<op>__generated` / `__handwritten`: the gas of each side (same "
            f"inputs, same assertion, one baseline).\n\n{imports}\n\n"
            f"fn fx(raw: i64) -> Fixed {{\n    Fixed {{ raw }}\n}}\n\n" + "\n\n".join(fns) + "\n")


@dataclass
class Case:
    a: dict
    b: dict
    k: int
    v: dict | None


def hw_literal(s: Shape, values: dict[str, str]) -> str:
    H = f"H{HANDWRITTEN[s]}"
    if s == Shape(6, 1):
        x = [values[f] for f in s.fields]
        return (f"{H} {{ a: nalgebra::base::Vector3 {{ x: {x[0]}, y: {x[1]}, z: {x[2]} }}, "
                f"b: nalgebra::base::Vector3 {{ x: {x[3]}, y: {x[4]}, z: {x[5]} }} }}")
    return f"{H} {{ {', '.join(f'{f}: {values[f]}' for f in s.fields)} }}"


def side_new(s: Shape, side: str, v: dict) -> str:
    trait = f"{s.name}Trait" if side == "g" else f"H{HANDWRITTEN[s]}Trait"
    return f"{trait}::new({', '.join(f'fx({v[k]})' for k in s.row_major)})"


def side_lit(s: Shape, side: str, v) -> str:
    if s is None:
        return f"fx({v})"
    vals = {f: f"fx({v[f]})" for f in s.fields}
    return s.lit(vals) if side == "g" else hw_literal(s, vals)


def model(op: str, s: Shape, c: Case, vec):
    """(output shape or None for a scalar, raw value(s)): the integer model of the kernels."""
    a, b, k = c.a, c.b, c.k
    dp = lambda p, q, r, t: floor_scale(p * q - r * t)  # noqa: E731 (diff_prod)
    if op == "new":
        return s, a
    if op == "zeros":
        return s, {f: 0 for f in s.fields}
    if op == "identity":
        return s, {s.f(i, j): ONE if i == j else 0 for i in range(s.r) for j in range(s.c)}
    if op == "add":
        return s, {f: a[f] + b[f] for f in s.fields}
    if op == "sub":
        return s, {f: a[f] - b[f] for f in s.fields}
    if op == "neg":
        return s, {f: -a[f] for f in s.fields}
    if op == "scale":
        return s, {f: floor_scale(a[f] * k) for f in s.fields}
    if op == "transpose":
        t = s.transposed()
        return t, {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
    if op == "mul":
        return s, model_product(s, s, a, b)
    if op == "mul_vec":
        return vec, model_product(s, vec, a, c.v)
    if op == "dot":
        return None, floor_scale(sum(a[f] * b[f] for f in s.fields))
    if op == "norm_squared":
        return None, floor_scale(sum(a[f] * a[f] for f in s.fields))
    if op == "cross":
        return s, {"x": dp(a["y"], b["z"], a["z"], b["y"]), "y": dp(a["z"], b["x"], a["x"], b["z"]),
                   "z": dp(a["x"], b["y"], a["y"], b["x"])}
    if op == "determinant" and s.r == 2:
        return None, dp(a["m11"], a["m22"], a["m12"], a["m21"])
    if op == "determinant" and s.r == 3:
        return None, floor_scale(a["m11"] * dp(a["m22"], a["m33"], a["m23"], a["m32"])
                                 + a["m12"] * dp(a["m23"], a["m31"], a["m21"], a["m33"])
                                 + a["m13"] * dp(a["m21"], a["m32"], a["m22"], a["m31"]))
    raise ValueError(op)


def call(op: str, s: Shape, side: str, c: Case, vec, literal: bool) -> str:
    """The expression of `op` on one side, on literal inputs or on the bench's `a, b, k, v`."""
    trait = f"{s.name}Trait" if side == "g" else f"H{HANDWRITTEN[s]}Trait"
    a = side_new(s, side, c.a) if literal else "a"
    b = side_new(s, side, c.b) if literal else "b"
    k = f"fx({c.k})" if literal else "k"
    v = (side_new(vec, side, c.v) if literal else "v") if vec else None
    if op == "new":
        return a if literal else f"{trait}::new({', '.join(f'r{i}' for i in range(s.n))})"
    return {"zeros": f"{trait}::zeros()", "identity": f"{trait}::identity()",
            "add": f"({a} + {b})", "sub": f"({a} - {b})", "neg": f"(-{a})",
            "scale": f"{a}.scale({k})", "transpose": f"{a}.transpose()", "mul": f"({a} * {b})",
            "mul_vec": f"{a}.mul_vec({v})", "dot": f"{a}.dot({b})", "cross": f"{a}.cross({b})",
            "norm_squared": f"{a}.norm_squared()",
            "determinant": f"{a}.determinant()"}[op]


def unused(lines: list[str]) -> list[str]:
    return [re.sub(r"^let (\w+)", r"let _\1", line) for line in lines]


def bench_trio(op: str, s: Shape, c: Case, vec) -> list[str]:
    """baseline / generated / handwritten on the same black-boxed inputs and expectation."""
    group = f"{s.module}_{op}"
    out_shape, value = model(op, s, c, vec)

    def inputs(side: str) -> list[str]:
        if op == "new":
            return [f"let r{i} = black_box(fx({c.a[f]}));" for i, f in enumerate(s.row_major)]
        if op in ("zeros", "identity"):
            return []
        lines = [f"let a = black_box({side_new(s, side, c.a)});"]
        if op in ("add", "sub", "mul", "dot", "cross"):
            lines.append(f"let b = black_box({side_new(s, side, c.b)});")
        if op == "scale":
            lines.append(f"let k = black_box(fx({c.k}));")
        if op == "mul_vec":
            lines.append(f"let v = black_box({side_new(vec, side, c.v)});")
        return lines

    def expected(side: str) -> str:
        return f"let e = black_box({side_lit(out_shape, side, value)});"

    fns = [f"#[test]\n#[inline(never)]\nfn bench_{group}__baseline() {{\n"
           + "\n".join(unused(inputs("g")) + [expected("g"), "assert!(e == e);"]) + "\n}"]
    for side, variant in (("g", "generated"), ("h", "handwritten")):
        lines = inputs(side) + [expected(side),
                                f"assert!({call(op, s, side, c, vec, False)} == e);"]
        fns.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__{variant}() {{\n"
                   + "\n".join(lines) + "\n}")
    return fns


def render_index_alternatives(shapes: list[Shape], uses: set[str]) -> list[str]:
    """The linear 2-D index (`i + j * R`, row check, one `match`): the loser, kept as evidence."""
    out = []
    for s in (Shape(3, 3), Shape(2, 3)):
        if s not in shapes:
            continue
        uses.add(f"crate::{s.module}::{{{s.name}, {s.name}Trait}}")
        uses.add("crate::errors")
        m = s.module
        out.append(
            f"/// Loser of the 2-D index: linear offset then one `match` (row checked first).\n"
            f"#[inline(always)]\nfn alt_index_linear_{m}(self: @{s.name}<Fixed>, index: "
            f"(usize, usize)) -> Fixed {{\nlet (i, j) = index;\nif i >= {s.r} {{\n"
            f"core::panic_with_felt252(errors::INDEX_OUT_OF_BOUNDS)\n}}\n"
            f"let index = i + j * {s.r};\n{index_linear_body(s)}\n}}")
        rng = random.Random(f"index/{s.name}")
        a = raws(rng, s)
        i, j = s.r - 1, s.c - 1
        lit = cairo_lit(s, a)
        ex = f"fx({a[s.f(i, j)]})"
        out.append(test_fn(f"test_{m}_index2_alt_linear_matches",
                           "\n".join(f"assert!(alt_index_linear_{m}(@{lit}, ({ii}, {jj})) == "
                                     f"{lit}[({ii}, {jj})]);"
                                     for ii in range(s.r) for jj in range(s.c))))
        pre = [f"let a = black_box({lit});", f"let i = black_box({i});",
               f"let j = black_box({j});", f"let e = black_box({ex});"]
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__baseline() {{\n"
                   + "\n".join(pre).replace("let a", "let _a").replace("let i ", "let _i ")
                   .replace("let j ", "let _j ") + "\nassert!(e == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__nested() {{\n"
                   + "\n".join(pre) + "\nassert!(a[(i, j)] == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index2__alt_linear() {{\n"
                   + "\n".join(pre) + "\nassert!(alt_index_linear_" + m + "(@a, (i, j)) == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index1__baseline() {{\n"
                   + f"let _a = black_box({lit});\nlet _i = black_box({s.n - 1});\n"
                   f"let e = black_box({ex});\nassert!(e == e);\n}}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{m}_index1__match() {{\n"
                   + f"let a = black_box({lit});\nlet i = black_box({s.n - 1});\n"
                   f"let e = black_box({ex});\nassert!(a[i] == e);\n}}")
    return out


def render_mul_mat_benches(shapes: list[Shape], uses: set[str]) -> list[str]:
    """`mul_mat` against `*` (square) and a rectangular product, for the gas table."""
    out = []
    pairs = [(Shape(3, 3), Shape(3, 3)), (Shape(2, 3), Shape(3, 2)), (Shape(3, 2), Shape(2, 3)),
             (Shape(1, 3), Shape(3, 1)), (Shape(3, 1), Shape(1, 3)), (Shape(2, 3), Shape(3, 1))]
    for a_s, b_s in pairs:
        o = Shape(a_s.r, b_s.c)
        if a_s not in shapes or b_s not in shapes or o not in shapes:
            continue
        for x in (a_s, b_s, o):
            uses.add(f"crate::{x.module}::{{{x.name}, {x.name}Trait}}")
        rng = random.Random(f"mulmat/{a_s.name}*{b_s.name}")
        va, vb = raws(rng, a_s), raws(rng, b_s)
        vo = model_product(a_s, b_s, va, vb)
        group = f"{a_s.module}_mul_{b_s.module}"
        pre = [f"let a = black_box({cairo_lit(a_s, va)});",
               f"let b = black_box({cairo_lit(b_s, vb)});",
               f"let e = black_box({cairo_lit(o, vo)});"]
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__baseline() {{\n"
                   + "\n".join(pre).replace("let a", "let _a").replace("let b", "let _b")
                   + "\nassert!(e == e);\n}")
        out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__mul_mat() {{\n"
                   + "\n".join(pre) + "\nassert!(a.mul_mat(b) == e);\n}")
        if a_s == b_s:
            out.append(f"#[test]\n#[inline(never)]\nfn bench_{group}__operator() {{\n"
                       + "\n".join(pre) + "\nassert!(a * b == e);\n}")
    return out


