def shapes_from(spec: str) -> list[Shape]:
    if spec == "all":
        return [Shape(r, c) for r in range(1, 7) for c in range(1, 7)]
    if spec == "proto":
        return PROTO_SHAPES
    if spec == "none":
        return []
    out = []
    for token in spec.split(","):
        r, c = token.split("x")
        out.append(Shape(int(r), int(c)))
    return out


