def generate(pkg: Path, shapes: list[Shape], compare: bool, tests: bool, manifest_root: str,
             name: str, test_families: set[str] | None = None, integration: bool = False):
    src = pkg / "src"
    if src.exists():
        shutil.rmtree(src)
    (src / "tests").mkdir(parents=True)
    nalgebra = f'nalgebra = {{ path = "{manifest_root}/crates/nalgebra" }}\n' if compare else ""
    (pkg / "Scarb.toml").write_text(MANIFEST.format(root=manifest_root, name=name,
                                                    nalgebra=nalgebra))
    shapeset = set(shapes)
    (src / "lib.cairo").write_text(render_lib(shapes, compare) if tests else
                                   render_lib(shapes, compare).replace(
                                       "#[cfg(test)]\nmod tests;\n", ""))
    (src / "errors.cairo").write_text(render_errors())
    (src / "matrix_mul.cairo").write_text(render_matrix_mul())
    if FUSED_HELPERS:
        (src / "kernels.cairo").write_text(render_kernels())
    for s in shapes:
        (src / f"{s.module}.cairo").write_text(render_shape(s, shapeset))
    if tests and integration:
        # One integration-test file per family: Scarb compiles each as its own crate.
        shutil.rmtree(src / "tests")
        (pkg / "tests").mkdir()
        (src / "lib.cairo").write_text(render_lib(shapes, compare).replace(
            "#[cfg(test)]\nmod tests;\n", ""))
        helpers = TESTS_HELPERS.split("#[test]")[0]
        for fam, text in render_tests(shapes).items():
            if test_families is not None and fam not in test_families:
                continue
            text = re.sub(r"use super::\{[^}]*\};\n", "", text).replace("crate::", f"{name}::")
            text = text.replace("use fixed::Fixed;\n", "") + helpers
            (pkg / "tests" / f"{fam}.cairo").write_text(text)
    elif tests:
        families = {f: text for f, text in render_tests(shapes).items()
                    if test_families is None or f in test_families}
        for fam, text in families.items():
            (src / "tests" / f"{fam}.cairo").write_text(text)
        (src / "tests.cairo").write_text(render_tests_root(list(families)))
    else:
        shutil.rmtree(src / "tests")
    if compare:
        (src / "compare.cairo").write_text(render_compare(shapes))
    subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)


FMT_MANIFEST = """[package]
name = "shapegen_library"
version = "0.1.0"
edition = "2024_07"

[tool.fmt]
sort-module-level-items = true
max-line-length = 100
"""


def library_outputs(pkg: Path) -> dict[Path, Path]:
    """Writes the library shapes (`shapes.py`, `library.py`), their shared modules and the
    generated blocks of `base.cairo` / `lib.cairo` into `pkg/src`, formats them with `scarb fmt`
    (the workspace's `[tool.fmt]`), and returns {committed path: generated path}."""
    src = pkg / "src"
    src.mkdir(parents=True)
    (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
    (src / "lib.cairo").write_text("")
    out = {}
    for shape in ALL_SHAPES:
        (src / f"{shape.module}.cairo").write_text(shapes.render(shape))
        out[library.BASE / f"{shape.module}.cairo"] = src / f"{shape.module}.cairo"
    for module, render in shapes.SHARED_MODULES.items():
        (src / f"{module}.cairo").write_text(render())
        out[library.BASE / f"{module}.cairo"] = src / f"{module}.cairo"
    # WP 8.5-P14a: generated modules of `linalg` (their `mod` lines are hand-written in
    # `linalg.cairo`); written in a sub-directory so that their names cannot clash with `base`'s.
    (src / "linalg").mkdir()
    for module, render in shapes.LINALG_MODULES.items():
        (src / "linalg" / f"{module}.cairo").write_text(render())
        out[library.BASE.parent / "linalg" / f"{module}.cairo"] = src / "linalg" / f"{module}.cairo"
    # WP 8.5-P13: the static side of the dynamic matrices (its `mod` line is hand-written in
    # `base/dynamic.cairo`).
    (src / "dynamic").mkdir()
    (src / "dynamic" / "shapes.cairo").write_text(dynamic.render())
    out[library.BASE / "dynamic" / "shapes.cairo"] = src / "dynamic" / "shapes.cairo"
    for target, module in dynamic.TYPE_MODULES.items():
        committed = library.BASE / "dynamic" / f"{module}.cairo"
        (src / "dynamic" / f"{module}.cairo").write_text(
            shapes.splice(committed.read_text(), dynamic.conversion_block(target)))
        out[committed] = src / "dynamic" / f"{module}.cairo"
    # WP 8.6-P21: the construction macros (their `mod` line is hand-written in `lib.cairo`).
    (src / "macros.cairo").write_text(root_ops.render_macros())
    out[library.BASE.parent / "macros.cairo"] = src / "macros.cairo"
    base_rs, lib_rs = library.BASE.parent / "base.cairo", library.BASE.parent / "lib.cairo"
    (src / "base.cairo").write_text(shapes.splice(base_rs.read_text(), shapes.base_block()))
    (src / "crate_root.cairo").write_text(shapes.splice(lib_rs.read_text(), shapes.lib_block()))
    out[base_rs], out[lib_rs] = src / "base.cairo", src / "crate_root.cairo"
    subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    shapes.check_block((src / "base.cairo").read_text(), "base.cairo", shapes.owned_modules())
    root = (src / "crate_root.cairo").read_text()
    block = root[root.index(shapes.BEGIN):root.index(shapes.END)]
    if not re.search(r"pub use base::\{\s*ColumnPart,", block) or "MatrixMul" in root.replace(block, ""):
        raise SystemExit("shapegen: the generated re-exports of lib.cairo left their markers")
    return out


def proto_outputs(pkg: Path) -> dict[Path, Path]:
    """Writes the prototype package into `pkg` and returns {committed path: generated path}."""
    generate(pkg, PROTO_SHAPES, True, True, "../../..", "shapegen_proto")
    rels = {p.relative_to(pkg) for p in (pkg / "src").rglob("*.cairo")} | {Path("Scarb.toml")}
    return {PROTO / rel: pkg / rel for rel in rels}


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true", help="fail if a committed output is stale")
    p.add_argument("--compare", type=Path, metavar="DIR",
                   help="write the staging comparison package there (`compare.py`)")
    p.add_argument("--out", type=Path, help="write a measurement package there instead")
    p.add_argument("--shapes", default="proto", help="'proto', 'all', 'none' or '2x3,3x1,...'")
    p.add_argument("--compare-root", type=Path, metavar="ROOT",
                   help="with --compare: the checkout whose crates are the hand-written side "
                        "(default: this repository)")
    p.add_argument("--no-compare", action="store_true", help="omit the comparison module")
    p.add_argument("--no-tests", action="store_true", help="omit the generated tests")
    p.add_argument("--test-families", help="only these test families ('products,index')")
    p.add_argument("--replicate", type=int, default=1,
                   help="measurement: N renamed copies of every trait method")
    p.add_argument("--integration", action="store_true",
                   help="generated tests as one integration-test crate per family (tests/)")
    args = p.parse_args()
    shapes = sorted(shapes_from(args.shapes), key=lambda s: (s.r, s.c))
    global REPLICATE
    REPLICATE = args.replicate
    if args.out:
        generate(args.out, shapes, not args.no_compare, not args.no_tests, str(ROOT),
                 "shapegen_" + re.sub(r"\W", "_", args.out.name.lstrip(".")).lower(),
                 set(args.test_families.split(",")) if args.test_families else None,
                 args.integration)
        return 0
    if args.compare:
        compare.generate(args.compare, str((args.compare_root or ROOT).resolve()))
        subprocess.run(["scarb", "fmt"], cwd=args.compare, check=True)
        print(f"shapegen: staging comparison package written to {args.compare}")
        return 0
    # Generated next to the real packages (same depth: the relative path dependencies resolve),
    # formatted by `scarb fmt`, then compared or copied.
    tmp_proto, tmp_lib = TOOL / ".tmp-proto", TOOL / ".tmp-library"
    tmp_tests, tmp_ops = TOOL / ".tmp-tests", TOOL / ".tmp-tests-ops"
    tmp_fun = TOOL / ".tmp-tests-functional"
    tmp_views = TOOL / ".tmp-tests-views"
    tmp_cg = TOOL / ".tmp-tests-cg"
    tmp_p06 = TOOL / ".tmp-tests-p06"
    tmps = (tmp_proto, tmp_lib, tmp_tests, tmp_ops, tmp_fun, tmp_views, tmp_cg, tmp_p06)
    try:
        for tmp in tmps:
            shutil.rmtree(tmp, ignore_errors=True)
        outputs = (proto_outputs(tmp_proto) | library_outputs(tmp_lib)
                   | tests_core.outputs(tmp_tests) | tests_ops.outputs(tmp_ops)
                   | tests_functional.outputs(tmp_fun) | tests_views.outputs(tmp_views)
                   | tests_cg.outputs(tmp_cg) | tests_stats.outputs(tmp_p06)
                   | tests_blas.outputs(tmp_p06))
        committed = (set((PROTO / "src").rglob("*.cairo"))
                     | set((tests_core.PACKAGE / "src").rglob("*.cairo"))
                     | {p for pkg in tests_ops.PACKAGES
                        for p in (ROOT / "crates" / pkg / "src").rglob("*.cairo")}
                     | {p for pkg in tests_functional.PACKAGES
                        for p in (ROOT / "crates" / pkg / "src").rglob("*.cairo")}
                     | {p for pkg in tests_views.PACKAGES
                        for p in (ROOT / "crates" / pkg / "src").rglob("*.cairo")}
                     | set((ROOT / "crates" / tests_cg.PACKAGE / "src").rglob("*.cairo"))
                     | {p for pkg in (tests_stats.PACKAGE, *tests_blas.PACKAGES)
                        for p in (ROOT / "crates" / pkg / "src").rglob("*.cairo")})
        removed = sorted(committed - set(outputs))
        stale = sorted(dst for dst, gen in outputs.items()
                       if not dst.is_file() or not filecmp.cmp(gen, dst, shallow=False))
        if args.check:
            if stale or removed:
                names = [str(p.relative_to(ROOT)) for p in stale + removed]
                print("stale shapegen output: " + ", ".join(names), file=sys.stderr)
                return 1
            print(f"shapegen: {len(outputs)} generated files up to date")
            return 0
        for path in removed:
            path.unlink()
        for dst in stale:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(outputs[dst], dst)
        print(f"shapegen: {len(stale) + len(removed)} file(s) updated")
    finally:
        for tmp in tmps:
            shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
