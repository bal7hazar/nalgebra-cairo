"""Template of `crates/nalgebra/src/base/dynamic/shapes.cairo` (WP 8.5-P13, API_PARITY package
P13): what the 36 static shapes gain from the dynamic matrices (DESIGN D5), behind the `dynamic`
feature with the rest of `base/dynamic*.cairo`.

* conversions `Into<S, DMatrix>` for every shape, `Into<VectorN, DVector>` and `Into<RowVectorN,
  RowDVector>` (upstream `From<Matrix> for DMatrix`, a change of storage): one column-major
  array literal each;
* `<S>DynamicTrait` per shape (upstream `edition.rs`, `construction.rs`, `properties.rs`,
  `statistics.rs`): the edition forms whose result has a dynamic dimension (`insert_columns`,
  `insert_rows`, `remove_columns`, `remove_rows`, `remove_columns_at`, `remove_rows_at`,
  `resize_horizontally`, `resize_vertically`: the shape converted, then the dynamic kernel; the
  result is upstream's `OMatrix<R, Dyn>` / `OMatrix<Dyn, C>`, i.e. `RowDVector` for one row,
  `DVector` for one column, `DMatrix` otherwise), `from_vec` / `from_iterator` /
  `from_row_iterator` (a `Array` / `Span` read by `from_column_slice` / `from_row_slice`), `len`,
  `is_empty`, and with `closures` `compress_rows` / `compress_rows_tr` / `compress_columns`
  (straight-line, the columns as `VectorR` literals);
* `InsertFixedColumns` / `InsertFixedRows` / `RemoveFixedColumns` / `RemoveFixedRows<M, Out, T>`:
  upstream's `insert_fixed_columns::<D>` .. `remove_fixed_rows::<D>` whose result is another
  static shape. Cairo has no const generics: like `FixedRows` (`matrix_view.cairo`), the output
  type selects `D` (inferred like `Into`), one impl per (shape, D) pair, so an impossible size is
  a compile error. Each impl pads `self` onto the `Matrix6` canvas (`PadTo6`), runs ONE of the
  `Canvas6Edit` kernels (a `match` on the position selecting one `Matrix6` literal) and crops
  (`CropFrom6`): struct moves are free once inlined, 80 canvas literals instead of 720 per-pair
  literals (`bench_matrix3x4_insert_fixed_columns__alt_direct`, equal gas).
"""

from model import ALL_SHAPES, Shape

HEADER = ("// Generated by tools/shapegen/shapegen.py: do not edit by hand. Template:\n"
          "// tools/shapegen/dynamic.py.\n")
BOUNDS = ("T, impl R: Real<T>, +Copy<T>, +Drop<T>, +Drop<R::Wide>, +Add<T>, +Sub<T>, +Mul<T>, "
          "+Neg<T>, +PartialEq<T>, +PartialOrd<T>")
CANVAS = Shape(6, 6)
INDEX_ERROR = "errors::INDEX_OUT_OF_BOUNDS"
PATH = "super::super"


def col(r: int) -> Shape:
    return Shape(r, 1)


def row(c: int) -> Shape:
    return Shape(1, c)


def doc(text: str, indent: str = "") -> str:
    """One `///` line (`scarb fmt` wraps it at 100 columns)."""
    return f"{indent}/// {text.replace(chr(10), ' ')}\n"


def data_literal(s: Shape) -> str:
    return "array![" + ", ".join(f"self.{f}" for f in s.fields) + "].span()"


def conversions(s: Shape) -> list[str]:
    out = [doc(f"The `{s.r}x{s.c}` `DMatrix` of the components of a `{s.name}` (column-major "
               "copy). Upstream: `From<Matrix> for DMatrix`.") +
           f"pub impl {s.name}IntoDMatrix<T, +Copy<T>, +Drop<T>> of Into<{s.name}<T>, "
           f"DMatrix<T>> {{\n#[inline]\nfn into(self: {s.name}<T>) -> DMatrix<T> {{\n"
           f"DMatrix {{ data: {data_literal(s)}, nrows: {s.r}, ncols: {s.c} }}\n}}\n}}\n"]
    if s.is_column:
        out.append(doc(f"The `DVector` of the {s.r} components of a `{s.name}`. Upstream: "
                       "`From<Matrix> for DVector`.") +
                   f"pub impl {s.name}IntoDVector<T, +Copy<T>, +Drop<T>> of Into<{s.name}<T>, "
                   f"DVector<T>> {{\n#[inline]\nfn into(self: {s.name}<T>) -> DVector<T> {{\n"
                   f"DVector {{ data: {data_literal(s)} }}\n}}\n}}\n")
    if s.is_row:
        out.append(doc(f"The `RowDVector` of the {s.c} components of a `{s.name}`. Upstream: "
                       "`From<Matrix> for RowDVector`.") +
                   f"pub impl {s.name}IntoRowDVector<T, +Copy<T>, +Drop<T>> of Into<{s.name}<T>, "
                   f"RowDVector<T>> {{\n#[inline]\nfn into(self: {s.name}<T>) -> RowDVector<T> {{\n"
                   f"RowDVector {{ data: {data_literal(s)} }}\n}}\n}}\n")
    return out


def horizontal(s: Shape) -> tuple[str, str]:
    """The type of upstream's `OMatrix<R, Dyn>` for `s` and the conversion of `self` to it."""
    return ("RowDVector", "RowDVector") if s.r == 1 else ("DMatrix", "DMatrix")


def vertical(s: Shape) -> tuple[str, str]:
    """The type of upstream's `OMatrix<Dyn, C>`."""
    return ("DVector", "DVector") if s.c == 1 else ("DMatrix", "DMatrix")


def column_literal(s: Shape, j: int) -> str:
    c = col(s.r)
    return c.lit({c.f(i, 0): f"self.{s.f(i, j)}" for i in range(s.r)})


def method(docs: str, sig: str, body: str, attrs: str = "#[inline]") -> str:
    return doc(docs, "    ") + f"    {attrs}\n    fn {sig} {{\n{body}\n    }}\n"


def dynamic_trait(s: Shape) -> str:
    S, T = s.name, f"{s.name}<T>"
    h, _ = horizontal(s)
    v, _ = vertical(s)
    ms = []
    ms.append(method(f"The {s.kind} of the {s.n} values of `data` in COLUMN-major order. Panics "
                     "with `nalgebra: wrong slice length` unless\n"
                     f"`data.len() == {s.n}`. Upstream: `{S}::from_vec(Vec<T>)`.",
                     f"from_vec(data: Array<T>) -> {T}",
                     f"        {S}Trait::from_column_slice(data.span())"))
    ms.append(method(f"The {s.kind} of the values of `data` in COLUMN-major order. Panics with "
                     "`nalgebra: wrong slice length` unless\n"
                     f"`data.len() == {s.n}`. Upstream: `{S}::from_iterator(iter)` (a `Span` of "
                     "exactly the length here).",
                     f"from_iterator(data: Span<T>) -> {T}",
                     f"        {S}Trait::from_column_slice(data)"))
    ms.append(method(f"The {s.kind} of the values of `data` in ROW-major order. Panics with "
                     "`nalgebra: wrong slice length` unless\n"
                     f"`data.len() == {s.n}`. Upstream: `{S}::from_row_iterator(iter)` (a `Span` "
                     "here).",
                     f"from_row_iterator(data: Span<T>) -> {T}",
                     f"        {S}Trait::from_row_slice(data)"))
    ms.append(method(f"The number of components, {s.n}. Upstream: `len`.",
                     f"len(self: {T}) -> usize", f"        {s.n}", "#[inline(always)]"))
    ms.append(method("`false`: a static shape has at least one component. Upstream: `is_empty`.",
                     f"is_empty(self: {T}) -> bool", "        false", "#[inline(always)]"))
    for name, args, call, what, target in (
        ("insert_columns", "i: usize, n: usize, val: T", "insert_columns(i, n, val)",
         "`self` with `n` columns of `val` inserted at index `i` (`i <= "
         f"{s.c}`; panics with `nalgebra: index out of bounds`\notherwise)", h),
        ("insert_rows", "i: usize, n: usize, val: T", "insert_rows(i, n, val)",
         f"`self` with `n` rows of `val` inserted at index `i` (`i <= {s.r}`; panics with "
         "`nalgebra: index out of bounds`\notherwise)", v),
        ("remove_columns", "i: usize, n: usize", "remove_columns(i, n)",
         f"`self` without the columns `i .. i + n` (`i + n <= {s.c}`; panics with `nalgebra: "
         "index out of bounds`\notherwise)", h),
        ("remove_rows", "i: usize, n: usize", "remove_rows(i, n)",
         f"`self` without the rows `i .. i + n` (`i + n <= {s.r}`; panics with `nalgebra: index "
         "out of bounds`\notherwise)", v),
        ("remove_columns_at", "indices: Span<usize>", "remove_columns_at(indices)",
         "`self` without the columns whose index is in `indices` (repeated or out of range "
         "indices are\nignored)", h),
        ("remove_rows_at", "indices: Span<usize>", "remove_rows_at(indices)",
         "`self` without the rows whose index is in `indices` (repeated or out of range indices "
         "are\nignored)", v),
        ("resize_horizontally", "new_ncols: usize, val: T", "resize_horizontally(new_ncols, val)",
         "`self` with `new_ncols` columns, the common columns kept, the new components `val`", h),
        ("resize_vertically", "new_nrows: usize, val: T", "resize_vertically(new_nrows, val)",
         "`self` with `new_nrows` rows, the common rows kept, the new components `val`", v),
    ):
        upstream_type = ("OMatrix<U1, Dyn>" if target == "RowDVector" and h == target else
                         "OMatrix<Dyn, U1>" if target == "DVector" else
                         f"OMatrix<U{s.r}, Dyn>" if target == h else f"OMatrix<Dyn, U{s.c}>")
        alias = {"RowDVector": "Matrix1xX", "DVector": "MatrixXx1"}.get(
            target, f"Matrix{s.r}xX" if target == h and name in (
                "insert_columns", "remove_columns", "remove_columns_at", "resize_horizontally")
            else f"MatrixXx{s.c}")
        ms.append(method(f"{what}, a `{alias}` (`{target}`). Upstream: `{name}` "
                         f"(`{upstream_type}`).",
                         f"{name}(self: {T}, {args}) -> {target}<T>",
                         f"        let d: {target}<T> = self.into();\n        d.{call}"))
    cols = [column_literal(s, j) for j in range(s.c)]
    V, RV = col(s.r).name, row(s.c).name
    rv = row(s.c)
    cv = col(s.c)
    closure = ("F, +Drop<F>, impl Func: core::ops::Fn<F, ({arg},)>, +Into<Func::Output, {out}>, "
               "+Drop<Func::Output>")
    ms.append(method(f"The row vector of `f(column)` for the {s.c} columns (a `{V}` each). `f`'s "
                     "output converts `Into<T>`.\nUpstream: `compress_rows` (`f` takes a column "
                     "view).",
                     f"compress_rows<{closure.format(arg=f'{V}<T>', out='T')}>(self: {T}, f: F) "
                     f"-> {RV}<T>",
                     "        " + rv.lit({rv.f(0, j): f"f({cols[j]}).into()" for j in range(s.c)}),
                     "#[cfg(feature: 'closures')]\n    #[inline]"))
    ms.append(method(f"The column vector of `f(column)` for the {s.c} columns. Upstream: "
                     "`compress_rows_tr`.",
                     f"compress_rows_tr<{closure.format(arg=f'{V}<T>', out='T')}>(self: {T}, "
                     f"f: F) -> {cv.name}<T>",
                     "        " + cv.lit({cv.f(j, 0): f"f({cols[j]}).into()" for j in range(s.c)}),
                     "#[cfg(feature: 'closures')]\n    #[inline]"))
    folds = "init"
    for j in range(s.c):
        folds = f"f({folds}, {cols[j]}).into()"
    ms.append(method("`init` folded with every column, `acc = f(acc, column)` from the first to "
                     "the last. `f`'s output\nconverts `Into<" + V + ">`. Upstream: "
                     "`compress_columns(init, f)` (`f` mutates `&mut acc`; Cairo closures\ntake "
                     "and return it by value).",
                     f"compress_columns<F, +Drop<F>, impl Func: core::ops::Fn<F, ({V}<T>, "
                     f"{V}<T>)>, +Into<Func::Output, {V}<T>>, +Drop<Func::Output>>(self: {T}, "
                     f"init: {V}<T>, f: F) -> {V}<T>",
                     f"        {folds}",
                     "#[cfg(feature: 'closures')]\n    #[inline]"))
    return (doc(f"The members of the static `{S}` that come with the dynamic matrices (DESIGN D5, "
                "feature `dynamic`):\nthe edition forms with a dynamic result, `from_vec`, "
                "`from_iterator`, `from_row_iterator`, `len`,\n`is_empty`, `compress_*`.") +
            f"#[generate_trait]\npub impl {S}DynamicImpl<{BOUNDS}> of {S}DynamicTrait<T> {{\n" +
            "\n".join(ms) + "}\n")


# --- the fixed-size edition forms on the `Matrix6` canvas -------------------------------------


def canvas_fields(pick) -> str:
    """A `Matrix6` literal whose component `(i, j)` is `pick(i, j)` (a canvas field or `val`)."""
    return "Matrix6 { " + ", ".join(f"{CANVAS.f(i, j)}: {pick(i, j)}"
                                    for j in range(6) for i in range(6)) + " }"


def canvas_kernel(kind: str, d: int) -> str:
    arms = []
    for p in range(0, 7 - d):
        if kind == "insert_columns":
            def pick(i, j, p=p):
                return f"m.{CANVAS.f(i, j)}" if j < p else "val" if j < p + d else \
                    f"m.{CANVAS.f(i, j - d)}"
        elif kind == "insert_rows":
            def pick(i, j, p=p):
                return f"m.{CANVAS.f(i, j)}" if i < p else "val" if i < p + d else \
                    f"m.{CANVAS.f(i - d, j)}"
        elif kind == "remove_columns":
            def pick(i, j, p=p):
                return f"m.{CANVAS.f(i, j)}" if j < p else f"m.{CANVAS.f(i, j + d)}" \
                    if j + d < 6 else "val"
        else:
            def pick(i, j, p=p):
                return f"m.{CANVAS.f(i, j)}" if i < p else f"m.{CANVAS.f(i + d, j)}" \
                    if i + d < 6 else "val"
        arms.append(f"{p} => {canvas_fields(pick)},")
    return (f"    #[inline(always)]\n    fn {kind}{d}(m: Matrix6<T>, i: usize, val: T) -> "
            f"Matrix6<T> {{\n        match i {{\n" + "\n".join(arms) +
            f"\n_ => core::panic_with_felt252({INDEX_ERROR}),\n}}\n    }}\n")


FIXED = {
    # trait: (method, upstream, kernel, doc)
    "InsertFixedColumns": ("insert_fixed_columns", "insert_columns",
                           "`D` columns of `val` inserted at index `i`", "i <= C"),
    "InsertFixedRows": ("insert_fixed_rows", "insert_rows",
                        "`D` rows of `val` inserted at index `i`", "i <= R"),
    "RemoveFixedColumns": ("remove_fixed_columns", "remove_columns",
                           "the columns `i .. i + D` removed", "i + D <= C"),
    "RemoveFixedRows": ("remove_fixed_rows", "remove_rows", "the rows `i .. i + D` removed",
                        "i + D <= R"),
}


def fixed_pairs(trait: str) -> list[tuple[Shape, Shape, int]]:
    out = []
    for s in ALL_SHAPES:
        for d in range(1, 6):
            if trait == "InsertFixedColumns" and s.c + d <= 6:
                out.append((s, Shape(s.r, s.c + d), d))
            if trait == "InsertFixedRows" and s.r + d <= 6:
                out.append((s, Shape(s.r + d, s.c), d))
            if trait == "RemoveFixedColumns" and s.c - d >= 1:
                out.append((s, Shape(s.r, s.c - d), d))
            if trait == "RemoveFixedRows" and s.r - d >= 1:
                out.append((s, Shape(s.r - d, s.c), d))
    return out


def fixed_impl(trait: str, s: Shape, o: Shape, d: int) -> str:
    fname, kernel, what, cond = FIXED[trait]
    limit = s.c if "Columns" in trait else s.r
    check = f"i > {limit}" if trait.startswith("Insert") else f"i + {d} > {limit}"
    if trait.startswith("Insert"):
        body = (f"if {check} {{\ncore::panic_with_felt252({INDEX_ERROR})\n}}\n"
                f"CropFrom6::crop(Canvas6Edit::{kernel}{d}(PadTo6::pad(self, val), i, val))")
        sig = f"fn {fname}(self: {s.name}<T>, i: usize, val: T) -> {o.name}<T>"
    else:
        first = s.fields[0]
        # The canvas components shifted in are cropped away: any component fills them.
        body = (f"if {check} {{\ncore::panic_with_felt252({INDEX_ERROR})\n}}\n"
                f"let val = self.{first};\n"
                f"CropFrom6::crop(Canvas6Edit::{kernel}{d}(PadTo6::pad(self, val), i, val))")
        sig = f"fn {fname}(self: {s.name}<T>, i: usize) -> {o.name}<T>"
    return (f"pub impl {s.name}{trait}{o.name}<T, +Copy<T>, +Drop<T>> of {trait}<{s.name}<T>, "
            f"{o.name}<T>, T> {{\n#[inline]\n{sig} {{\n{body}\n}}\n}}\n")


def fixed_traits() -> list[str]:
    out = []
    for trait, (fname, kernel, what, cond) in FIXED.items():
        insert = trait.startswith("Insert")
        axis = "columns" if "Columns" in trait else "rows"
        example = {"InsertFixedColumns": "Matrix3x5<Fixed>", "InsertFixedRows": "Matrix5x3<Fixed>",
                   "RemoveFixedColumns": "Matrix3x2<Fixed>",
                   "RemoveFixedRows": "Matrix2x3<Fixed>"}[trait]
        sig = (f"fn {fname}(self: M, i: usize, val: T) -> Out;" if insert else
               f"fn {fname}(self: M, i: usize) -> Out;")
        out.append(
            doc(f"`self` with {what} (`{cond}`, else panics with `nalgebra: index out of "
                f"bounds`), a static shape `Out` whose {axis[:-1]} count selects `D`. Upstream: "
                f"`{fname}::<D>(i{', val' if insert else ''})` (a const generic; the output type "
                f"here, inferred like `Into`'s: `let r: {example} = m.{fname}(i"
                f"{', v' if insert else ''});`).") +
            f"pub trait {trait}<M, Out, T> {{\n" +
            doc(f"`self` with {what}. Upstream: `{fname}::<D>`.", "    ") + f"    {sig}\n}}\n")
    return out


def render() -> str:
    parts = [HEADER + """//! What the 36 static shapes gain from the dynamic matrices (DESIGN D5, feature `dynamic`):
//! the conversions to `DMatrix` / `DVector` / `RowDVector`, the edition forms with a dynamic
//! result, `from_vec` / `from_iterator` / `from_row_iterator`, `len`, `is_empty`, `compress_*`
//! (`<S>DynamicTrait`), and the fixed-size edition forms whose result is another static shape
//! (`InsertFixedColumns`, `InsertFixedRows`, `RemoveFixedColumns`, `RemoveFixedRows`: the output
//! type selects upstream's const generic `D`, one impl per (shape, D) pair, on the `Matrix6`
//! canvas of `FixedResize`).

use simba::scalar::Real;
"""]
    uses = sorted({f"use {PATH}::{s.module}::{{{s.name}, {s.name}Trait}};" for s in ALL_SHAPES})
    uses.append(f"use {PATH}::errors;")
    uses.append(f"use {PATH}::matrix_view::{{CropFrom6, PadTo6}};")
    uses.append("use super::dmatrix::{DMatrix, DMatrixTrait};")
    uses.append("use super::dvector::{DVector, DVectorTrait};")
    uses.append("use super::row_dvector::{RowDVector, RowDVectorTrait};")
    parts.append("\n".join(sorted(uses)) + "\n")
    parts.extend(fixed_traits())
    kernels = []
    for kind in ("insert_columns", "insert_rows", "remove_columns", "remove_rows"):
        for d in range(1, 6):
            kernels.append(canvas_kernel(kind, d))
    parts.append(doc("The fixed-size edition kernels on the `Matrix6` canvas: `D` columns / rows "
                     "of `val` inserted at `i`, or\nthe columns / rows `i .. i + D` removed (the "
                     "canvas components shifted in are `val`, cropped\naway by the caller).") +
                 "trait Canvas6Edit<T> {\n" +
                 "".join(f"    fn {k}{d}(m: Matrix6<T>, i: usize, val: T) -> Matrix6<T>;\n"
                         for k in ("insert_columns", "insert_rows", "remove_columns",
                                   "remove_rows") for d in range(1, 6)) +
                 "}\n\nimpl Canvas6EditImpl<T, +Copy<T>, +Drop<T>> of Canvas6Edit<T> {\n" +
                 "\n".join(kernels) + "}\n")
    for s in ALL_SHAPES:
        parts.extend(conversions(s))
        parts.append(dynamic_trait(s))
        for trait in FIXED:
            for (src, o, d) in fixed_pairs(trait):
                if src == s:
                    parts.append(fixed_impl(trait, s, o, d))
    return "\n".join(parts)


