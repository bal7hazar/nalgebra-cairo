def new_methods(s: Shape) -> list[L.Fn]:
    S, T = s.name, f"{s.name}<T>"
    t = s.transposed()
    lit = lambda g: L.lit(S, [(k, g(k)) for k in s.fields])  # noqa: E731
    out = []
    order = "the given components" if s.is_vector else "the given components, in ROW-major order"
    args = ", ".join(f"{p}: T" for p in s.row_major)
    out.append(fn("new", f"The {s.kind} with {order}. Upstream: `{S}::new`.",
                  f"fn new({args}) -> {T}", L.lit(S, [(k, k) for k in s.fields])))
    out.append(fn("zeros", f"The zero {s.kind}. Upstream: `{S}::zeros`.", f"fn zeros() -> {T}",
                  lit(lambda k: "R::zero()")))
    if s.is_square:
        n = s.r
        v = Shape(n, 1)
        diag = lambda on: L.lit(S, [(s.f(i, j), on(i) if i == j else "R::zero()")  # noqa: E731
                                    for j in range(n) for i in range(n)])
        out.append(fn("identity", f"The identity matrix. Upstream: `{S}::identity`.",
                      f"fn identity() -> {T}", diag(lambda i: "R::one()")))
        out.append(fn("from_diagonal", f"The diagonal matrix `diag(d)`. Upstream: "
                                       f"`{S}::from_diagonal`.",
                      f"fn from_diagonal(d: {v.name}<T>) -> {T}", diag(lambda i: f"d.{v.f(i, 0)}")))
        out.append(fn("from_diagonal_element", f"The matrix `e * I`. Upstream: "
                                               f"`{S}::from_diagonal_element`.",
                      f"fn from_diagonal_element(e: T) -> {T}", diag(lambda i: "e")))
        out.append(fn("diagonal", f"The diagonal, a `{v.name}`. Upstream: `diagonal`.",
                      f"fn diagonal(self: {T}) -> {v.name}<T>",
                      L.lit(v.name, [(v.f(i, 0), f"self.{s.f(i, i)}") for i in range(n)])))
    out.append(fn("transpose", f"The transpose, a `{t.name}`. Exact. Upstream: `transpose`.",
                  f"fn transpose(self: {T}) -> {t.name}<T>",
                  L.lit(t.name, [(t.f(i, j), f"self.{s.f(j, i)}") for j in range(t.c)
                                 for i in range(t.r)])))
    if s.is_square:
        out.append(fn("trace", "Sum of the diagonal, left to right. Exact; panics on overflow. "
                               "Upstream: `trace`.", f"fn trace(self: {T}) -> T",
                      " + ".join(f"self.{s.f(i, i)}" for i in range(s.r))))
    out.append(fn("abs", "Component-wise absolute value. Exact; panics on overflow (`|MIN|`). "
                         "Upstream: `abs`.", f"fn abs(self: {T}) -> {T}",
                  lit(lambda k: f"R::abs(self.{k})")))
    out.append(fn("scale", "`self * k`, each component floored once. Panics on overflow. "
                           "Upstream: `scale` (`self * k`).", f"fn scale(self: {T}, k: T) -> {T}",
                  lit(lambda k: f"self.{k} * k")))
    if s.is_column:
        out.append(fn("lerp", "`self + (rhs - self) * t` per component (`Real::lerp`: exact "
                              "difference and product, one floor rounding). `t` is not clamped; "
                              "`t = 0` gives `self` and `t = 1` gives `rhs` exactly. Panics on "
                              "overflow of the result. Upstream: `lerp` "
                              "(`self * (1 - t) + rhs * t`).",
                      f"fn lerp(self: {T}, rhs: {T}, t: T) -> {T}",
                      lit(lambda k: f"R::lerp(self.{k}, rhs.{k}, t)")))
    if s.n == 1:
        for name, what in (("into_scalar", "Upstream: `into_scalar`."),
                           ("to_scalar", "Upstream: `to_scalar`."),
                           ("as_scalar", "Upstream: `as_scalar`, which returns `&T`: Cairo values "
                                         "are `Copy` and passed by value.")):
            out.append(fn(name, f"The single component `x`. {what}", f"fn {name}(self: {T}) -> T",
                          "self.x"))
    if s.is_square:
        out.append(fn("is_identity", "Whether every component is within `ulps` smallest units of "
                                     "the identity's. Upstream: `is_identity(eps)`, with the "
                                     "tolerance in raw units instead of a float epsilon.",
                      f"fn is_identity(self: {T}, ulps: u64) -> bool",
                      "\n&& ".join(f"R::abs_diff_eq(self.{s.f(i, j)}, "
                                   f"{'R::one()' if i == j else 'R::zero()'}, ulps)"
                                   for j in range(s.c) for i in range(s.r))))
    out.append(fn("abs_diff_eq", "Whether every component of `self` is within `ulps` smallest "
                                 "units (raw units for fixed point) of `other`'s; cannot "
                                 "overflow. Upstream: `approx::AbsDiffEq::abs_diff_eq`, the "
                                 "tolerance being counted in ulp instead of a float epsilon "
                                 "(DESIGN D3).",
                  f"fn abs_diff_eq(self: {T}, other: {T}, ulps: u64) -> bool",
                  "\n&& ".join(f"R::abs_diff_eq(self.{k}, other.{k}, ulps)" for k in s.fields)))
    return out


def new_operators(s: Shape) -> list[str]:
    S, T = s.name, f"{s.name}<T>"
    lit = lambda g: L.lit(S, [(k, g(k)) for k in s.fields])  # noqa: E731
    out = [L.section("operators", 100)]
    for trait, op, verb in (("Add", "+", "add"), ("Sub", "-", "sub")):
        out.append(item(f"`lhs {op} rhs`, component-wise. Exact; panics on overflow. Upstream: "
                        f"`{trait}`.",
                        f"pub impl {S}{trait}<T, +{trait}<T>, +Copy<T>, +Drop<T>> of "
                        f"{trait}<{T}> {{\n{L.INLINE}\nfn {verb}(lhs: {T}, rhs: {T}) -> {T} {{\n"
                        f"{lit(lambda k: f'lhs.{k} {op} rhs.{k}')}\n}}\n}}"))
    out.append(item("`-a`, component-wise. Exact; panics on overflow (`-MIN`). Upstream: `Neg`.",
                    f"pub impl {S}Neg<T, +Neg<T>, +Copy<T>, +Drop<T>> of Neg<{T}> {{\n"
                    f"{L.INLINE}\nfn neg(a: {T}) -> {T} {{\n{lit(lambda k: f'-a.{k}')}\n}}\n}}"))
    for trait, op, verb in (("Add", "+", "add"), ("Sub", "-", "sub")):
        out.append(item(f"`self {op}= rhs`. Exact; panics on overflow. Upstream: `{trait}Assign`.",
                        f"pub impl {S}{trait}Assign<T, +{trait}<T>, +Copy<T>, +Drop<T>> of "
                        f"{trait}Assign<{T}, {T}> {{\n{L.INLINE}\n"
                        f"fn {verb}_assign(ref self: {T}, rhs: {T}) {{\nself = self {op} rhs;\n}}"
                        f"\n}}"))
    if s.is_square:
        n = s.r
        wide = n >= 5
        body = L.lit(S, [(s.f(i, j), kernel([(f"lhs.{s.f(i, q)}", f"rhs.{s.f(q, j)}")
                                             for q in range(n)], False))
                         for j in range(n) for i in range(n)])
        inline = f"{L.INLINE}\n" if product_inline(s) else ""
        real = "impl R: Real<T>, +Mul<T>, +Copy<T>, +Drop<T>" + (", +Drop<R::Wide>" if wide
                                                                  else "")
        out.append(item(f"`a * b` (matrix product): {kernel_note(n)}. Panics on overflow. "
                        f"Upstream: `Mul`.",
                        f"pub impl {S}Mul<T, {real}> of Mul<{T}> {{\n{inline}"
                        f"fn mul(lhs: {T}, rhs: {T}) -> {T} {{\n{body}\n}}\n}}"))
        out.append(item("`a *= b` (matrix product, `a = a * b`). Upstream: `MulAssign`.",
                        f"pub impl {S}MulAssign<T, {real}> of MulAssign<{T}, {T}> {{\n"
                        f"{L.INLINE}\nfn mul_assign(ref self: {T}, rhs: {T}) {{\n"
                        f"self = self * rhs;\n}}\n}}"))
    if s.is_vector:
        n = s.n
        comps = s.fields
        arr = f"[{', '.join(comps)}]"
        out.append(item(f"`{arr}.into()`. Upstream: `From<[T; {n}]>`.",
                        f"pub impl {S}FromArray<T> of Into<[T; {n}], {T}> {{\n{L.INLINE}\n"
                        f"fn into(self: [T; {n}]) -> {T} {{\nlet {arr} = self;\n"
                        f"{L.lit(S, [(c, c) for c in comps])}\n}}\n}}"))
        out.append(item(f"The components as a fixed-size array `{arr}`. Upstream: "
                        f"`Into<[T; {n}]>`.",
                        f"pub impl {S}IntoArray<T> of Into<{T}, [T; {n}]> {{\n{L.INLINE}\n"
                        f"fn into(self: {T}) -> [T; {n}] {{\n"
                        f"let {L.lit(S, [(c, c) for c in comps])} = self;\n{arr}\n}}\n}}"))
    return out


def render_new(s: Shape) -> str:
    S = s.name
    t = s.transposed()
    uses = ["core::ops::{AddAssign, DivAssign, MulAssign, SubAssign}",
            "simba::scalar::{Real, Transcendental}"]
    if t != s:
        uses.append(use_of(t))
    if s.is_square and s.r > 1:
        uses.append(use_of(Shape(s.r, 1)))
    if s.is_square and s.r >= 5:
        uses.append("super::kernels::Fused")
    au, ai = aliases(s)
    pu, pi = products(s, {})
    uses = [u for u in L.dedup(uses + au + pu + C.uses(s)) if u != use_of(s)]
    ops = "`+`, `-`, unary `-`" + (", `*` between matrices" if s.is_square else "")
    conv = f", conversions from / to `[T; {s.n}]`" if s.is_vector else ""
    module_doc = wrap(
        f"`{S}`: a statically sized {s.kind} (upstream `nalgebra::{S}`).\n\n"
        f"Every sum of products goes through a fused `Real` kernel: one rounding (floor) and one "
        f"overflow check per output scalar. Operators ({ops} and their assigning forms{conv}) "
        f"are implemented in this module, so they need no import; the other operations are "
        f"methods of `{S}Trait`, the products with every conformable shape `MatrixMul::mul_mat` "
        f"(`self * rhs`) and `MatrixTrMul::tr_mul` (`selfᵀ * rhs`).")
    module_doc = "\n".join(f"//! {line}" if line else "//!" for line in module_doc.split("\n"))
    if s.is_vector:
        layout = "Components are named like upstream's `Deref` targets (`x, y, z, w, a, b`)."
    else:
        layout = ("`mRC` is the component at row `R`, column `C`.\n\nFields are declared in "
                  "column-major order, so `Serde` matches upstream's storage order, while `new` "
                  "takes its arguments in row-major order like upstream.")
    struct = item(f"A {s.kind}. {layout}",
                  "#[derive(Copy, Drop, PartialEq, Serde, Default, Debug, Hash)]\n"
                  f"pub struct {S}<T> {{\n" + "\n".join(f"pub {k}: T," for k in s.fields) + "\n}")
    base = new_methods(s)
    fns = base + C.missing(s, {m.name for m in base})
    methods = "\n\n".join(m.definition() for m in fns)
    impl = (f"/// Methods of `{S}<T>` for any `Real` scalar.\n#[generate_trait]\n"
            f"pub impl {S}Impl<\n{L.bounds(L.MATRIX_IMPL_BOUNDS)}\n> of {S}Trait<T> {{\n"
            f"{methods}\n}}")
    blocks = [module_doc, "\n".join(f"use {u};" for u in uses), struct] + ai + [impl]
    blocks.append(C.angle_impl(s, C.angle_methods(s)))
    blocks += new_operators(s) + [L.section("products", 100)] + pi + C.items(s)
    return HEADER + "\n\n".join(blocks) + "\n"


def render(s: Shape) -> str:
    """The library file of any of the 36 shapes."""
    if s in LEGACY:
        module = L.LIBRARY_SHAPES[(s.r, s.c)]
        return L.render((s.r, s.c), extra=legacy_extra(s, L.read_specs(module).docs))
    return render_new(s)


