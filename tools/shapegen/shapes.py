"""Templates of the 36 static shapes of `crates/nalgebra` (WP 8.1b-3, `DESIGN.md` §2.5).

The 8 shapes written by hand before WP 8.1b (`Vector2/3/4/6`, `Matrix2/3/4/6`) keep their
templates in `library.py` (bit- and gas-identical to the hand-written kernels); this module adds
to them, and gives the 28 other shapes (`Matrix1`, `Matrix5`, `Vector5`, `RowVector2..6` and the
20 `MatrixRxC`, R != C) their whole file:

* the upstream aliases of every shape as Cairo `type` aliases (`Matrix3x1 = Vector3`,
  `Matrix1x3 = RowVector3`, `Vector1` / `RowVector1` = `Matrix1`, `UnitVectorN = Unit<VectorN>`);
* the conformable products, one impl per pair, in the file of the left operand:
  `MatrixMul::mul_mat` (`self * rhs`, 216 impls) and `MatrixTrMul::tr_mul` (`selfᵀ * rhs`,
  216 impls). Cairo's `Mul` is homogeneous, so `*` / `*=` exist on the square shapes only, and
  the square `mul_mat` delegates to `*`;
* for the 28 new shapes, the surface upstream's `Matrix` / `SquareMatrix` / `Vector` /
  `RowSVector` items that nalgebra.cairo ports on the former shapes require on every shape
  (`scripts/api_parity.py`, `OWNER_CANDIDATES` / `DIM_ONLY`): `new`, `zeros`, `transpose`,
  `abs`, `scale`, `abs_diff_eq`, `+ - -x += -=`; on squares `identity`, `from_diagonal`,
  `from_diagonal_element`, `diagonal`, `trace`, `is_identity`, `* *=`; on column vectors `lerp`;
  on vectors the `[T; N]` conversions; on `Matrix1` `into_scalar` / `to_scalar` / `as_scalar`.
  The rest of the upstream surface (norms, component-wise operations, views...) comes with WP
  8.2 on every shape at once.

Kernels (AGENTS.md rule 4): each output scalar of a product is ONE fused sum of products,
`a * b` for one term, `Real::sum_prodK` for 2-4 terms, and for 5-6 terms the private
`#[inline(always)]` helpers `Fused::sum_prod5/6` of `base/kernels.cairo` (one `Real::Wide` chain,
rescaled once; same Sierra as the chain written in place, `DESIGN.md` §2), except the products
that existed on `Matrix6` before, which keep their nested chain verbatim (`LEGACY_WIDE`).
Inlining reproduces the measured rule of the former shapes: `#[inline(always)]` when the output
is a vector of at most 4 components, the default otherwise.
"""

import re
import textwrap

import completion as C
import library as L
from model import ALL_SHAPES, Shape

LEGACY = {Shape(r, c) for (r, c) in L.LIBRARY_SHAPES}
NEW = [s for s in ALL_SHAPES if s not in LEGACY]

HEADER = ("// Generated by tools/shapegen/shapegen.py: do not edit by hand. Template:\n"
          "// tools/shapegen/shapes.py.\n")

# The products the hand-written `Matrix6` had (`*`, `mul_vec`): their 6-term sums stay ONE nested
# `Real::Wide` expression each, as measured (`matrix6.cairo`). (`tr_mul` is `mul_mat` of the
# transposed fields, so the former `tr_mul` / `tr_mul_vec` of `Matrix6` get the same chains.)
LEGACY_WIDE = {("mul", Shape(6, 6), Shape(6, 1))}

BOUNDS = "T, impl R: Real<T>, +Mul<T>, +Copy<T>, +Drop<T>, +Drop<R::Wide>"


def wrap(text: str, indent: int = 0) -> str:
    """A doc comment of `text` (paragraphs separated by blank lines), wrapped at 100 columns
    once indented by `indent` (`scarb fmt` never re-wraps comments)."""
    width = 100 - indent - 4
    paras = [textwrap.fill(p, width, break_long_words=False, break_on_hyphens=False)
             for p in text.strip().split("\n\n")]
    return "\n\n".join(paras)


def fn(name: str, doc: str, sig: str, body: str, inline: bool = True) -> L.Fn:
    return L.Fn(name, wrap(doc, 4), sig, body, inline)


def item(doc: str, code: str) -> str:
    return "\n".join(f"/// {line}" if line else "///"
                     for line in wrap(doc).split("\n")) + "\n" + code


def use_of(s: Shape) -> str:
    return f"super::{s.module}::{s.name}"


# --------------------------------------------------------------------------------------------
# Products
# --------------------------------------------------------------------------------------------


def kernel(pairs: list[tuple[str, str]], legacy_wide: bool) -> str:
    """ONE fused sum of products (one floor, one overflow check)."""
    k = len(pairs)
    if k == 1:
        return f"{pairs[0][0]} * {pairs[0][1]}"
    args = ", ".join(f"{a}, {b}" for a, b in pairs)
    if k <= 4:
        return f"R::sum_prod{k}({args})"
    if legacy_wide:
        return L.wide_expr(pairs)
    return f"Fused::sum_prod{k}({args})"


def kernel_note(k: int) -> str:
    if k == 1:
        return "one floored product per component"
    if k <= 4:
        return f"one `sum_prod{k}` per component (one rounding each)"
    return (f"the {k} products of each component accumulated exactly in `Real::Wide` and "
            f"rescaled once")


def product_inline(out: Shape) -> bool:
    """`#[inline(always)]` for vector outputs of at most 4 components (the former
    `Matrix2/3/4::mul_vec` / `tr_mul_vec`), the default for the others (matrix products,
    `Matrix6 * Vector6`), as measured on the hand-written shapes."""
    return out.is_vector and out.n <= 4


def products(s: Shape, docs: dict[str, str]) -> tuple[list[str], list[str]]:
    """`(uses, items)`: the `MatrixMul` and `MatrixTrMul` impls whose left operand is `s`.
    `docs`: `// @doc mul_mat <Rhs>` / `// @doc tr_mul <Rhs>` sections replacing a doc comment."""
    uses, items = [], []
    A = s.name
    for op in ("mul", "tr_mul"):
        for b in ALL_SHAPES:
            if (op == "mul" and b.r != s.c) or (op == "tr_mul" and b.r != s.r):
                continue
            o = Shape(s.r, b.c) if op == "mul" else Shape(s.c, b.c)
            k = s.c if op == "mul" else s.r
            B, O = b.name, o.name
            uses += [use_of(t) for t in (b, o) if t != s]
            wide = (op, s, b) in LEGACY_WIDE
            inline = "#[inline(always)]\n" if product_inline(o) else ""
            if op == "mul":
                uses.append("super::matrix_mul::MatrixMul")
                name, trait, method = f"{A}Mul{B}", "MatrixMul", "mul_mat"
                key = f"mul_mat {B}"
                if s == b:
                    doc = ("`self * rhs` through `MatrixMul`: the `*` operator (same kernel, same "
                           "gas), for code written over every conformable shape. Upstream: `Mul`.")
                    body, inline = "self * rhs", "#[inline(always)]\n"
                else:
                    if k >= 5 and not wide:
                        uses.append("super::kernels::Fused")
                    doc = (f"`self * rhs`, a `{O}`: {kernel_note(k)}. Panics on overflow. "
                           f"Upstream: `{A} * {B}` (`Mul`).")
                    values = {o.f(i, j): kernel([(f"self.{s.f(i, q)}", f"rhs.{b.f(q, j)}")
                                                 for q in range(k)], wide)
                              for i in range(o.r) for j in range(o.c)}
                    body = L.lit(O, [(fld, values[fld]) for fld in o.fields])
            else:
                # `mul_mat` of the transposed fields: the transpose only relabels values, so this
                # is the gas of a fused `selfᵀ * rhs` kernel (measured: `bench_matrix*_tr_mul*`,
                # `bench_*_tr_mul_*__alt_transpose_then_mul_mat`) for half the library code.
                t = s.transposed()
                uses += ["super::matrix_tr_mul::MatrixTrMul", "super::matrix_mul::MatrixMul"]
                uses += [use_of(t)] if t != s else []
                name, trait, method = f"{A}TrMul{B}", "MatrixTrMul", "tr_mul"
                key = f"tr_mul {B}"
                doc = (f"`selfᵀ * rhs`, a `{O}`: `mul_mat` of the transposed components, so "
                       f"{kernel_note(k)}; bit-identical to `self.transpose().mul_mat(rhs)`, at "
                       f"the same gas (the transpose only relabels values). Panics on overflow. "
                       f"Upstream: `tr_mul`.")
                tl = L.lit(t.name, [(t.f(i, j), f"self.{s.f(j, i)}") for j in range(t.c)
                                    for i in range(t.r)])
                body, inline = f"MatrixMul::mul_mat({tl}, rhs)", "#[inline(always)]\n"
            code = (f"pub impl {name}<{BOUNDS}> of {trait}<{A}<T>, {B}<T>> {{\n"
                    f"type Output = {O}<T>;\n{inline}"
                    f"fn {method}(self: {A}<T>, rhs: {B}<T>) -> {O}<T> {{\n{body}\n}}\n}}")
            items.append(f"{docs[key]}\n{code}" if key in docs else item(doc, code))
    return uses, items


