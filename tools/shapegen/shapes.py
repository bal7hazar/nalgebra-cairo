def render_matrix_mul() -> str:
    return HEADER + """//! `MatrixMul`: the product of two matrices of any conformable shapes.
//!
//! Upstream multiplies any `Matrix<R1, C1>` by any `Matrix<C1, C2>` with `*`. Cairo's `Mul` is
//! homogeneous (`fn mul(lhs: T, rhs: T) -> T`), so `*` only covers the square products
//! (`Matrix3 * Matrix3`); every conformable product, square ones and `M * v` included, is
//! `lhs.mul_mat(rhs)`, the output shape being the impl's associated `Output`. The impls (one per
//! conformable pair of the 36 static shapes, 216) live in the module of the left operand.

/// `lhs * rhs` for conformable shapes (`Matrix2x3 * Matrix3x4 -> Matrix2x4`, `Matrix3 * Vector3
/// -> Vector3`). Every component of the result is ONE fused sum of products (one floor rounding,
/// one overflow check). Upstream: `Mul<Matrix<C1, C2>> for Matrix<R1, C1>`.
pub trait MatrixMul<Lhs, Rhs> {
    /// The shape of `lhs * rhs`.
    type Output;
    /// `self * rhs`.
    fn mul_mat(self: Lhs, rhs: Rhs) -> Self::Output;
}
"""


def render_matrix_tr_mul() -> str:
    return HEADER + """//! `MatrixTrMul`: `lhsᵀ * rhs` for any shapes with the same number of rows.
//!
//! Upstream's `tr_mul` takes any right-hand matrix with as many rows as `self`; Cairo has no
//! overloading, so the method is the one of a trait generic over both operands, with the output
//! shape as the impl's associated `Output`. The impls (one per pair of the 36 static shapes with
//! the same number of rows, 216) live in the module of the left operand.

/// `lhsᵀ * rhs` without forming the transpose (`Matrix3x2ᵀ * Vector3 -> Vector2`). Every component
/// of the result is ONE fused sum of products (one floor rounding, one overflow check), so it is
/// bit-identical to `lhs.transpose().mul_mat(rhs)`. Upstream: `Matrix::tr_mul`.
pub trait MatrixTrMul<Lhs, Rhs> {
    /// The shape of `lhsᵀ * rhs`.
    type Output;
    /// `selfᵀ * rhs`.
    fn tr_mul(self: Lhs, rhs: Rhs) -> Self::Output;
    /// `selfᴴ * rhs`, the adjoint (conjugate transpose) times `rhs`: `tr_mul` for a real scalar.
    /// Upstream: `ad_mul`.
    #[inline(always)]
    fn ad_mul(self: Lhs, rhs: Rhs) -> Self::Output {
        Self::tr_mul(self, rhs)
    }
}
"""


def render_kernels() -> str:
    def fused(n: int) -> str:
        params = ", ".join(f"a{i}: T, b{i}: T" for i in range(n))
        expr = L.wide_expr([(f"a{i}", f"b{i}") for i in range(n)])
        return (f"/// `a0 * b0 + .. + a{n - 1} * b{n - 1}`: the exact sum in `Real::Wide`, floored "
                f"once.\n#[inline(always)]\nfn sum_prod{n}({params}) -> T {{\n{expr}\n}}")
    return HEADER + f"""//! Private fused kernels of the generated shapes: the 5- and 6-term sums of products that
//! `simba::Real` does not provide (it stops at `sum_prod4`), as ONE `Real::Wide` chain each.
//! `#[inline(always)]`: after inlining, a call is the same Sierra as the chain written in place
//! (measured equal gas, `tools/shapegen/DESIGN.md` §2).

use simba::scalar::Real;

/// Sums of 5 and 6 products with one rounding.
#[generate_trait]
pub(crate) impl Fused<T, impl R: Real<T>, +Drop<T>, +Drop<R::Wide>> of FusedTrait<T> {{
{fused(5)}

{fused(6)}
}}

/// `x^p` for a runtime exponent (`lp_norm`): exponentiation by squaring, each product floored.
#[generate_trait]
pub(crate) impl Powi<T, impl R: Real<T>, +Mul<T>, +Copy<T>, +Drop<T>> of PowiTrait<T> {{
    /// `x^p`, `x^0 = 1`: `⌊log2 p⌋` squarings and one product per set bit of `p` (the loop runs
    /// on the bits of the runtime `p`), each floored. Panics on overflow.
    fn powi(x: T, p: u32) -> T {{
        let mut acc = R::one();
        let mut base = x;
        let mut e = p;
        while e != 0 {{
            let (q, r) = DivRem::div_rem(e, 2);
            if r == 1 {{
                acc = acc * base;
            }}
            e = q;
            if e != 0 {{
                base = base * base;
            }}
        }}
        acc
    }}
}}
"""


