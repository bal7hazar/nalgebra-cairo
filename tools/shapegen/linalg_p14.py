def permute_body(n: int, s: Shape, rows: bool, inverse: bool) -> str:
    """Destructure `rhs`, replay the conditional transpositions of `PermN`, rebuild."""
    lines = [f"let mut a{i}{j} = rhs.{s.f(i, j)};" for j in range(s.c) for i in range(s.r)]
    steps = list(range(n - 1))
    if inverse:
        steps.reverse()
    for k in steps:
        branches = []
        for t in range(k + 1, n):
            swaps = []
            for q in range(s.c if rows else s.r):
                a, b = (f"a{k}{q}", f"a{t}{q}") if rows else (f"a{q}{k}", f"a{q}{t}")
                swaps.append(f"let tmp = {a};\n{a} = {b};\n{b} = tmp;")
            branches.append(f"if self.p{k + 1} == {t + 1} {{\n" + "\n".join(swaps) + "\n}")
        lines.append(" else ".join(branches))
    lines.append("rhs = " + lit(s, lambda i, j: f"a{i}{j}") + ";")
    return "\n".join(lines)


