"""Templates of the statistics of the static shapes (WP 8.3, API_PARITY package P06, first half):
upstream `src/base/statistics.rs` on the 36 shapes, written into ONE shared module,
`crates/nalgebra/src/base/statistics.cairo` (upstream's file), as one `#[generate_trait]` per
shape, `{S}StatisticsTrait` (any `Real` scalar):

* `sum`, `product`, `mean`, `variance` of all the components (column-major order, upstream's
  `iter()`); `sum` of `Vector2/3/4/6` predates this module and stays in their `VectorNTrait`
  (same kernel), so their statistics trait has no second `sum`;
* per column (upstream's `compress_rows`): `row_sum`, `row_product`, `row_mean`, `row_variance`
  (a `RowVectorC`) and their `_tr` forms (the same values as a `VectorC`);
* per row (upstream's `compress_columns`): `column_sum`, `column_product`, `column_mean`,
  `column_variance` (a `VectorR`).

Numerics (upstream's results, the project's rounding):

* sums are exact (`fixed` addition), left to right in upstream's order (an intermediate overflow
  panics, like the final one);
* products: one floored product per step, left to right (upstream's fold from `1`, whose first
  step `1 * x` is exact);
* `mean`: the exact sum divided by the count, correctly rounded (`Real::div`; the per-column /
  per-row forms divide several sums by ONE prepared divisor, `Real::divN` in the fewest chunks,
  bit-identical to `/`); a count of 1 divides by nothing (`x / 1 = x` exactly);
* `variance`: upstream's two-pass formula `sum((x - mean)^2) / n`, the mean correctly rounded,
  the differences exact, their squares summed exactly and floored ONCE (`Real::norm_squaredK`, a
  `Real::Wide` chain above 4 terms), then divided by `n` correctly rounded (two roundings where
  f64 has one per operation; `simba::Real` has no division of a wide accumulator);
* `column_mean` / `column_variance` are the `mean` / `variance` of each row: upstream computes
  them as `sum(x / n)` and `sum(x^2 / n) - mean^2` (the same values mathematically), whose
  reciprocal and one-pass cancellation would cost several ulp in fixed point.
"""

import library as L
from completion import div_chunks, fn, item
from model import ALL_SHAPES, Shape

HEADER = ("// Generated by tools/shapegen/shapegen.py: do not edit by hand. Template:\n"
          "// tools/shapegen/stats.py.\n")
BOUNDS = ["T", "impl R: Real<T>", "+Copy<T>", "+Drop<T>", "+Drop<R::Wide>", "+Add<T>", "+Sub<T>",
          "+Mul<T>"]
# `sum` already in the explicit `VectorNTrait` of the hand-written vectors (`library.py`).
HAS_SUM = {Shape(2, 1), Shape(3, 1), Shape(4, 1), Shape(6, 1)}


# --------------------------------------------------------------------------------------------
# Kernels
# --------------------------------------------------------------------------------------------


def infix(op: str, xs: list[str]) -> str:
    """`((x0 op x1) op x2) ..`: upstream's left fold."""
    return f" {op} ".join(xs)


def sum_of_squares(ds: list[str]) -> str:
    """`sum(d^2)` of the (bound, exact) differences `ds`, floored once."""
    k = len(ds)
    if k == 1:
        return f"{ds[0]} * {ds[0]}"
    if k <= 4:
        return f"R::norm_squared{k}({', '.join(ds)})"
    acc = "R::wide_zero()"
    for d in ds:
        acc = f"R::wide_add_prod({acc}, {d}, {d})"
    return f"R::wide_rescale({acc})"


def divide(names: list[str], xs: list[str], d: str) -> list[str]:
    """`let` statements binding `names` to `xs / d`, correctly rounded, ONE prepared divisor per
    chunk (`Real::divN`, bit-identical to `Real::div`)."""
    lines, i = [], 0
    for k in div_chunks(len(xs)):
        ns, vs = names[i:i + k], xs[i:i + k]
        i += k
        if k == 1:
            lines.append(f"let {ns[0]} = R::div({vs[0]}, {d});")
        else:
            lines.append(f"let ({', '.join(ns)}) = R::div{k}({', '.join(vs)}, {d});")
    return lines


def means(groups: list[list[str]], prefix: str) -> list[str]:
    """`let` statements binding `{prefix}{g}` to the mean of each group (same count)."""
    n = len(groups[0])
    sums = [infix("+", g) for g in groups]
    names = [f"{prefix}{g}" for g in range(len(groups))]
    if n == 1:
        return [f"let {nm} = {s};" for nm, s in zip(names, sums)]
    return [f"let n = R::from_int({n});"] + divide(names, sums, "n")


def variances(groups: list[list[str]]) -> list[str]:
    """`let v{g}` = the variance of each group (same count), upstream's two-pass formula."""
    n = len(groups[0])
    if n == 1:
        return [f"let v{g} = R::zero();" for g in range(len(groups))]
    lines = means(groups, "m")
    for g, xs in enumerate(groups):
        ds = [f"d{k}" for k in range(n)]
        body = [f"let d{k} = {x} - m{g};" for k, x in enumerate(xs)]
        lines.append(f"let s{g} = {{\n" + "\n".join(body) + f"\n{sum_of_squares(ds)}\n}};")
    return lines + divide([f"v{g}" for g in range(len(groups))],
                          [f"s{g}" for g in range(len(groups))], "n")


# --------------------------------------------------------------------------------------------
# Methods
# --------------------------------------------------------------------------------------------


def tail(lines: list[str], var: str) -> str:
    """The body `lines; var`, the last `let var = e;` returned directly as `e`."""
    head = f"let {var} = "
    if lines and lines[-1].startswith(head):
        return "\n".join(lines[:-1] + [lines[-1][len(head):].rstrip(";")])
    return "\n".join(lines + [var])


def row(n: int) -> Shape:
    return Shape(1, n)


def col(n: int) -> Shape:
    return Shape(n, 1)


def methods(s: Shape) -> list[L.Fn]:
    R_, C_, S, T = s.r, s.c, s.name, f"{s.name}<T>"
    xs = [f"self.{f}" for f in s.fields]
    cols = [[f"self.{s.f(i, j)}" for i in range(R_)] for j in range(C_)]
    rows = [[f"self.{s.f(i, j)}" for j in range(C_)] for i in range(R_)]
    RV, CV, RT = row(C_), col(R_), col(C_)
    small = s.n <= 4
    unused = [] if s.n > 1 else ["let _ = self;"]
    out: list[L.Fn] = []

    def lit(shape: Shape, values: list[str]) -> str:
        fields = [shape.f(0, k) if shape.r == 1 else shape.f(k, 0) for k in range(len(values))]
        return L.lit(shape.name, list(zip(fields, values)))

    if s not in HAS_SUM:
        out.append(fn("sum", "The sum of all the components, left to right in column-major order "
                      "(upstream's iteration order), exact. Panics on overflow (of any partial "
                      "sum). Upstream: `sum`.",
                      f"fn sum(self: {T}) -> T", infix("+", xs)))
    out.append(fn("product", "The product of all the components, left to right in column-major "
                  "order (upstream's fold), each product floored. Panics on overflow. Upstream: "
                  "`product`.", f"fn product(self: {T}) -> T", infix("*", xs), inline=s.n <= 16))
    mean_doc = ("The mean of all the components: their exact sum divided by "
                f"{s.n}, correctly rounded (to nearest, ties to even, like `f64 /`)"
                + ("; the component itself for a 1x1 matrix" if s.n == 1 else "")
                + ". Panics if the sum overflows. Upstream: `mean`.")
    out.append(fn("mean", mean_doc, f"fn mean(self: {T}) -> T",
                  tail(means([xs], "m"), "m0"), inline=small))
    var_doc = ("The population variance of all the components, upstream's two-pass formula "
               "`sum((x - mean)^2) / n`: the mean correctly rounded, the differences exact, their "
               "squares summed exactly and floored once, the quotient by "
               f"{s.n} correctly rounded"
               + (" (zero for a 1x1 matrix)" if s.n == 1 else "")
               + ". Panics on overflow. Upstream: `variance`.")
    out.append(fn("variance", var_doc, f"fn variance(self: {T}) -> T",
                  tail(unused + variances([xs]), "v0"), inline=small))

    # Per column (`compress_rows`) and per row (`compress_columns`).
    def per_group(name: str, groups: list[list[str]], shape: Shape, what: str, count: int,
                  kind: str) -> L.Fn:
        g = len(groups)
        if kind == "sum":
            body = lit(shape, [infix("+", x) for x in groups])
            doc = (f"The sum of each {what}, exact, left to right. Panics on overflow. Upstream: "
                   f"`{name}`.")
        elif kind == "product":
            body = lit(shape, [infix("*", x) for x in groups])
            doc = (f"The product of each {what}, left to right, each product floored. Panics on "
                   f"overflow. Upstream: `{name}`.")
        elif kind == "mean":
            body = "\n".join(means(groups, "m") + [lit(shape, [f"m{k}" for k in range(g)])])
            doc = (f"The mean of each {what}: its exact sum divided by {count}, correctly rounded"
                   + (" (one prepared divisor for all, `Real::divN`, bit-identical to `/`)"
                      if count > 1 and g > 2 else "") + ". Panics if a sum overflows. Upstream: "
                   f"`{name}`" + (" (computed as `sum(x / n)`: the same value mathematically, "
                                  "without the rounded reciprocal)" if name == "column_mean" else "")
                   + ".")
        else:
            body = "\n".join((unused if count == 1 else []) + variances(groups)
                             + [lit(shape, [f"v{k}" for k in range(g)])])
            doc = (f"The population variance of each {what}, upstream's two-pass formula "
                   f"`sum((x - mean)^2) / {count}` (see `variance`: mean and quotient correctly "
                   "rounded, squares summed exactly and floored once). Panics on overflow. "
                   f"Upstream: `{name}`" + (" (computed there as `sum(x^2 / n) - mean^2`: the same "
                                            "value mathematically, whose cancellation would cost "
                                            "several ulp in fixed point)"
                                            if name == "column_variance" else "") + ".")
        return fn(name, doc, f"fn {name}(self: {T}) -> {shape.name}<T>", body,
                  inline=small and kind in ("sum", "product"))

    for kind in ("sum", "product", "mean", "variance"):
        out.append(per_group(f"row_{kind}", cols, RV, "column", R_, kind))
        if C_ == 1:
            tr_body = f"Self::row_{kind}(self)"
        else:
            tr_body = (f"let r = Self::row_{kind}(self);\n"
                       + L.lit(RT.name, [(RT.f(k, 0), f"r.{RV.f(0, k)}") for k in range(C_)]))
        out.append(fn(f"row_{kind}_tr",
                      f"`row_{kind}` as a column vector (the same values, bit-identical). "
                      f"Upstream: `row_{kind}_tr`.",
                      f"fn row_{kind}_tr(self: {T}) -> {RT.name}<T>", tr_body))
        out.append(per_group(f"column_{kind}", rows, CV, "row", C_, kind))
    return out


# --------------------------------------------------------------------------------------------
# Module
# --------------------------------------------------------------------------------------------


def trait_name(s: Shape) -> str:
    return f"{s.name}StatisticsTrait"


def render_statistics() -> str:
    uses = ["simba::scalar::Real"] + [f"super::{s.module}::{s.name}" for s in ALL_SHAPES]
    blocks = []
    for s in ALL_SHAPES:
        blocks.append(
            item(f"The statistics of `{s.name}<T>` (upstream `base/statistics.rs`): sums, products, "
                 "means and variances of all the components, of each column (`row_*`, `row_*_tr`) "
                 "and of each row (`column_*`). By value, unrolled, no loop.",
                 "#[generate_trait]\n")
            + f"pub impl {s.name}StatisticsImpl<\n{L.bounds(BOUNDS)}\n> of {trait_name(s)}<T> {{\n"
            + "\n\n".join(x.definition() for x in methods(s)) + "\n}")
    doc = ("//! Statistics of the static shapes (upstream `nalgebra::base::statistics`,\n"
           "//! `src/base/statistics.rs`): `sum`, `product`, `mean`, `variance` of all the "
           "components, of\n//! each column (`row_*`: a row vector, `row_*_tr`: the same values as "
           "a column vector) and of\n//! each row (`column_*`: a column vector).\n//!\n"
           "//! Sums are exact, products floored step by step, means and variances divided by the "
           "count\n//! correctly rounded (`Real::div`, `Real::divN` with one prepared divisor); "
           "the squares of a\n//! variance are summed exactly and floored once. Overflow panics. "
           "Methods need their trait in\n//! scope (`use nalgebra::Matrix2x3StatisticsTrait;`).\n")
    return (HEADER + doc + "\n" + "".join(f"use {u};\n" for u in uses) + "\n"
            + "\n\n".join(blocks) + "\n")


SHARED_MODULES = {"statistics": render_statistics}
SHARED_EXPORTS = {"statistics": sorted(trait_name(s) for s in ALL_SHAPES)}
