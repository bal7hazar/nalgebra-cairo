def numerator(b: str, terms: list[tuple[str, str]]) -> str:
    """`b - sum(a * x)` floored once: `b` itself, `Real::mul_add(-a, x, b)` (the negation `n..` of
    the matrix entry is bound once per row, shared by the columns), or the exact `Real::Wide`
    chain."""
    if not terms:
        return b
    if len(terms) == 1:
        a, x = terms[0]
        return f"R::mul_add({a}, {x}, {b})"
    acc = f"R::wide_add(R::wide_zero(), {b})"
    for a, x in terms:
        acc = f"R::wide_sub_prod({acc}, {a}, {x})"
    return f"R::wide_rescale({acc})"


def divide(names: list[str], values: list[str], divisor: str) -> list[str]:
    """`let name = value / divisor` for each pair, ONE prepared divisor per `Real::divN` chunk."""
    lines, i = [], 0
    for d in div_chunks(len(names)):
        ns, vs = names[i:i + d], values[i:i + d]
        i += d
        if d == 1:
            lines.append(f"let {ns[0]} = R::div({vs[0]}, {divisor});")
        else:
            lines.append(f"let ({', '.join(ns)}) = R::div{d}({', '.join(vs)}, {divisor});")
    return lines


def substitution(m: Shape, b: Shape, order: list[int], below: bool, mode: str) -> str:
    """The body of a substitution kernel. `order`: the rows in solving order; `below`: the
    already solved rows are those after (`upper`) or before (`lower`) in `order`. `mode`:
    `div` (divide by the diagonal), `unit` (implicit unit diagonal), `diag` (upstream's
    `with_diag`: the sums use the quotients `x_k / diag`, the solution is the numerator)."""
    n, c = m.r, b.c
    lines, done = [], []
    for i in order:
        # The negated entries of row `i` used by a one-product numerator (shared by the columns).
        terms_idx = [k for k in done]
        if len(terms_idx) == 1:
            k = terms_idx[0]
            lines.append(f"let n{i}{k} = -self.{m.f(i, k)};")
            coef = {k: f"n{i}{k}"}
        else:
            coef = {k: f"self.{m.f(i, k)}" for k in terms_idx}
        src = "q" if mode == "diag" else "x"
        nums = [numerator(f"b.{b.f(i, j)}", [(coef[k], f"{src}{k}{j}") for k in terms_idx])
                for j in range(c)]
        names = [f"x{i}{j}" for j in range(c)]
        if mode == "div":
            lines += divide(names, nums, f"self.{m.f(i, i)}")
        else:
            lines += [f"let {x} = {v};" for x, v in zip(names, nums)]
            if mode == "diag" and len(done) + 1 < n:
                lines += divide([f"q{i}{j}" for j in range(c)], names, "diag")
        done.append(i)
    if mode == "diag" and n == 1:
        lines.append("let _ = diag;")
    lines.append(L.lit(b.name, [(b.f(i, j), f"x{i}{j}") for j in range(c) for i in range(n)]))
    body = "\n".join(lines)
    return body


def kernel_impl(m: Shape, b: Shape) -> str:
    n = m.r
    fwd, bwd = list(range(n)), list(range(n - 1, -1, -1))
    M, B = f"{m.name}<T>", f"{b.name}<T>"
    inline = "#[inline(always)]\n" if small(b) else ""
    diag = " && ".join(f"self.{m.f(i, i)} != R::zero()" for i in range(n))
    fns = [
        f"{inline}fn lower(self: {M}, b: {B}) -> {B} {{\n{substitution(m, b, fwd, False, 'div')}\n}}",
        f"{inline}fn upper(self: {M}, b: {B}) -> {B} {{\n{substitution(m, b, bwd, True, 'div')}\n}}",
        f"{inline}fn lower_unit(self: {M}, b: {B}) -> {B} {{\n"
        f"{substitution(m, b, fwd, False, 'unit')}\n}}",
        f"{inline}fn lower_with_diag(self: {M}, b: {B}, diag: T) -> {B} {{\n"
        f"{substitution(m, b, fwd, False, 'diag')}\n}}",
        f"#[inline(always)]\nfn nonzero_diagonal(self: {M}) -> bool {{\n{diag}\n}}",
        "#[inline(always)]\nfn is_zero(x: T) -> bool {\nx == R::zero()\n}",
        f"#[inline(always)]\nfn tr_mul_rhs(self: {M}, b: {B}) -> {B} {{\nMatrixTrMul::tr_mul(self, b)\n}}",
    ]
    return (f"impl {m.name}SolveKernel{b.name}<\n{L.bounds(BOUNDS)}\n> of SolveKernel<{M}, {B}> {{\n"
            "type Scalar = T;\n\n" + "\n\n".join(fns) + "\n}")


