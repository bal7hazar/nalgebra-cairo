# (name, signature tail, doc, body) of the 26 methods, in upstream's order.
CHECKED = ("Returns `false` (`None`) and leaves `b` unchanged when a diagonal entry of `self` is "
           "exactly zero (upstream stops at the first zero pivot and leaves `b` partially "
           "overwritten, its content unspecified).")
UNCHECKED = ("A zero diagonal entry panics with the scalar's division-by-zero error (upstream "
             "divides by zero: infinities / NaN, which a fixed-point scalar does not have).")
ROUNDING = ("Each component: the exact sum of products floored once, then one correctly rounded "
            "division by the diagonal entry (quotients of one row through one prepared divisor, "
            "`Real::divN`). Panics on overflow.")

SIDES = {
    "lower": ("self x = b", "`self` lower triangular (its strictly upper triangle is not read), "
              "by forward substitution", "K::lower(self, b)"),
    "upper": ("self x = b", "`self` upper triangular (its strictly lower triangle is not read), "
              "by back substitution", "K::upper(self, b)"),
    "tr_lower": ("selfᵀ x = b", "`self` lower triangular (its strictly upper triangle is not "
                 "read), by back substitution on the transpose (moves only; bit-identical to "
                 "`self.transpose().solve_upper_triangular(b)`)", "KT::upper(Tr::tr(self), b)"),
    "tr_upper": ("selfᵀ x = b", "`self` upper triangular (its strictly lower triangle is not "
                 "read), by forward substitution on the transpose (moves only; bit-identical to "
                 "`self.transpose().solve_lower_triangular(b)`)", "KT::lower(Tr::tr(self), b)"),
}


def trait_and_blanket() -> tuple[str, str]:
    decls, defs = [], []

    def add(name: str, sig: str, doc: str, body: str):
        decls.append("\n".join(f"/// {line}" if line else "///"
                               for line in wrap(doc, 4).split("\n")) + f"\n{sig};")
        defs.append(f"#[inline(always)]\n{sig} {{\n{body}\n}}")

    for prefix in ("", "tr_", "ad_"):
        for side in ("lower", "upper"):
            key = f"{prefix.rstrip('_')}_{side}".lstrip("_") if prefix != "ad_" else f"tr_{side}"
            eq, how, kernel = SIDES[key]
            base = f"{prefix}solve_{side}_triangular"
            adj = (" The scalar is real: the adjoint is the transpose, this is "
                   f"`tr_solve_{side}_triangular` under upstream's `ad_` name (bit-identical)."
                   if prefix == "ad_" else "")
            add(base, f"fn {base}(self: M, b: B) -> Option<B>",
                f"The solution `x` of `{eq}`, {how}, or `None` when a diagonal entry is exactly "
                f"zero. {ROUNDING}{adj} Upstream: `{base}`.",
                f"if K::nonzero_diagonal(self) {{\nOption::Some({kernel})\n}} else {{\n"
                "Option::None\n}")
            add(f"{base}_mut", f"fn {base}_mut(self: M, ref b: B) -> bool",
                f"Overwrites `b` with the solution of `{eq}` (see `{base}`) and returns `true`. "
                f"{CHECKED}{adj} Upstream: `{base}_mut`.",
                f"if K::nonzero_diagonal(self) {{\nb = {kernel};\ntrue\n}} else {{\nfalse\n}}")
            if prefix == "" and side == "lower":
                add("solve_lower_triangular_with_diag_mut",
                    "fn solve_lower_triangular_with_diag_mut(self: M, ref b: B, diag: Self::Scalar)"
                    " -> bool",
                    "Upstream's forward elimination with `diag` in place of the diagonal of "
                    "`self`: for each row `i`, `b_i -= sum_(k<i) self[i, k] * (b_k / diag)`, the "
                    "updated `b_k` divided by `diag` (one correctly rounded quotient each, one "
                    "prepared divisor per row), then the sum accumulated exactly and floored once. "
                    "The result is `diag * x` for `(strict lower triangle of self + diag * I) x = "
                    "b`, exactly what upstream leaves in `b` (it never writes the quotients back); "
                    "with `diag = 1` it is the unit lower triangular solve of `LU`. Returns "
                    "`false` and leaves `b` unchanged when `diag` is exactly zero. Panics on "
                    "overflow. Upstream: `solve_lower_triangular_with_diag_mut`.",
                    "if K::is_zero(diag) {\nfalse\n} else {\nb = K::lower_with_diag(self, b, "
                    "diag);\ntrue\n}")
            add(f"{base}_unchecked", f"fn {base}_unchecked(self: M, b: B) -> B",
                f"The solution `x` of `{eq}` (see `{base}`) without the zero-diagonal test. "
                f"{UNCHECKED}{adj} Upstream: `{base}_unchecked`.", kernel)
            add(f"{base}_unchecked_mut", f"fn {base}_unchecked_mut(self: M, ref b: B)",
                f"Overwrites `b` with `{base}_unchecked(b)`.{adj} Upstream: "
                f"`{base}_unchecked_mut`.", f"b = {kernel};")
            if prefix == "" and side == "lower":
                add("solve_lower_triangular_with_diag_unchecked_mut",
                    "fn solve_lower_triangular_with_diag_unchecked_mut(self: M, ref b: B, "
                    "diag: Self::Scalar)",
                    "`solve_lower_triangular_with_diag_mut` without the zero test: a zero `diag` "
                    "panics with the scalar's division-by-zero error as soon as a quotient is "
                    "needed (never for a 1x1 `self`, like upstream, which divides nothing). "
                    "Upstream: `solve_lower_triangular_with_diag_unchecked_mut`.",
                    "b = K::lower_with_diag(self, b, diag);")
    trait = ("/// The triangular solves of a square `self` against any right-hand side `b` with as "
             "many rows\n/// (a column vector or a matrix: one kernel impl per pair of shapes, 36). "
             "`b` is taken by\n/// value (`ref b` for the `_mut` forms, upstream's `&mut`). "
             "Upstream: `SquareMatrix::solve_*`,\n/// `tr_solve_*`, `ad_solve_*` "
             "(`src/linalg/solve.rs`).\npub trait MatrixSolve<M, B> {\n"
             "/// The scalar (`diag` of the `with_diag` forms).\ntype Scalar;\n\n"
             + "\n\n".join(decls) + "\n}")
    blanket = ("/// The one impl of `MatrixSolve`: every method is a kernel of `SolveKernel` (the "
               "`tr_` / `ad_`\n/// forms on the transpose of `self`, struct moves only), "
               "`#[inline(always)]`.\npub impl MatrixSolveImpl<\nM,\nB,\n"
               "impl K: SolveKernel<M, B>,\nimpl Tr: BlasTranspose<M>,\n"
               "impl KT: SolveKernel<Tr::Output, B>,\n+Copy<M>,\n+Drop<M>,\n+Drop<B>,\n"
               "+Copy<K::Scalar>,\n+Drop<K::Scalar>,\n"
               "> of MatrixSolve<M, B> {\ntype Scalar = K::Scalar;\n\n"
               + "\n\n".join(defs) + "\n}")
    return trait, blanket


KERNEL_TRAIT = """/// The unrolled substitutions of one (square, right-hand side) pair (crate-private: `LU` and
/// `Cholesky` use them directly).
pub(crate) trait SolveKernel<M, B> {
    /// The scalar.
    type Scalar;
    /// `self x = b`, `self` lower triangular: forward substitution, one floor per sum and one
    /// correctly rounded division per component.
    fn lower(self: M, b: B) -> B;
    /// `self x = b`, `self` upper triangular: back substitution.
    fn upper(self: M, b: B) -> B;
    /// `self x = b` with an implicit unit diagonal (the `L` of `LU`): no division, bit-identical
    /// to `lower_with_diag(b, 1)`.
    fn lower_unit(self: M, b: B) -> B;
    /// Upstream's `solve_lower_triangular_with_diag_mut` (see `MatrixSolve`).
    fn lower_with_diag(self: M, b: B, diag: Self::Scalar) -> B;
    /// Whether every diagonal entry is nonzero.
    fn nonzero_diagonal(self: M) -> bool;
    /// `x == 0`.
    fn is_zero(x: Self::Scalar) -> bool;
    /// `selfᵀ * b` (`MatrixTrMul::tr_mul`, whose output has `b`'s shape since `self` is square):
    /// the `Qᵀ b` of `QR`.
    fn tr_mul_rhs(self: M, b: B) -> B;
}"""

GENERIC_TRAITS = ["MatrixSolve"]


def render_solve() -> str:
    uses = ["simba::scalar::Real", "super::blas::BlasTranspose",
            "super::matrix_tr_mul::MatrixTrMul"] + sorted(
        {f"super::{s.module}::{s.name}" for p in pairs() for s in p})
    trait, blanket = trait_and_blanket()
    doc = ("//! Triangular solves of the static square matrices (upstream `SquareMatrix::solve_*`, "
           "`src/linalg/solve.rs`):\n//! `m.solve_lower_triangular(b)`, `m.tr_solve_upper_triangular"
           "_mut(ref b)`... for any right-hand\n//! side `b` with as many rows as `m` (vectors and "
           "matrices). Import `MatrixSolve`.\n//!\n//! Each component of the solution is ONE exact "
           "sum of products floored once (`Real::Wide`), then\n//! ONE correctly rounded division "
           "by the diagonal entry; the quotients of one row share a prepared\n//! divisor "
           "(`Real::divN`) from 3 columns on. Upstream's f64 `axpy` updates round every product;"
           "\n//! the checked forms test the diagonal once, up front, and leave `b` unchanged on "
           "failure.\n")
    blocks = [trait, KERNEL_TRAIT, blanket] + [kernel_impl(m, b) for m, b in pairs()]
    return (HEADER + doc + "\n" + "".join(f"use {u};\n" for u in uses) + "\n"
            + "\n\n".join(blocks) + "\n")


