"""Templates of the triangular solves of the static square shapes (WP 8.5-P14a, API_PARITY package
P14): upstream `src/linalg/solve.rs` on the 6 squares, written into ONE shared module,
`crates/nalgebra/src/base/solve.cairo`:

* `MatrixSolve<M, B>` (public): the 26 methods of `solve.rs` (`solve_{lower,upper}_triangular`
  with their `_mut`, `_unchecked`, `_unchecked_mut` forms, `solve_lower_triangular_with_diag_mut`
  / `_with_diag_unchecked_mut`, and the `tr_` / `ad_` forms), ONE blanket impl
  (`MatrixSolveImpl`) over the crate-private kernel trait below. `M` is the square `self`, `B`
  any shape with as many rows (a column vector or a matrix: upstream's `R2 x C2` right-hand
  side with `SameNumberOfRows<R2, D>`), which the kernel impls enumerate: 36 pairs;
* `SolveKernel<M, B>` (crate-private): one impl per pair, the unrolled substitutions (`lower`,
  `upper`, `lower_unit` for `LU`, `lower_with_diag`) and the zero-diagonal test. The `tr_`
  forms are the kernels of the transpose (`BlasTranspose`, moves only): `Lᵀ x = b` is the upper
  substitution on `Lᵀ`, the same fused sums in the same order, bit-identical.

Numerics. Each component of the solution is `x_i = (b_i - sum_k t_ik x_k) / t_ii`: the sum of
products accumulated exactly in `Real::Wide` and floored ONCE (one product: `Real::mul_add`,
also one floor), then ONE correctly rounded division (to nearest). Upstream (f64) updates `b`
column-wise with `axpy`, rounding every product and every sum; the exact accumulation is the
project's rule (AGENTS.md rule 4) and the tolerance of the oracle covers the difference. The
quotients of one row share their divisor: `Real::divN` (one prepared divisor, bit-identical to
`N` divisions) from 3 right-hand columns on.
"""

import library as L
from completion import div_chunks, item, wrap
from model import ALL_SHAPES, Shape

HEADER = ("// Generated by tools/shapegen/shapegen.py: do not edit by hand. Template:\n"
          "// tools/shapegen/solve.py.\n")
BOUNDS = ["T", "impl R: Real<T>", "+Copy<T>", "+Drop<T>", "+Drop<R::Wide>", "+Mul<T>", "+Neg<T>",
          "+PartialEq<T>"]
DIMS = range(1, 7)
SQUARES = [Shape(n, n) for n in DIMS]


def pairs() -> list[tuple[Shape, Shape]]:
    """(square `self`, right-hand side with as many rows): 36."""
    return [(Shape(n, n), Shape(n, c)) for n in DIMS for c in DIMS]


def small(b: Shape) -> bool:
    """`#[inline(always)]` for the column-vector right-hand sides (and the other shapes of at most
    4 components), measured (`crates/tests_linalg_solve`, net gas of
    `solve_lower_triangular_unchecked`): out of line, a kernel costs `Vector6` 44 740 against
    31 090 inlined (the operands copied in and out of the call), `Matrix3` 54 410 against 39 980,
    `Matrix6` 227 000 against 174 260. The matrix right-hand sides stay out of line anyway: every
    call site would carry a copy of the whole unrolled kernel, and the test package of this WP,
    compiled with every kernel inlined, peaked at 16.9 GB (12 min) against the budget of ~8.5 GB.
    Destructuring the operands once at the top of an out-of-line kernel was also measured: the
    same gas to the unit (the compiler already does it)."""
    return b.is_column or b.n <= 4


