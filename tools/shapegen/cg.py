def trait_names(s: Shape) -> list[str]:
    return [f"{s.name}CgTrait"] + ([f"{s.name}CgAngleTrait"] if angle_methods(s) else [])


def impl_block(s: Shape, suffix: str, bounds: list[str], fns: list[L.Fn], doc: str) -> str:
    return (item(doc, "#[generate_trait]\n")
            + f"pub impl {s.name}{suffix}Impl<\n{L.bounds(bounds)}\n> of {s.name}{suffix}Trait<T> {{\n"
            + "\n\n".join(x.definition() for x in fns) + "\n}")


def render_cg() -> str:
    uses = ["simba::scalar::{Real, Transcendental}",
            "crate::geometry::{IsometryMatrix3Trait, Rotation2AngleTrait, "
            "Rotation2Trait, Rotation3AngleTrait, Rotation3Trait}",
            "super::kernels::Fused", "super::point2::Point2", "super::point3::Point3",
            "super::unit::Unit"]
    uses += [f"super::{s.module}::{s.name}" for s in SQUARES]
    uses += [f"super::{vec(k).module}::{vec(k).name}" for k in range(2, 6)]
    blocks = []
    for s in SQUARES:
        blocks.append(impl_block(
            s, "Cg", BOUNDS, methods(s),
            f"The homogeneous-coordinates helpers of `{s.name}<T>` (upstream `base/cg.rs`) that "
            "need no trigonometry, for any `Real` scalar. By value, unrolled, no loop."))
        if angle_methods(s):
            blocks.append(impl_block(
                s, "CgAngle", ANGLE_BOUNDS, angle_methods(s),
                f"The rotation constructors of `{s.name}<T>` (upstream `base/cg.rs`), which need "
                "`Transcendental`: a scalar may implement `Real` only."))
    doc = ("//! Homogeneous / computer-graphics helpers of the square shapes (upstream "
           "`nalgebra::base::cg`,\n//! `src/base/cg.rs`): scalings, translations, their "
           "composition with a homogeneous matrix,\n//! the homogeneous transform of vectors and "
           "points, and on `Matrix3` / `Matrix4` the rotation,\n//! observer and view "
           "constructors (delegating to `Rotation2/3` / `IsometryMatrix3`, like upstream).\n"
           "//!\n//! Every sum of products goes through a fused `Real` kernel (one floor rounding "
           "per output scalar),\n//! every quotient is correctly rounded (`Real::div`, "
           "`div3/4/5`); overflow panics. Associated\n//! functions are called through their "
           "trait (`Matrix4CgTrait::new_translation(v)`), methods need\n//! the trait in scope. "
           "`Matrix4::new_perspective` / `new_orthographic` are `Perspective3` /\n//! "
           "`Orthographic3`'s (upstream delegates them there).\n")
    return (HEADER + doc + "\n" + "".join(f"use {u};\n" for u in uses) + "\n"
            + "\n\n".join(blocks) + "\n")


SHARED_MODULES = {"cg": render_cg}
SHARED_EXPORTS = {"cg": sorted(n for s in SQUARES for n in trait_names(s))}
