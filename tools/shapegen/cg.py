def methods(s: Shape, form: str = CG_ADDEND) -> list[L.Fn]:
    """`form`: the kernel of the sums with an exact addend (`dot_plus`); the benches of
    `tests_cg.py` render the other form as the measured alternative."""
    N, K, S, T = s.r, s.r - 1, s.name, f"{s.name}<T>"
    V = vec(K) if K else None
    f = s.f
    out: list[L.Fn] = []

    def mat(g) -> str:
        return L.lit(S, [(f(i, j), g(i, j)) for j in range(N) for i in range(N)])

    def keep(i: int, j: int) -> str:
        return f"self.{f(i, j)}"

    one, zero = "R::one()", "R::zero()"
    out.append(fn(
        "new_scaling",
        f"The homogeneous matrix of the uniform scaling by `scaling`: `scaling` on the first "
        f"{K} diagonal entries, 1 on the last, 0 elsewhere (exact"
        + ("; `Matrix1` is the identity, upstream's `new_scaling` on a 1x1 matrix" if K == 0 else "")
        + "). Upstream: `new_scaling`.",
        f"fn new_scaling(scaling: T) -> {T}",
        (f"let _ = scaling;\n" if K == 0 else "")
        + mat(lambda i, j: (("scaling" if i < K else one) if i == j else zero))))
    if V:
        v = lambda k: f"scaling.{COORDS[k]}"  # noqa: E731
        out.append(fn(
            "new_nonuniform_scaling",
            f"The homogeneous matrix of the non-uniform scaling by the components of `scaling` "
            f"(diagonal `scaling`, then 1; exact). Upstream: `new_nonuniform_scaling`.",
            f"fn new_nonuniform_scaling(scaling: {V.name}<T>) -> {T}",
            mat(lambda i, j: ((v(i) if i < K else one) if i == j else zero))))
        out.append(fn(
            "new_translation",
            "The homogeneous matrix of the translation by `translation`: the identity whose last "
            "column starts with `translation` (exact). Upstream: `new_translation`.",
            f"fn new_translation(translation: {V.name}<T>) -> {T}",
            mat(lambda i, j: (f"translation.{COORDS[i]}" if j == K and i < K
                              else (one if i == j else zero)))))

    # Scalings.
    def scaled(rows: bool, factor) -> str:
        return mat(lambda i, j: (f"self.{f(i, j)} * {factor(i if rows else j)}"
                                 if (i if rows else j) < K else keep(i, j)))

    if K:
        out.append(fn(
            "append_scaling",
            "The transformation `self` followed by the uniform scaling `scaling`: the first "
            f"{K} rows of `self` times `scaling`, each product floored once. Upstream: "
            "`append_scaling`.",
            f"fn append_scaling(self: {T}, scaling: T) -> {T}",
            scaled(True, lambda k: "scaling")))
        out.append(fn(
            "prepend_scaling",
            "The uniform scaling `scaling` followed by the transformation `self`: the first "
            f"{K} columns of `self` times `scaling`, each product floored once. Upstream: "
            "`prepend_scaling`.",
            f"fn prepend_scaling(self: {T}, scaling: T) -> {T}",
            scaled(False, lambda k: "scaling")))
    else:
        for name, what in (("append_scaling", "followed by"), ("prepend_scaling", "preceded by")):
            out.append(fn(
                name,
                f"`self` {what} the uniform scaling `scaling`: `self` (a 1x1 homogeneous matrix "
                f"has no row / column to scale, like upstream's). Upstream: `{name}`.",
                f"fn {name}(self: {T}, scaling: T) -> {T}", "let _ = scaling;\nself"))
    if V:
        out.append(fn(
            "append_nonuniform_scaling",
            "The transformation `self` followed by the non-uniform scaling `scaling`: row `i < "
            f"{K}` of `self` times `scaling[i]`, each product floored once. Upstream: "
            "`append_nonuniform_scaling`.",
            f"fn append_nonuniform_scaling(self: {T}, scaling: {V.name}<T>) -> {T}",
            scaled(True, lambda k: f"scaling.{COORDS[k]}")))
        out.append(fn(
            "prepend_nonuniform_scaling",
            "The non-uniform scaling `scaling` followed by the transformation `self`: column `j < "
            f"{K}` of `self` times `scaling[j]`, each product floored once. Upstream: "
            "`prepend_nonuniform_scaling`.",
            f"fn prepend_nonuniform_scaling(self: {T}, scaling: {V.name}<T>) -> {T}",
            scaled(False, lambda k: f"scaling.{COORDS[k]}")))
        # Translations.
        out.append(fn(
            "append_translation",
            "The transformation `self` followed by the translation `shift`: `m[j, i] + shift[j] "
            f"* m[{K}, i]` for `j < {K}`, one fused `R::mul_add` each (the bits of upstream's "
            "product then sum: the addend is exact), the last row untouched. Upstream: "
            "`append_translation`.",
            f"fn append_translation(self: {T}, shift: {V.name}<T>) -> {T}",
            mat(lambda i, j: (dot_plus([(f"shift.{COORDS[i]}", f"self.{f(K, j)}")],
                                       f"self.{f(i, j)}", form) if i < K else keep(i, j))),
            inline=N <= 4))
        out.append(fn(
            "prepend_translation",
            "The translation `shift` followed by the transformation `self`: `m[j, "
            f"{K}] + m[j, :{K}] . shift` for every row `j`, each ONE fused sum of products (the "
            "bits of upstream's dot product then sum: the addend is exact), the other columns "
            "untouched. Upstream: `prepend_translation`.",
            f"fn prepend_translation(self: {T}, shift: {V.name}<T>) -> {T}",
            mat(lambda i, j: (dot_plus([(f"self.{f(i, k)}", f"shift.{COORDS[k]}")
                                        for k in range(K)], f"self.{f(i, K)}", form)
                              if j == K else keep(i, j))),
            inline=N <= 4))
    # In-place forms.
    ins = [("append_scaling", "scaling", "T"), ("prepend_scaling", "scaling", "T")]
    if V:
        ins += [("append_nonuniform_scaling", "scaling", f"{V.name}<T>"),
                ("prepend_nonuniform_scaling", "scaling", f"{V.name}<T>"),
                ("append_translation", "shift", f"{V.name}<T>"),
                ("prepend_translation", "shift", f"{V.name}<T>")]
    for name, arg, ty in ins:
        out.append(fn(
            f"{name}_mut",
            f"`self = self.{name}({arg})` (same rounding). Upstream: `{name}_mut`.",
            f"fn {name}_mut(ref self: {T}, {arg}: {ty})",
            f"self = Self::{name}(self, {arg});"))
    if V:
        w = [f"w.{COORDS[k]}" for k in range(K)]
        body = (f"let n = {dot([(f'self.{f(K, k)}', f'v.{COORDS[k]}') for k in range(K)])};\n"
                f"let w = if n != R::zero() {{\n"
                + divide([f"v.{COORDS[k]}" for k in range(K)], "n", list(COORDS[:K]))
                + L.lit(V.name, [(c, c) for c in COORDS[:K]]) + "\n} else {\nv\n};\n"
                + L.lit(V.name, [(COORDS[i], dot([(f"self.{f(i, k)}", w[k]) for k in range(K)]))
                                 for i in range(K)]))
        out.append(fn(
            "transform_vector",
            "`v` transformed by the homogeneous matrix `self`: with the normaliser `n = m[" + str(K)
            + f", :{K}] . v` (one fused dot product), `m[:{K}, :{K}] * (v / n)` if `n != 0`, else "
            f"`m[:{K}, :{K}] * v` (upstream's branch); each quotient correctly rounded, each "
            "output one fused dot product. Panics on overflow. Upstream: `transform_vector`.",
            f"fn transform_vector(self: {T}, v: {V.name}<T>) -> {V.name}<T>", body,
            inline=N <= 4))
    if N in (3, 4):
        P = point(K)
        q = [f"q{COORDS[i]}" for i in range(K)]
        body = (f"let n = {dot_plus([(f'self.{f(K, k)}', f'pt.{COORDS[k]}') for k in range(K)], f'self.{f(K, K)}', form)};\n"
                + "".join(f"let {q[i]} = "
                          f"{dot_plus([(f'self.{f(i, k)}', f'pt.{COORDS[k]}') for k in range(K)], f'self.{f(i, K)}', form)};\n"
                          for i in range(K))
                + "if n != R::zero() {\n"
                + divide(q, "n", list(COORDS[:K]))
                + L.lit(P, [(c, c) for c in COORDS[:K]]) + "\n} else {\n"
                + L.lit(P, [(COORDS[i], q[i]) for i in range(K)]) + "\n}")
        out.append(fn(
            "transform_point",
            f"`pt` transformed by the homogeneous matrix `self`: `q = m[:{K}, :{K}] * pt + "
            f"m[:{K}, {K}]` and `n = m[{K}, :{K}] . pt + m[{K}, {K}]` (one fused sum of products "
            "each, the bits of upstream's product then sum), then `q / n` correctly rounded if `n "
            "!= 0`, else `q` (upstream's branch). Panics on overflow. Upstream: `transform_point`.",
            f"fn transform_point(self: {T}, pt: {P}<T>) -> {P}<T>", body, inline=False))
        out.append(fn(
            "new_nonuniform_scaling_wrt_point",
            "The homogeneous matrix of the non-uniform scaling by `scaling` about the point `pt`: "
            "diagonal `scaling`, then 1, last column `pt - pt * scaling`, each ONE fused "
            "`R::mul_add(-pt, scaling, pt)` (the floor of the exact value, where upstream rounds "
            "the product then the difference). Upstream: `new_nonuniform_scaling_wrt_point`.",
            f"fn new_nonuniform_scaling_wrt_point(scaling: {V.name}<T>, pt: {P}<T>) -> {T}",
            mat(lambda i, j: (f"R::mul_add(-pt.{COORDS[i]}, scaling.{COORDS[i]}, pt.{COORDS[i]})"
                              if j == K and i < K else
                              (f"scaling.{COORDS[i]}" if i < K else one) if i == j else zero))))
    if N == 4:
        for name, what in (
                ("face_towards", "the local frame of an observer at `eye` looking towards `target` "
                                 "(the view direction mapped to `+z`, the origin to `eye`)"),
                ("look_at_rh", "the right-handed look-at view matrix"),
                ("look_at_lh", "the left-handed look-at view matrix")):
            out.append(fn(
                name,
                f"{what[0].upper() + what[1:]}: `IsometryMatrix3::{name}(eye, target, up)"
                f".to_homogeneous()`, upstream's delegation (same rounding as `IsometryMatrix3::"
                f"{name}`). `up` must not be parallel to `target - eye`. Upstream: "
                f"`Matrix4::{name}`.",
                f"fn {name}(eye: Point3<T>, target: Point3<T>, up: Vector3<T>) -> {T}",
                f"IsometryMatrix3Trait::{name}(eye, target, up).to_homogeneous()", inline=False))
        out.append(fn(
            "new_observer_frame",
            "Deprecated upstream (renamed `face_towards`): `face_towards(eye, target, up)`. "
            "Upstream: `Matrix4::new_observer_frame`.",
            f"fn new_observer_frame(eye: Point3<T>, target: Point3<T>, up: Vector3<T>) -> {T}",
            "Self::face_towards(eye, target, up)"))
    return out


def angle_methods(s: Shape) -> list[L.Fn]:
    T = f"{s.name}<T>"
    if s.r == 3:
        return [fn("new_rotation",
                   "The homogeneous matrix of the 2D rotation by `angle` radians: "
                   "`Rotation2::new(angle).to_homogeneous()` (one `sin_cos`). Upstream: "
                   "`Matrix3::new_rotation`.",
                   f"fn new_rotation(angle: T) -> {T}",
                   "Rotation2AngleTrait::new(angle).to_homogeneous()")]
    if s.r != 4:
        return []
    out = [fn("new_rotation",
              "The homogeneous matrix of the 3D rotation by the rotation vector `axisangle` (axis "
              "times angle; the identity for a zero vector): `Rotation3::new(axisangle)"
              ".to_homogeneous()`. Upstream: `Matrix4::new_rotation`.",
              f"fn new_rotation(axisangle: Vector3<T>) -> {T}",
              "Rotation3AngleTrait::new(axisangle).to_homogeneous()"),
           fn("new_rotation_wrt_point",
              "The homogeneous matrix of the rotation by the rotation vector `axisangle` about the "
              "point `pt` (`pt` is invariant): `IsometryMatrix3::rotation_wrt_point("
              "Rotation3::from_scaled_axis(axisangle), pt).to_homogeneous()`. Upstream: "
              "`Matrix4::new_rotation_wrt_point`.",
              f"fn new_rotation_wrt_point(axisangle: Vector3<T>, pt: Point3<T>) -> {T}",
              "IsometryMatrix3Trait::rotation_wrt_point(\nRotation3AngleTrait::from_scaled_axis("
              "axisangle), pt,\n)\n.to_homogeneous()", inline=False),
           fn("from_scaled_axis",
              "The same as `new_rotation`: `Rotation3::from_scaled_axis(axisangle)"
              ".to_homogeneous()`. Upstream: `Matrix4::from_scaled_axis`.",
              f"fn from_scaled_axis(axisangle: Vector3<T>) -> {T}",
              "Rotation3AngleTrait::from_scaled_axis(axisangle).to_homogeneous()"),
           fn("from_euler_angles",
              "The homogeneous matrix of the rotation of Euler angles `roll`, `pitch`, `yaw` "
              "(applied in this order): `Rotation3::from_euler_angles(roll, pitch, yaw)"
              ".to_homogeneous()`. Upstream: `Matrix4::from_euler_angles`.",
              f"fn from_euler_angles(roll: T, pitch: T, yaw: T) -> {T}",
              "Rotation3AngleTrait::from_euler_angles(roll, pitch, yaw).to_homogeneous()"),
           fn("from_axis_angle",
              "The homogeneous matrix of the rotation of `angle` radians about the unit `axis`: "
              "`Rotation3::from_axis_angle(axis, angle).to_homogeneous()`. Upstream: "
              "`Matrix4::from_axis_angle`.",
              f"fn from_axis_angle(axis: Unit<Vector3<T>>, angle: T) -> {T}",
              "Rotation3AngleTrait::from_axis_angle(axis, angle).to_homogeneous()")]
    return out


