"""Templates of the homogeneous / computer-graphics helpers (WP 8.3, API_PARITY package P07):
upstream `src/base/cg.rs` on the square shapes, written into ONE shared module,
`crates/nalgebra/src/base/cg.cairo` (upstream's file), as one `#[generate_trait]` per square:

* `Matrix{N}CgTrait` (`Matrix1..6`, any `Real` scalar): `new_scaling`, `append_scaling` /
  `prepend_scaling` (and `_mut`) on every square; on `Matrix2..6` (the squares whose dimension
  minus one is a static vector, `Vector1` being `Matrix1`) `new_nonuniform_scaling`,
  `new_translation`, `append_*` / `prepend_*` of the non-uniform scalings and translations (and
  `_mut`), `transform_vector`; on `Matrix3` / `Matrix4` `new_nonuniform_scaling_wrt_point`,
  `transform_point`, and on `Matrix4` the observer / view frames (`face_towards`,
  `new_observer_frame`, `look_at_rh`, `look_at_lh`), which need no trigonometry;
* `Matrix3CgAngleTrait` / `Matrix4CgAngleTrait` (`Transcendental` scalars): the rotation
  constructors (`new_rotation`, `new_rotation_wrt_point`, `from_scaled_axis`, `from_axis_angle`,
  `from_euler_angles`).

`Matrix1` has no `new_nonuniform_scaling` ... `transform_vector`: their vector would be 0-dimensional
(`scripts/api_parity.py` `DIM_ONLY`); upstream's `Matrix1::new_scaling` is the identity and its
`append_scaling` / `prepend_scaling` scale no row / column (they return `self`), ported as such.
`Matrix4::new_perspective` / `new_orthographic` come with `Perspective3` / `Orthographic3` (WP
8.4-P11b), which upstream delegates them to.

Numerics (upstream's formulas, the project's rounding):

* scalings: one floored product per scaled component (upstream's `*=` on rows / columns), the
  homogeneous row / column untouched;
* translations: `append_translation` adds `shift_j * m[K, i]` to every `m[j, i]` (`K = N - 1`),
  `prepend_translation` adds `m[K, :K] . shift` to `m[K, K]` and `m[j, :K] . shift` to `m[j, K]`:
  each output is ONE fused sum of products whose addend is exact, so its bits equal upstream's
  "sum rounded then added" (`floor(x + c) = floor(x) + c` for a representable `c`); the kernel
  (`R::mul_add` / a `Real::Wide` chain with `wide_add`, or `sum_prodK` then `+`) is the measured
  cheapest (`CG_ADDEND`, benches `bench_*_prepend_translation__*`);
* `transform_vector` / `transform_point`: the normaliser `n` is one fused dot product (plus the
  exact `m[K, K]` for points); if `n != 0` the vector is divided by `n` BEFORE the product (vector,
  upstream's order) or the image after it (point), each quotient correctly rounded (`R::div`,
  `R::div3/4/5`, bit-identical); if `n == 0`, upstream's other branch: no division;
* `new_nonuniform_scaling_wrt_point`: `pt - pt * scaling` as ONE fused `R::mul_add(-pt, scaling,
  pt)` (the floor of the exact value; upstream rounds the product then the difference);
* the rotations and frames delegate to `Rotation2` / `Rotation3` / `IsometryMatrix3` and their
  `to_homogeneous`, exactly as upstream (`Rotation3::new(axisangle).to_homogeneous()`...).
"""

import library as L
from completion import ANGLE_BOUNDS, fn, item, vec
from model import COORDS, Shape

HEADER = ("// Generated by tools/shapegen/shapegen.py: do not edit by hand. Template:\n"
          "// tools/shapegen/cg.py.\n")
BOUNDS = ["T", "impl R: Real<T>", "+Copy<T>", "+Drop<T>", "+Drop<R::Wide>", "+Add<T>", "+Sub<T>",
          "+Mul<T>", "+Neg<T>", "+PartialEq<T>", "+PartialOrd<T>"]
SQUARES = [Shape(n, n) for n in range(1, 7)]
# The kernel of a sum of products plus one exact addend (bit-identical forms, see the module doc):
# "wide" = one `Real::Wide` chain closed by `wide_add` (`R::mul_add` for one product), "plain" =
# `R::sum_prodK(..) + c`. Chosen by the benches of `crates/shapes_tests_cg` (`benches.cairo`).
CG_ADDEND = "wide"


# --------------------------------------------------------------------------------------------
# Kernels
# --------------------------------------------------------------------------------------------


def dot(pairs: list[tuple[str, str]]) -> str:
    """`Σ a * b`, ONE rounding (AGENTS.md rule 4)."""
    k = len(pairs)
    flat = ", ".join(f"{a}, {b}" for a, b in pairs)
    if k == 1:
        return f"{pairs[0][0]} * {pairs[0][1]}"
    if k <= 4:
        return f"R::sum_prod{k}({flat})"
    return f"Fused::sum_prod{k}({flat})"


def wide_chain(pairs: list[tuple[str, str]]) -> str:
    w = "R::wide_zero()"
    for a, b in pairs:
        w = f"R::wide_add_prod({w}, {a}, {b})"
    return w


def dot_plus(pairs: list[tuple[str, str]], c: str, form: str = CG_ADDEND) -> str:
    """`Σ a * b + c` for an exact `c`: bit-identical to `dot(pairs) + c` (one rounding)."""
    if form == "plain":
        return f"{dot(pairs)} + {c}"
    if len(pairs) == 1:
        return f"R::mul_add({pairs[0][0]}, {pairs[0][1]}, {c})"
    return f"R::wide_rescale(R::wide_add({wide_chain(pairs)}, {c}))"


def divide(xs: list[str], d: str, names: list[str]) -> str:
    """`let (names) = (xs / d)`, each quotient correctly rounded (`Real::div`, `div3/4/5`)."""
    k = len(xs)
    if k <= 2:
        return "".join(f"let {n} = R::div({x}, {d});\n" for n, x in zip(names, xs))
    return f"let ({', '.join(names)}) = R::div{k}({', '.join(xs)}, {d});\n"


def point(d: int) -> str:
    return f"Point{d}"


