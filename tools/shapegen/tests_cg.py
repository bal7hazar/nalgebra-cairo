def constructors(f: File, s: Shape):
    N, K, S = s.r, s.r - 1, s.name
    rng = random.Random(f"tests_cg/constructors/{S}")
    k = rand_raw(rng, 34)
    lines = [f"let k = fx({k});",
             f"assert_raws({S}CgTrait::new_scaling(k), "
             f"{col(s, grid(s, lambda i, j: (k if i < K else ONE) if i == j else 0))});"]
    if K:
        v = [rand_raw(rng, 34) for _ in range(K)]
        lines += [vload(K, "v", v),
                  f"assert_raws({S}CgTrait::new_nonuniform_scaling(v), "
                  f"{col(s, grid(s, lambda i, j: (v[i] if i < K else ONE) if i == j else 0))});",
                  f"assert_raws({S}CgTrait::new_translation(v), "
                  f"{col(s, grid(s, lambda i, j: v[i] if j == K and i < K else (ONE if i == j else 0)))});"]
    if N in (3, 4):
        sc = [rand_raw(rng, 34) for _ in range(K)]
        p = [rand_raw(rng, 36) for _ in range(K)]
        lines += [vload(K, "sc", sc), pload(K, "p", p),
                  f"assert_raws({S}CgTrait::new_nonuniform_scaling_wrt_point(sc, p), "
                  f"{col(s, grid(s, lambda i, j: mul(-p[i], sc[i]) + p[i] if j == K and i < K else ((sc[i] if i < K else ONE) if i == j else 0)))});"]
    f.add(f"test_{s.module}_cg_constructors", lines, [f"{S}CgTrait"])


def compose(f: File, s: Shape):
    """`append_*` / `prepend_*` and their `_mut` forms."""
    K, S = s.r - 1, s.name
    rng = random.Random(f"tests_cg/compose/{S}")
    a = raws(rng, s, 36)
    k = rand_raw(rng, 34)
    at = lambda i, j: a[s.f(i, j)]  # noqa: E731
    cases = [("append_scaling", "k", grid(s, lambda i, j: mul(at(i, j), k) if i < K else at(i, j))),
             ("prepend_scaling", "k", grid(s, lambda i, j: mul(at(i, j), k) if j < K else at(i, j)))]
    lines = [load(s, "a", a), f"let k = fx({k});"]
    if K:
        v = [rand_raw(rng, 34) for _ in range(K)]
        lines.append(vload(K, "v", v))
        cases += [
            ("append_nonuniform_scaling", "v",
             grid(s, lambda i, j: mul(at(i, j), v[i]) if i < K else at(i, j))),
            ("prepend_nonuniform_scaling", "v",
             grid(s, lambda i, j: mul(at(i, j), v[j]) if j < K else at(i, j))),
            ("append_translation", "v",
             grid(s, lambda i, j: mul(v[i], at(K, j)) + at(i, j) if i < K else at(i, j))),
            ("prepend_translation", "v",
             grid(s, lambda i, j: dot([at(i, q) for q in range(K)], v) + at(i, K) if j == K
                  else at(i, j)))]
    for name, arg, expected in cases:
        lines.append(f"assert_raws(a.{name}({arg}), {col(s, expected)});")
        lines += [f"let mut b = a;", f"b.{name}_mut({arg});", f"assert_raws(b, {col(s, expected)});"]
    f.add(f"test_{s.module}_cg_append_prepend", lines, [f"{S}CgTrait"])


def transforms(f: File, s: Shape):
    N, K, S = s.r, s.r - 1, s.name
    if not K:
        return
    rng = random.Random(f"tests_cg/transforms/{S}")
    v = [rand_raw(rng, 34) for _ in range(K)]
    a = normaliser_at_least(rng, s, raws(rng, s, 34), v, False)
    # Affine: the normaliser row `m[K, :K]` is zero, `n == 0` (upstream's other branch).
    b = {**a, **{s.f(K, k): 0 for k in range(K)}}
    lines = [load(s, "a", a), load(s, "b", b), vload(K, "v", v),
             f"assert_raws(a.transform_vector(v), {span(model_transform_vector(s, a, v))});",
             f"assert_raws(b.transform_vector(v), {span(model_transform_vector(s, b, v))});"]
    f.add(f"test_{s.module}_transform_vector", lines, [f"{S}CgTrait"])
    if N not in (3, 4):
        return
    p = [rand_raw(rng, 34) for _ in range(K)]
    a = normaliser_at_least(rng, s, raws(rng, s, 34), p, True)
    z = {**a, **{s.f(K, k): 0 for k in range(K + 1)}}
    t = [rand_raw(rng, 36) for _ in range(K)]
    lines = [load(s, "a", a), load(s, "z", z), pload(K, "p", p), vload(K, "t", t),
             f"assert_raws(a.transform_point(p), {span(model_transform_point(s, a, p))});",
             f"assert_raws(z.transform_point(p), {span(model_transform_point(s, z, p))});",
             # A translation moves a point exactly (`n = 1`).
             f"assert_raws({S}CgTrait::new_translation(t).transform_point(p), "
             f"{span(p[i] + t[i] for i in range(K))});"]
    f.add(f"test_{s.module}_transform_point", lines, [f"{S}CgTrait"])
    # `|q / n|` out of range: the quotient's overflow panics (nothing wraps).
    big = {**{x: 0 for x in s.fields}, **{s.f(i, i): ONE for i in range(K)},
           s.f(0, K): 1 << 40, s.f(K, K): 1}
    f.add(f"test_{s.module}_transform_point_overflow_panics",
          [load(s, "a", big), pload(K, "p", [0] * K), "let _ = a.transform_point(p);"],
          [f"{S}CgTrait"], attr="#[should_panic]\n")


def rotations(f: File, s: Shape):
    """Delegation to the geometry types (bit-identical) and exact identities."""
    S = s.name
    rng = random.Random(f"tests_cg/rotations/{S}")
    ident = grid(s, lambda i, j: ONE if i == j else 0)
    if s.r == 3:
        angle = rand_raw(rng, 33)
        f.add(f"test_{s.module}_new_rotation", [
            f"let angle = fx({angle});",
            f"assert!({S}CgAngleTrait::new_rotation(angle) == "
            "Rotation2AngleTrait::new(angle).to_homogeneous());",
            f"assert_raws({S}CgAngleTrait::new_rotation(fx(0)), {col(s, ident)});"],
            [f"{S}CgAngleTrait"])
        return
    aa = [rand_raw(rng, 32) for _ in range(3)]
    eul = [rand_raw(rng, 32) for _ in range(3)]
    pt = [rand_raw(rng, 34) for _ in range(3)]
    eye, up = [rand_raw(rng, 35) for _ in range(3)], [0, ONE, 0]
    target = [eye[0] + ONE, eye[1] + (ONE >> 2), eye[2] - 2 * ONE]
    f.add(f"test_{s.module}_rotation_constructors", [
        vload(3, "aa", aa), vload(3, "zero", [0, 0, 0]), pload(3, "pt", pt),
        f"let (roll, pitch, yaw) = (fx({eul[0]}), fx({eul[1]}), fx({eul[2]}));",
        "let axis = UnitTrait::new_normalize(aa);",
        "let angle = fx(" + str(rand_raw(rng, 33)) + ");",
        "let r = Rotation3AngleTrait::new(aa);",
        f"assert!({S}CgAngleTrait::new_rotation(aa) == r.to_homogeneous());",
        f"assert!({S}CgAngleTrait::from_scaled_axis(aa) == "
        "Rotation3AngleTrait::from_scaled_axis(aa).to_homogeneous());",
        f"assert!({S}CgAngleTrait::from_euler_angles(roll, pitch, yaw) == "
        "Rotation3AngleTrait::from_euler_angles(roll, pitch, yaw).to_homogeneous());",
        f"assert!({S}CgAngleTrait::from_axis_angle(axis, angle) == "
        "Rotation3AngleTrait::from_axis_angle(axis, angle).to_homogeneous());",
        f"assert!({S}CgAngleTrait::new_rotation_wrt_point(aa, pt) == "
        "IsometryMatrix3Trait::rotation_wrt_point(Rotation3AngleTrait::from_scaled_axis(aa), pt)"
        ".to_homogeneous());",
        f"assert_raws({S}CgAngleTrait::new_rotation(zero), {col(s, ident)});",
        f"assert_raws({S}CgAngleTrait::new_rotation_wrt_point(zero, pt), {col(s, ident)});"],
        [f"{S}CgAngleTrait"])
    f.add(f"test_{s.module}_view_frames", [
        pload(3, "eye", eye), pload(3, "target", target), vload(3, "up", up),
        f"assert!({S}CgTrait::look_at_rh(eye, target, up) == "
        "IsometryMatrix3Trait::look_at_rh(eye, target, up).to_homogeneous());",
        f"assert!({S}CgTrait::look_at_lh(eye, target, up) == "
        "IsometryMatrix3Trait::look_at_lh(eye, target, up).to_homogeneous());",
        f"assert!({S}CgTrait::face_towards(eye, target, up) == "
        "IsometryMatrix3Trait::face_towards(eye, target, up).to_homogeneous());",
        f"assert!({S}CgTrait::new_observer_frame(eye, target, up) == "
        f"{S}CgTrait::face_towards(eye, target, up));",
        # The observer frame maps the origin to `eye` (`n = 1`: exact).
        f"assert_raws({S}CgTrait::face_towards(eye, target, up).transform_point(Point3 {{ x: "
        f"fx(0), y: fx(0), z: fx(0) }}), {span(eye)});"],
        [f"{S}CgTrait"])


