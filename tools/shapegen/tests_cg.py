def alt_fn(s: Shape, name: str, form: str) -> str:
    """The library's `name` of `s` rendered with the other addend kernel, as a free function."""
    m = next(x for x in cg.methods(s, form) if x.name == name)
    sig = re.sub(r"fn (\w+)\(self: ", rf"fn alt_{form}_\1_{s.module}(m: ", m.sig)
    sig = sig.replace("<T>", "<Fixed>")
    body = re.sub(r"\bself\.", "m.", m.body).replace("R::", "Real::")
    return (f"/// `{s.name}::{name}` with the `{form}` addend kernel (`cg.py` `dot_plus`): the "
            f"same bits.\n{sig} {{\n{body}\n}}")


def render_benches() -> str:
    fns, helpers, need = [], [], set()
    m3, m4, m6 = Shape(3, 3), Shape(4, 4), Shape(6, 6)
    other = "plain" if cg.CG_ADDEND == "wide" else "wide"

    def group(name: str, s: Shape, pre: list[str], expr: str, ety: str, expected: str,
              variants=(), traits=()):
        need.update({s.name, *traits})
        pre = pre + [f"let e: {ety} = black_box({expected});"]
        base = [re.sub(r"let (\w+):", r"let _\1:", line) if not line.startswith("let e:") else line
                for line in pre]
        fns.append(bench(name, "baseline", base + ["assert!(e == e);"]))
        fns.append(bench(name, "library", pre + [f"let r: {ety} = {expr};", "assert!(r == e);"]))
        for v, alt in variants:
            fns.append(bench(name, v, pre + [f"let r: {ety} = {alt};", "assert!(r == e);"]))

    def bb(t: str, var: str, raw) -> str:
        return f"let {var}: {t}<Fixed> = black_box(load({span(raw)}));"

    rng = random.Random("tests_cg/benches")
    for s in (m3, m4, m6):
        K = s.r - 1
        a = raws(rng, s, 34)
        v = [rand_raw(rng, 34) for _ in range(K)]
        V = vec(K).name
        need.add(V)
        pre = [bb(s.name, "a", [a[x] for x in s.fields]), bb(V, "v", v)]
        at = lambda i, j: a[s.f(i, j)]  # noqa: E731
        tr = [f"{s.name}CgTrait"]
        exp = grid(s, lambda i, j: dot([at(i, q) for q in range(K)], v) + at(i, K) if j == K
                   else at(i, j))
        variants = []
        if s.r in (3, 4):
            helpers.append(alt_fn(s, "prepend_translation", other))
            variants = [(f"alt_{other}", f"alt_{other}_prepend_translation_{s.module}(a, v)")]
        group(f"{s.module}_prepend_translation", s, pre, "a.prepend_translation(v)",
              f"{s.name}<Fixed>", f"load({col(s, exp)})", variants, tr)
        exp = grid(s, lambda i, j: mul(v[i], at(K, j)) + at(i, j) if i < K else at(i, j))
        variants = []
        if s.r == 4:
            helpers.append(alt_fn(s, "append_translation", other))
            variants = [(f"alt_{other}", f"alt_{other}_append_translation_{s.module}(a, v)")]
        group(f"{s.module}_append_translation", s, pre, "a.append_translation(v)",
              f"{s.name}<Fixed>", f"load({col(s, exp)})", variants, tr)
        exp = grid(s, lambda i, j: mul(at(i, j), v[i]) if i < K else at(i, j))
        group(f"{s.module}_append_nonuniform_scaling", s, pre, "a.append_nonuniform_scaling(v)",
              f"{s.name}<Fixed>", f"load({col(s, exp)})", (), tr)
        exp = grid(s, lambda i, j: v[i] if j == K and i < K else (ONE if i == j else 0))
        group(f"{s.module}_new_translation", s, [bb(V, "v", v)], f"{s.name}CgTrait::new_translation(v)",
              f"{s.name}<Fixed>", f"load({col(s, exp)})", (), tr)
        b = normaliser_at_least(rng, s, a, v, False)
        group(f"{s.module}_transform_vector", s,
              [bb(s.name, "a", [b[x] for x in s.fields]), bb(V, "v", v)], "a.transform_vector(v)",
              f"{V}<Fixed>", f"load({span(model_transform_vector(s, b, v))})", (), tr)
        if s.r in (3, 4):
            P = f"Point{K}"
            need.add(P)
            p = [rand_raw(rng, 34) for _ in range(K)]
            b = normaliser_at_least(rng, s, a, p, True)
            helpers.append(alt_fn(s, "transform_point", other))
            group(f"{s.module}_transform_point", s,
                  [bb(s.name, "a", [b[x] for x in s.fields]), bb(P, "p", p)],
                  "a.transform_point(p)", f"{P}<Fixed>",
                  f"load({span(model_transform_point(s, b, p))})",
                  [(f"alt_{other}", f"alt_{other}_transform_point_{s.module}(a, p)")], tr)
    # The delegating constructors: their result has no integer model, so the benches check its
    # exact homogeneous corner `m44 == 1` (the rotations' and frames' own oracle tests are in
    # `crates/tests_base`).
    need.update({"Point3", "Vector3"})
    one = f"fx({ONE})"
    aa = [rand_raw(rng, 32) for _ in range(3)]
    group("matrix4_new_rotation", m4, [bb("Vector3", "aa", aa)],
          "Matrix4CgAngleTrait::new_rotation(aa).m44", "Fixed", one, (), ["Matrix4CgAngleTrait"])
    group("matrix4_from_euler_angles", m4,
          [f"let {n}: Fixed = black_box(fx({rand_raw(rng, 32)}));" for n in ("r", "p", "y")],
          "Matrix4CgAngleTrait::from_euler_angles(r, p, y).m44", "Fixed", one, (),
          ["Matrix4CgAngleTrait"])
    eye = [rand_raw(rng, 35) for _ in range(3)]
    target = [eye[0] + ONE, eye[1] + (ONE >> 2), eye[2] - 2 * ONE]
    group("matrix4_look_at_rh", m4,
          [bb("Point3", "eye", eye), bb("Point3", "target", target),
           bb("Vector3", "up", [0, ONE, 0])],
          "Matrix4CgTrait::look_at_rh(eye, target, up).m44", "Fixed", one, (), ["Matrix4CgTrait"])
    body = "\n\n".join(fns)
    geo = sorted(n for n in GEOMETRY if re.search(rf"\b{n}\b", body))
    names = sorted(need | set(geo))
    uses = ["use fixed::Fixed;", "use simba::scalar::Real;", "use nalgebra_testing::black_box;",
            "use nalgebra::{" + ", ".join(names) + "};", "use crate::helpers::{fx, load};"]
    return (f"{HEADER}//! Gas of the homogeneous / computer-graphics helpers "
            f"(`bench_<group>__<variant>`, net of the\n//! `baseline`) on `Matrix3` / `Matrix4` / "
            f"`Matrix6`, and the measured alternative of the kernel of\n//! the sums with an "
            f"exact addend (`alt_{other}`: the library's form is `{cg.CG_ADDEND}`, `cg.py` "
            f"`CG_ADDEND`).\n\n" + "\n".join(uses) + "\n\n" + "\n\n".join(helpers) + "\n\n"
            + body + "\n")


