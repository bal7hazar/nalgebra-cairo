def dot(xs, ys) -> int:
    return floor_scale(sum(x * y for x, y in zip(xs, ys)))


def model_transform_vector(s: Shape, a: dict, v: list[int]) -> list[int]:
    K = s.r - 1
    n = dot([a[s.f(K, k)] for k in range(K)], v)
    w = [div_round(x, n) for x in v] if n else v
    return [dot([a[s.f(i, k)] for k in range(K)], w) for i in range(K)]


def model_transform_point(s: Shape, a: dict, p: list[int]) -> list[int]:
    K = s.r - 1
    n = dot([a[s.f(K, k)] for k in range(K)], p) + a[s.f(K, K)]
    q = [dot([a[s.f(i, k)] for k in range(K)], p) + a[s.f(i, K)] for i in range(K)]
    return [div_round(x, n) for x in q] if n else q


def normaliser_at_least(rng: random.Random, s: Shape, a: dict, x: list[int], point: bool) -> dict:
    """`a` with a last row redrawn until `|n| >= 1/4` (the quotients stay small)."""
    K = s.r - 1
    while True:
        n = dot([a[s.f(K, k)] for k in range(K)], x) + (a[s.f(K, K)] if point else 0)
        if abs(n) >= ONE // 4:
            return a
        a = dict(a)
        for k in range(K + (1 if point else 0)):
            a[s.f(K, k)] = rand_raw(rng, 34)


