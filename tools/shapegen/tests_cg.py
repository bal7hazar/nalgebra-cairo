FILES = {
    "cg": ("Generated tests, `cg` family: scalings, translations, `append_*` / `prepend_*` (and "
           "`_mut`), `transform_vector`, `transform_point`, `new_nonuniform_scaling_wrt_point` on "
           "the six squares, modelled exactly on integer raws.",
           (constructors, compose, transforms)),
    "rotations": ("Generated tests, `rotations` family: the rotation and view constructors of "
                  "`Matrix3` / `Matrix4` (delegation to `Rotation2/3` / `IsometryMatrix3`, exact "
                  "identities).", (rotations,)),
}


def render() -> dict[str, str]:
    files = {}
    for name, (what, gens) in FILES.items():
        f = CgFile(name, what)
        for s in cg.SQUARES:
            if name == "rotations" and s.r not in (3, 4):
                continue
            for gen in gens:
                gen(f, s)
        files[name] = f
    out = {f"{name}.cairo": f.render() for name, f in files.items()}
    out["helpers.cairo"] = HEADER + HELPERS + EXTRA_HELPERS
    out["benches.cairo"] = render_benches()
    mods = ["benches", "helpers", *files]
    out["lib.cairo"] = (HEADER + "//! Generated tests of the homogeneous / computer-graphics "
                        "helpers of the square shapes\n//! (`tools/shapegen/tests_cg.py`, WP "
                        "8.3-P07): Tier A of `tools/shapegen/DESIGN.md` §3.3, exact integer\n//! "
                        "models on the six squares, delegation checks of the rotation and view "
                        "constructors.\n//! Test-only package, not published.\n\n"
                        + "".join(f"#[cfg(test)]\nmod {m};\n" for m in sorted(mods)))
    return out


def outputs(tmp: Path) -> dict[Path, Path]:
    """Writes the package's sources under `tmp/<package>/src`, formatted, and returns
    {committed: generated}."""
    pkg = tmp / PACKAGE
    src = pkg / "src"
    src.mkdir(parents=True)
    (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
    out = {}
    for name, text in render().items():
        (src / name).write_text(text)
        out[ROOT / "crates" / PACKAGE / "src" / name] = src / name
    subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    return out
