"""Generated tests of the homogeneous / computer-graphics helpers (WP 8.3-P07, `cg.py`): the
package `crates/shapes_tests_cg` (`PACKAGE`).

Tier A of `DESIGN.md` §3.3 on the six squares: every operation of `Matrix{N}CgTrait` is a
composition of floored products, fused sums with an exact addend and correctly rounded quotients,
so its result is modelled EXACTLY on integer raws here (`floor_scale`, `div_round`): one exact
case per (square, family), both branches of `transform_vector` / `transform_point` (non-zero and
zero normaliser) and the `_mut` forms. The rotation / frame constructors of `Matrix3/4CgAngleTrait`
and `Matrix4CgTrait` delegate to `Rotation2/3` / `IsometryMatrix3`: their tests check the
delegation (bit-identical to the geometry type's `to_homogeneous`) and exact identities; their
numerics are checked against the oracle in `crates/tests_base` (suite `cg`).

Files (`src/<file>.cairo`): `cg` (the six squares), `rotations` (`Matrix3` / `Matrix4`),
`benches` (`gas/nalgebra_shapes_tests_cg`).
"""

