GEOMETRY = ("Rotation2AngleTrait", "Rotation2Trait", "Rotation3AngleTrait", "Rotation3Trait",
            "IsometryMatrix3Trait", "UnitTrait")


class CgFile(File):
    """`tests_ops.File` that also imports the `Cg` traits and the geometry traits it uses."""

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        names = {n for n in GEOMETRY if re.search(rf"\b{n}\b", body) and n != "UnitTrait"}
        # `to_homogeneous` of a rotation is a method of its non-angle trait.
        names |= {f"Rotation{d}Trait" for d in (2, 3) if f"Rotation{d}AngleTrait" in names}
        names = sorted(names)
        if names:
            self.uses.add(f"use nalgebra::{{{', '.join(names)}}};")
        return File.render(self).replace(
            "// Generated by tools/shapegen/shapegen.py (tests_ops.py)", HEADER.strip())


def grid(s: Shape, g) -> dict[str, int]:
    return {s.f(i, j): g(i, j) for j in range(s.c) for i in range(s.r)}


def vload(n: int, var: str, v: list[int]) -> str:
    return f"let {var}: {vec(n).name}<Fixed> = load({span(v)});"


def pload(n: int, var: str, v: list[int]) -> str:
    return f"let {var}: Point{n}<Fixed> = load({span(v)});"


