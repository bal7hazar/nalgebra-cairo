def scaled_dot(alpha: str, pairs: list[tuple[str, str]], beta: str, c: str) -> str:
    """`alpha * sum(a * b) + beta * c` (`BlasKernels::scaled_dotK`)."""
    flat = ", ".join(f"{a}, {b}" for a, b in pairs)
    return f"BlasKernels::scaled_dot{len(pairs)}({alpha}, {flat}, {beta}, {c})"


def kernel_body(k: int, form: str = SCALED_DOT) -> str:
    acc = "R::wide_zero()"
    for i in range(k):
        acc = f"R::wide_add_prod({acc}, a{i}, b{i})"
    if form == "upstream":
        return f"R::sum_prod2(alpha, R::wide_rescale({acc}), beta, c)"
    return f"R::mul_add(beta, c, R::wide_mul_scalar({acc}, alpha))"


def render_kernels() -> str:
    fns = []
    for k in DIMS:
        args = ", ".join(f"a{i}: T, b{i}: T" for i in range(k))
        terms = " + ".join(f"a{i} * b{i}" for i in range(k))
        fns.append(f"/// `alpha * ({terms}) + beta * c`: the sum exact in `Real::Wide`, times `alpha`\n"
                   f"/// floored once, plus `beta * c` floored once (`Real::mul_add`, exact addend).\n"
                   f"#[inline(always)]\nfn scaled_dot{k}(alpha: T, {args}, beta: T, c: T) -> T {{\n"
                   f"{kernel_body(k)}\n}}")
    return ("/// The fused kernels of the BLAS-like operations (private): `alpha * sum_k(a_k * b_k) + "
            "beta * c`\n/// for 1 to 6 terms. `#[inline(always)]`: a call is the chain written in "
            "place.\n#[generate_trait]\npub(crate) impl BlasKernels<T, impl R: Real<T>, +Drop<T>, "
            "+Drop<R::Wide>> of BlasKernelsTrait<T> {\n" + "\n\n".join(fns) + "\n}")


