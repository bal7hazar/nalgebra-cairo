def trait_name(s: Shape) -> str:
    return f"{s.name}BlasTrait"


def render_blas() -> str:
    uses = ["simba::scalar::Real", "super::matrix_mul::MatrixMul",
            "super::matrix_view::ColumnVectorLen"] + [
        f"super::{s.module}::{s.name}" for s in ALL_SHAPES]
    blocks = [TRAITS, render_kernels()]
    for s in ALL_SHAPES:
        blocks.append(
            item(f"The BLAS-like operations of `{s.name}<T>` (upstream `base/blas.rs`) whose "
                 "operands have one possible shape; `gemv`, `gemm` and `quadform` are the generic "
                 "`MatrixGemv`, `MatrixGemm`... By value or `ref self`, unrolled, no loop.",
                 "#[generate_trait]\n")
            + f"pub impl {s.name}BlasImpl<\n{L.bounds(BOUNDS)}\n> of {trait_name(s)}<T> {{\n"
            + "\n\n".join(x.definition() for x in methods(s)) + "\n}")
    blocks += [BLANKETS] + gemm_impls() + helper_impls()
    doc = ("//! BLAS-like kernels of the static shapes (upstream `nalgebra::base::blas`, "
           "`src/base/blas.rs`):\n//! dot products (`dotc`, `tr_dot`), vector updates (`axpy`, "
           "`axcpy`), matrix-vector products\n//! (`gemv`, `gemv_tr`, `sygemv`...), rank-one "
           "updates (`ger`, `syger`...), matrix products (`gemm`,\n//! `gemm_tr`...) and "
           "quadratic forms (`quadform`, `quadform_tr` and their `_with_workspace` forms).\n"
           "//!\n//! `alpha * sum + beta * c` is the sum exact in `Real::Wide`, times `alpha` "
           "floored once, plus\n//! `beta * c` floored once (`BlasKernels`); `axpy` is one "
           "`Real::sum_prod2`. Overflow panics. The\n//! in-place forms take `ref self` like "
           "upstream's `&mut self`; methods need their trait in scope\n//! (`use "
           "nalgebra::{Matrix3BlasTrait, MatrixGemm};`).\n")
