def impl_head(name: str, trait: str, args: list[str]) -> str:
    return (f"pub impl {name}<\n{L.bounds(BOUNDS)}\n> of {trait}<{', '.join(['T'] + [a + '<T>' for a in args])}> {{\n")


def method(sig: str, body: str, inline: bool) -> str:
    return ("#[inline(always)]\n" if inline else "") + f"{sig} {{\n{body}\n}}"


def small(out: Shape) -> bool:
    """`#[inline(always)]` for vector outputs of at most 4 components, the rule of the products
    (`shapes.product_inline`)."""
    return out.is_vector and out.n <= 4


# The form of the `gemm` impls with several columns: "columns" = the one-column impl of each
# column of `self` (bit-identical, a sixth of the code), "direct" = every entry written in place.
# Measured by `crates/shapes_tests_blas` (`bench_matrix6_gemm__alt_direct`).
GEMM_FORM = "columns"


def gemm_entries(S: Shape, A: Shape, B: Shape) -> str:
    k = A.c
    return "self = " + lit(S, lambda i, j: scaled_dot(
        "alpha", [(f"a.{A.f(i, q)}", f"b.{B.f(q, j)}") for q in range(k)], "beta",
        f"self.{S.f(i, j)}")) + ";"


def gemm_columns(S: Shape, A: Shape, B: Shape) -> str:
    """`self`'s columns updated by the one-column impl (`gemv`'s), then reassembled."""
    Y, X = vec(S.r), vec(A.c)
    lines = []
    for j in range(S.c):
        lines.append(f"let mut c{j} = " + lit(Y, lambda i, _j: f"self.{S.f(i, j)}") + ";")
        lines.append(f"{Y.name}Gemm{A.name}::gemm(ref c{j}, alpha, a, "
                     + lit(X, lambda q, _j: f"b.{B.f(q, j)}") + ", beta);")
    lines.append("self = " + lit(S, lambda i, j: f"c{j}.{Y.f(i, 0)}") + ";")
    return "\n".join(lines)


def gemm_impls(form: str = GEMM_FORM) -> list[str]:
    """`MatrixGemm`: one impl per shape of `self` and inner dimension (216)."""
    out = []
    for r in DIMS:
        for c in DIMS:
            S = Shape(r, c)
            for k in DIMS:
                A, B = Shape(r, k), Shape(k, c)
                body = gemm_entries(S, A, B) if c == 1 or form == "direct" else \
                    gemm_columns(S, A, B)
                out.append(impl_head(f"{S.name}Gemm{A.name}", "MatrixGemm", [S.name, A.name, B.name])
                           + method(f"fn gemm(ref self: {S.name}<T>, alpha: T, a: {A.name}<T>, "
                                    f"b: {B.name}<T>, beta: T)", body, small(S)) + "\n}")
    return out


def helper_impls() -> list[str]:
    """The crate-private `BlasTranspose` / `BlasLastColumn` impls (36 each): struct moves only."""
    out = []
    for s in ALL_SHAPES:
        t, v = s.transposed(), vec(s.r)
        out.append(f"impl {s.name}BlasTranspose<T> of BlasTranspose<{s.name}<T>> {{\n"
                   f"type Output = {t.name}<T>;\n#[inline(always)]\n"
                   f"fn tr(self: {s.name}<T>) -> {t.name}<T> {{\n"
                   + lit(t, lambda i, j: f"self.{s.f(j, i)}") + "\n}\n}")
        out.append(f"impl {s.name}BlasLastColumn<T, +Drop<T>> of BlasLastColumn<{s.name}<T>> {{\n"
                   f"type Output = {v.name}<T>;\n#[inline(always)]\n"
                   f"fn last_column(self: {s.name}<T>) -> {v.name}<T> {{\n"
                   + lit(v, lambda i, _j: f"self.{s.f(i, s.c - 1)}") + "\n}\n}")
    return out


