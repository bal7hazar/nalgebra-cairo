BOUNDS = ["T", "impl R: Real<T>", "+Copy<T>", "+Drop<T>", "+Drop<R::Wide>", "+Add<T>", "+Sub<T>",
          "+Mul<T>"]
DIMS = range(1, 7)
# The kernel of `alpha * sum + beta * c`: "wide" = `mul_add(beta, c, wide_mul_scalar(w, alpha))`
# (two floors, < 2 ulp), "upstream" = `sum_prod2(alpha, rescale(w), beta, c)` (the sum floored
# before the product by `alpha`: `|alpha| + 1` ulp). Measured by the benches of
# `crates/shapes_tests_blas` (`alt_upstream`).
SCALED_DOT = "wide"


def vec(n: int) -> Shape:
    return Shape(n, 1)


