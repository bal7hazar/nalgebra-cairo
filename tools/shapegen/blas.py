"""Templates of the BLAS-like kernels of the static shapes (WP 8.3, API_PARITY package P06, second
half): upstream `src/base/blas.rs` on the 36 shapes, written into ONE shared module,
`crates/nalgebra/src/base/blas.cairo` (upstream's file):

* `{S}BlasTrait` (one `#[generate_trait]` per shape, any `Real` scalar): `dotc`, `tr_dot`,
  `ger` / `gerc` on every shape; `syger` / `hegerc` / `ger_symm` (lower triangle only) on the
  squares; `axcpy`, `axpy`, `sygemv` / `hegemv` (lower triangle only) on the column vectors;
* the operations whose operands have several possible shapes are the methods of generic traits,
  in this module: `MatrixGemm` (`gemm`, one impl per shape of `self` and inner dimension: 216,
  found by `scripts/api_parity.py` on their shapes) and the blanket impls built on it and on
  `MatrixMul` (`scripts/api_parity.py` `RENAMES`): `MatrixGemv` (`gemv` = `gemm` with one
  column), `MatrixGemvTr` (`gemv_tr`, default `gemv_ad`: `gemv` of the transpose),
  `MatrixGemmTr` (`gemm_tr`, default `gemm_ad`: `gemm` of the transpose), `MatrixQuadform`
  (`quadform`, `quadform_with_workspace`: `mid.mul_mat(rhs)` then `gemm_tr`) and
  `MatrixQuadformTr` (`quadform_tr`, `quadform_tr_with_workspace`: `lhs.mul_mat(mid)` then
  `gemm`). The transposes only relabel values (crate-private `BlasTranspose`), so every form is
  bit-identical to the direct kernel for a sixth of the code. The shapes being static, upstream's
  runtime dimension checks are compile errors here (no impl).

The scalar being real, the conjugate / adjoint forms (`dotc`, `gerc`, `hegerc`, `hegemv`,
`gemv_ad`, `gemm_ad`) equal the plain ones: ported under their own names, delegating.

Numerics (upstream's semantics, the project's rounding). Every output scalar of the form
`alpha * sum_k(a_k * b_k) + beta * c` is `BlasKernels::scaled_dotK`: the sum accumulated exactly
in `Real::Wide`, multiplied by `alpha` and floored ONCE (`Real::wide_mul_scalar`), then
`beta * c` added by ONE fused `Real::mul_add` (exact addend): two floor roundings, an error below
2 ulp whatever `alpha` (`simba::Real` has no single-rounding form of a sum of triple products).
Upstream (f64) rounds every product and every sum; its `beta == 0` branch ("the previous content
is ignored") is the same result here: `0 * c` is exactly 0 (fixed point has no NaN), so no branch
is needed. `axpy` (`a * x + b * y`) is ONE fused `Real::sum_prod2` per component (one rounding).
`quadform*` compute the intermediate product (`lhs * mid` / `mid * rhs`) with one fused sum of
products per entry (upstream's `gemv` into the workspace), then the `scaled_dot` of each output.
"""

