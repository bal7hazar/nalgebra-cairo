    a, b, e = raws(rng, s), raws(rng, s), rand_raw(rng)
    S, F = s.name, s.fields
    t = s.transposed()
    rw, cl, m = Shape(1, s.c), Shape(s.r, 1), min(s.r, s.c)
    dg = Shape(m, 1)
    row, column = raws(rng, rw), raws(rng, cl)
    d = [rand_raw(rng) for _ in range(m)]
    ri, cj = rng.randrange(s.r), rng.randrange(s.c)
    lo, up = rng.randrange(s.r), rng.randrange(s.c)
    val = lambda k: e  # noqa: E731
