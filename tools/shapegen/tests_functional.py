             "let mut m = a;", "m.fill_diagonal(e);",
             f"assert_raws(m, {col(s, put(s, a, lambda i, j: i == j, val))});",
             "let mut m = a;", "m.fill_with_identity();",
             f"assert_raws(m, {col(s, {x: ONE if i == j else 0 for x, (i, j) in ij(s).items()})});",
             "let mut m = a;", f"m.fill_row({ri}, e);",
