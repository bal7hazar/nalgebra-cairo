MARKERS = ("EuclideanNorm", "LpNorm", "OneNorm", "UniformNorm", "MatrixMul", "MatrixTrMul")


class FFile(File):
    """`tests_ops.File` that also imports the norm markers and the product traits it uses."""

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        names = [n for n in MARKERS if re.search(rf"\b{n}\b", body)]
        if re.search(r"\.mul_to\(", body):
            names.append("MatrixMul")
        if re.search(r"\.(?:tr|ad)_mul_to\(", body):
            names.append("MatrixTrMul")
        names = sorted(set(names))
        if names:
            self.uses.add(f"use nalgebra::{{{', '.join(names)}}};" if len(names) > 1 else
                          f"use nalgebra::{names[0]};")
        return File.render(self).replace(
            "// Generated by tools/shapegen/shapegen.py (tests_ops.py)", HEADER.strip())


def ij(s: Shape) -> dict[str, tuple[int, int]]:
    return {s.f(i, j): (i, j) for j in range(s.c) for i in range(s.r)}


def put(s: Shape, a: dict, sel, val) -> dict:
    pos = ij(s)
    return {k: (val(k) if sel(*pos[k]) else a[k]) for k in s.fields}


