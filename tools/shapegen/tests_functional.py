def inplace(f: File, s: Shape):
    rng = random.Random(f"tests_functional/inplace/{s.name}")
    a, c = raws(rng, s), raws(rng, s)
    b = {x: nonzero_raw(rng) for x in s.fields}
    k, kd, e = rand_raw(rng, 34), nonzero_raw(rng), rand_raw(rng)
    S, F = s.name, s.fields
    t = s.transposed()
    n = math.isqrt(sum(a[x] ** 2 for x in F))
    mag = 3 * ONE + 12345
    ratio = div_round(mag, n)
    tv = {t.f(j, i): a[s.f(i, j)] for i in range(s.r) for j in range(s.c)}
    zeros = lambda sh: col(sh, {x: 0 for x in sh.fields})  # noqa: E731
    lines = [load(s, "a", a), load(s, "b", b), load(s, "c", c),
             "let mut m = a;", "m.neg_mut();", f"assert_raws(m, {col(s, {x: -a[x] for x in F})});",
             "let mut m = a;", f"m.scale_mut(fx({k}));",
             f"assert_raws(m, {col(s, {x: mul(a[x], k) for x in F})});",
             "let mut m = a;", f"m.unscale_mut(fx({kd}));",
             f"assert_raws(m, {col(s, {x: div_round(a[x], kd) for x in F})});",
             "let mut m = a;", f"assert!(m.normalize_mut() == fx({n}));",
             f"assert_raws(m, {col(s, {x: div_round(a[x], n) for x in F})});",
             "let mut m = a;", f"assert!(m.try_normalize_mut(fx({n})).is_none());",
             f"assert_raws(m, {col(s, a)});",
             f"assert!(m.try_normalize_mut(fx({n - 1})).unwrap() == fx({n}));",
             f"assert_raws(m, {col(s, {x: div_round(a[x], n) for x in F})});",
             "let mut m = a;", f"m.set_magnitude(fx({mag}));",
             f"assert_raws(m, {col(s, {x: mul(a[x], ratio) for x in F})});",
             "let mut m = a;", f"m.add_scalar_mut(fx({e}));",
             f"assert_raws(m, {col(s, {x: a[x] + e for x in F})});",
             "let mut m = a;", "m.component_mul_mut(b);",
             f"assert_raws(m, {col(s, {x: mul(a[x], b[x]) for x in F})});",
             "let mut m = a;", "m.component_div_mut(b);",
             f"assert_raws(m, {col(s, {x: div_round(a[x], b[x]) for x in F})});",
             "let mut m = a;", "m.conjugate_mut();", f"assert_raws(m, {col(s, a)});"]
    if s.is_square:
        for name in ("transpose_mut", "adjoint_mut", "conjugate_transform_mut"):
            lines += ["let mut m = a;", f"m.{name}();", f"assert_raws(m, {col(t, tv)});"]
