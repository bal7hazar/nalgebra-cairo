class VFile(File):
    """`tests_ops.File` that also imports the generic view traits and the points it uses."""

    def render(self) -> str:
        body = "\n\n".join(self.tests)
        names = {n for n in TRAITS if re.search(rf"\b{n}\b", body)}
        for method, trait in (("fixed_rows", "FixedRows"), ("rows", "FixedRows"),
                              ("rows_range", "FixedRows"), ("select_rows", "FixedRows"),
                              ("fixed_columns", "FixedColumns"), ("columns", "FixedColumns"),
                              ("columns_range", "FixedColumns"),
                              ("select_columns", "FixedColumns"), ("fixed_view", "FixedView"),
                              ("view", "FixedView"), ("fixed_slice", "FixedView"),
                              ("slice", "FixedView"), ("row_part", "RowPart"),
                              ("column_part", "ColumnPart"), ("fixed_resize", "FixedResize"),
                              ("resize", "FixedResize"), ("kronecker", "MatrixKronecker")):
            if re.search(rf"\.{method}\(", body):
                names.add(trait)
        for d in range(1, 7):
            for n in (f"Point{d}", f"Point{d}SwizzleTrait"):
                if re.search(rf"\b{n}\b", body) and n not in ("Point2", "Point3"):
                    names.add(n)
        if names:
            self.uses.add(f"use nalgebra::{{{', '.join(sorted(names))}}};" if len(names) > 1 else
                          f"use nalgebra::{names.pop()};")
        return File.render(self).replace(
            "// Generated by tools/shapegen/shapegen.py (tests_ops.py)", HEADER.strip())


def ij(s: Shape) -> dict[str, tuple[int, int]]:
    return {s.f(i, j): (i, j) for j in range(s.c) for i in range(s.r)}


def at(s: Shape, a: dict, i: int, j: int) -> int:
    return a[s.f(i, j)]


def grid(s: Shape, g) -> dict[str, int]:
    """The raws of the `s`-shaped value whose component `(i, j)` is `g(i, j)`."""
    return {s.f(i, j): g(i, j) for j in range(s.c) for i in range(s.r)}


def signed_permutation(rng: random.Random, s: Shape) -> dict[str, int]:
    """A `s`-shaped matrix with orthonormal columns (R >= C): distinct rows get one `±1` each."""
    rows = rng.sample(range(s.r), s.c)
    return grid(s, lambda i, j: (ONE if rng.random() < 0.5 else -ONE) if rows[j] == i else 0)


