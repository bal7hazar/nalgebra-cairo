def swizzle(f: File, s: Shape):
    """The swizzles of a column vector (`Vector1` is `Matrix1`) and of the point of its size."""
    if not s.is_column:
        return
    rng = random.Random(f"tests_views/swizzle/{s.name}")
    a = raws(rng, s)
    lines = [load(s, "a", a)]
    for name in views.swizzle_names(s.r):
        idx = views.SWIZZLES[name]
        lines.append(f"assert_raws(a.{name}(), {span(a[s.f(i, 0)] for i in idx)});")
    f.add(f"test_{s.module}_swizzles", lines, [f"{s.name}Trait"])
    d = s.r
    P = f"Point{d}"
    p = {COORDS[i]: a[s.f(i, 0)] for i in range(d)}
    lines = [f"let p: {P}<Fixed> = load({span(p[COORDS[i]] for i in range(d))});"]
    for name in views.swizzle_names(d):
        idx = views.SWIZZLES[name]
        lines.append(f"assert_raws(p.{name}(), {span(p[COORDS[i]] for i in idx)});")
    if d == 3:
        # `Point3::xy` predates the swizzles and stays in `Point3Trait`.
        f.uses.add("use nalgebra::base::point3::Point3Trait;")
    f.add(f"test_point{d}_swizzles", lines, [f"{P}SwizzleTrait"])


def rows(f: File, s: Shape):
    rng = random.Random(f"tests_views/rows/{s.name}")
    a = raws(rng, s)
    S = s.name
    ri, cj = rng.randrange(s.r), rng.randrange(s.c)
    k = rng.randrange(s.n)
    lines = [load(s, "a", a),
             f"assert!(a.nrows() == {s.r});", f"assert!(a.ncols() == {s.c});",
             f"assert!(a.shape() == ({s.r}, {s.c}));",
             f"assert!(a.is_square() == {str(s.is_square).lower()});",
             f"assert!(a.vector_to_matrix_index({k}) == ({k % s.r}, {k // s.r}));",
             f"assert_raws(a.row({ri}), {span(at(s, a, ri, j) for j in range(s.c))});",
             f"assert_raws(a.column({cj}), {span(at(s, a, i, cj) for i in range(s.r))});",
             f"assert_raws(a.upper_triangle(), "
             f"{col(s, grid(s, lambda i, j: 0 if i > j else at(s, a, i, j)))});",
             f"assert_raws(a.lower_triangle(), "
             f"{col(s, grid(s, lambda i, j: 0 if i < j else at(s, a, i, j)))});"]
    rv, cv = Shape(s.c, 1), Shape(s.r, 1)
    rargs = ", ".join(f"r{i}" for i in range(s.r))
    cargs = ", ".join(f"c{j}" for j in range(s.c))
    lines += [f"let r{i}: {rv.name}<Fixed> = load({span(at(s, a, i, j) for j in range(s.c))});"
              for i in range(s.r)]
    lines.append(f"assert_raws({S}Trait::from_rows({rargs}), {col(s, a)});")
    lines += [f"let c{j}: {cv.name}<Fixed> = load({span(at(s, a, i, j) for i in range(s.r))});"
              for j in range(s.c)]
    lines.append(f"assert_raws({S}Trait::from_columns({cargs}), {col(s, a)});")
    e = rng.randrange(-ONE * 8, ONE * 8)
    if s.r < 6 or s.c < 6:
        lines.append(f"let e = fx({e});")
    if s.r < 6:
        p = rng.randrange(s.r + 1)
        o = Shape(s.r + 1, s.c)
        lines.append(f"assert_raws(a.insert_row({p}, e), {col(o, grid(o, lambda i, j: e if i == p else at(s, a, i if i < p else i - 1, j)))});")
    if s.c < 6:
        p = rng.randrange(s.c + 1)
        o = Shape(s.r, s.c + 1)
        lines.append(f"assert_raws(a.insert_column({p}, e), {col(o, grid(o, lambda i, j: e if j == p else at(s, a, i, j if j < p else j - 1)))});")
    if s.r > 1:
        p = rng.randrange(s.r)
        o = Shape(s.r - 1, s.c)
        lines.append(f"assert_raws(a.remove_row({p}), {col(o, grid(o, lambda i, j: at(s, a, i if i < p else i + 1, j)))});")
    if s.c > 1:
        p = rng.randrange(s.c)
        o = Shape(s.r, s.c - 1)
        lines.append(f"assert_raws(a.remove_column({p}), {col(o, grid(o, lambda i, j: at(s, a, i, j if j < p else j + 1)))});")
    # Properties on exact matrices: a random one is not orthogonal (its columns are not unit).
    lines.append("assert!(!a.is_orthogonal(4));")
    if s.r >= s.c:
        q = signed_permutation(rng, s)
        lines += [load(s, "q", q), "assert!(q.is_orthogonal(0));"]
    if s.is_square and s.r in views.DET_SQUARES:
        ident = grid(s, lambda i, j: ONE if i == j else 0)
        swapped = grid(s, lambda i, j: ONE if {0: 1, 1: 0}.get(j, j) == i else 0)
        lines += [load(s, "id", ident), load(s, "sw", swapped),
                  f"let z: {S}<Fixed> = load({col(s, {x: 0 for x in s.fields})});",
                  "assert!(id.is_invertible());", "assert!(sw.is_invertible());",
                  "assert!(!z.is_invertible());", "assert!(id.is_special_orthogonal(0));",
                  "assert!(!sw.is_special_orthogonal(0));", "assert!(!a.is_special_orthogonal(4));"]
    f.add(f"test_{s.module}_rows_columns", lines, [f"{S}Trait"])
    f.add(f"test_{s.module}_row_out_of_bounds_panics",
          [load(s, "a", a), f"let _ = a.row({s.r});"], [f"{S}Trait"],
          attr="#[should_panic(expected: 'nalgebra: index out of bounds')]\n")


def blocks(f: File, s: Shape):
    rng = random.Random(f"tests_views/blocks/{s.name}")
    a = raws(rng, s)
    S = s.name
    lines = [load(s, "a", a)]
    # FixedRows
    d = rng.randrange(1, s.r + 1)
    o = Shape(d, s.c)
    i0 = rng.randrange(s.r - d + 1)
    blk = lambda o, di, dj: col(o, grid(o, lambda i, j: at(s, a, i + di, j + dj)))  # noqa: E731
    sel = [rng.randrange(s.r) for _ in range(d)]
    lines += [f"let r: {o.name}<Fixed> = a.fixed_rows({i0});", f"assert_raws(r, {blk(o, i0, 0)});",
              f"let r: {o.name}<Fixed> = a.rows({i0}, {d});", f"assert_raws(r, {blk(o, i0, 0)});",
              f"let r: {o.name}<Fixed> = a.rows_range({i0}..{i0 + d});",
              f"assert_raws(r, {blk(o, i0, 0)});",
              f"let r: {o.name}<Fixed> = a.select_rows(array!{sel}.span());",
              f"assert_raws(r, {col(o, grid(o, lambda i, j: at(s, a, sel[i], j)))});"]
    # FixedColumns
    d = rng.randrange(1, s.c + 1)
    o = Shape(s.r, d)
    j0 = rng.randrange(s.c - d + 1)
    sel = [rng.randrange(s.c) for _ in range(d)]
    lines += [f"let c: {o.name}<Fixed> = a.fixed_columns({j0});", f"assert_raws(c, {blk(o, 0, j0)});",
              f"let c: {o.name}<Fixed> = a.columns({j0}, {d});", f"assert_raws(c, {blk(o, 0, j0)});",
              f"let c: {o.name}<Fixed> = a.columns_range({j0}..{j0 + d});",
              f"assert_raws(c, {blk(o, 0, j0)});",
              f"let c: {o.name}<Fixed> = a.select_columns(array!{sel}.span());",
              f"assert_raws(c, {col(o, grid(o, lambda i, j: at(s, a, i, sel[j])))});"]
    # FixedView
    o = Shape(rng.randrange(1, s.r + 1), rng.randrange(1, s.c + 1))
    i0, j0 = rng.randrange(s.r - o.r + 1), rng.randrange(s.c - o.c + 1)
    lines += [f"let v: {o.name}<Fixed> = a.fixed_view({i0}, {j0});", f"assert_raws(v, {blk(o, i0, j0)});",
              f"let v: {o.name}<Fixed> = a.view(({i0}, {j0}), ({o.r}, {o.c}));",
              f"assert_raws(v, {blk(o, i0, j0)});",
              f"let v: {o.name}<Fixed> = a.fixed_slice({i0}, {j0});", f"assert_raws(v, {blk(o, i0, j0)});",
              f"let v: {o.name}<Fixed> = a.slice(({i0}, {j0}), ({o.r}, {o.c}));",
              f"assert_raws(v, {blk(o, i0, j0)});"]
    # Parts
    n, i0 = rng.randrange(1, s.c + 1), rng.randrange(s.r)
    o = Shape(1, n)
    lines += [f"let p: {o.name}<Fixed> = a.row_part({i0}, {n});", f"assert_raws(p, {blk(o, i0, 0)});"]
    n, j0 = rng.randrange(1, s.r + 1), rng.randrange(s.c)
    o = Shape(n, 1)
    lines += [f"let p: {o.name}<Fixed> = a.column_part({j0}, {n});", f"assert_raws(p, {blk(o, 0, j0)});"]
    # FixedResize
    o = rng.choice(ALL_SHAPES)
    e = rng.randrange(-ONE * 8, ONE * 8)
    rs = col(o, grid(o, lambda i, j: at(s, a, i, j) if i < s.r and j < s.c else e))
    lines += [f"let z: {o.name}<Fixed> = a.fixed_resize(fx({e}));", f"assert_raws(z, {rs});",
              f"let z: {o.name}<Fixed> = a.resize({o.r}, {o.c}, fx({e}));", f"assert_raws(z, {rs});"]
    # MatrixKronecker
    b = rng.choice(views.kron_rhs(s))
    vb = raws(rng, b)
    o = Shape(s.r * b.r, s.c * b.c)
    kr = grid(o, lambda i, j: mul(at(s, a, i // b.r, j // b.c), vb[b.f(i % b.r, j % b.c)]))
    lines += [load(b, "b", vb), f"assert_raws(a.kronecker(b), {col(o, kr)});"]
    f.add(f"test_{s.module}_blocks", lines)
    o = Shape(1, s.c)
    f.add(f"test_{s.module}_rows_dimension_mismatch_panics",
          [load(s, "a", a), f"let _r: {o.name}<Fixed> = a.rows(0, 2);"], [],
          attr="#[should_panic(expected: 'nalgebra: dimension mismatch')]\n")
    o = Shape(s.r, 1)
    f.add(f"test_{s.module}_fixed_columns_out_of_bounds_panics",
          [load(s, "a", a), f"let _c: {o.name}<Fixed> = a.fixed_columns({s.c});"], [],
          attr="#[should_panic(expected: 'nalgebra: index out of bounds')]\n")


