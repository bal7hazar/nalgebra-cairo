"""Generated tests of the swizzles, rows, columns, blocks and edition (WP 8.2c, `views.py`): the
packages `crates/shapes_tests_{views,blocks}` (`PACKAGES`; one package for the three families
measured 7.5 GB of peak `scarb build --test`).

Tier A of `DESIGN.md` §3.3 on the 36 shapes and the six points: one exact case per (shape,
family). Every operation of this WP only moves components, except `kronecker` (one floored
product per component, the integer model of `tests_ops.mul`) and the properties
(`is_orthogonal`, `is_invertible`, `is_special_orthogonal`, checked on exact signed
permutations and on random matrices). The sizes chosen by the output type (`fixed_rows`,
`fixed_view`, `fixed_resize`, `kronecker`...) are drawn per shape from a seeded generator, so
every shape exercises one pair of each family; the dimension-mismatch and out-of-bounds panics
have one `#[should_panic]` test per (shape, family).

Families and files (`src/<file>.cairo`): `swizzle` (vectors and points), `rows` (`row`,
`column`, sizes, triangles, `from_rows` / `from_columns`, `insert_*` / `remove_*`,
properties), `blocks` (`FixedRows`, `FixedColumns`, `FixedView`, `RowPart`, `ColumnPart`,
`FixedResize`, `MatrixKronecker`), and `benches` (`gas/nalgebra_shapes_tests_views`).
"""

