# The test-only packages (compile budget: each under ~7 GB of peak `scarb build --test`), their
# families, and the rows of the shapes of each file of a family.
PACKAGES = {
    "shapes_tests_views": [("rows", [(1, 3), (4, 6)])],
    "shapes_tests_blocks": [("blocks", [(1, 3), (4, 6)]), ("swizzle", [(1, 6)])],
}
BENCHES_IN = "shapes_tests_views"
FAMILIES = {
    "swizzle": ("Generated tests, `swizzle` family: `xx() .. zzz()` on the column vectors and "
                "the points.", swizzle),
    "rows": ("Generated tests, `rows` family: `row`, `column`, sizes, triangles, `from_rows`, "
             "`from_columns`, `insert_*` / `remove_*`, orthogonality and invertibility.", rows),
    "blocks": ("Generated tests, `blocks` family: `FixedRows`, `FixedColumns`, `FixedView`, "
               "`RowPart`, `ColumnPart`, `FixedResize`, `MatrixKronecker`.", blocks),
}


def render(package: str) -> dict[str, str]:
    """{file name under `src/`: text} of one of the `PACKAGES`."""
    files: dict[str, File] = {}
    for name, groups in PACKAGES[package]:
        what, gen = FAMILIES[name]
        for lo, hi in groups:
            key = name if (lo, hi) == (1, 6) else f"{name}_r{lo}_{hi}"
            rows_note = f" Shapes of {lo} to {hi} rows." if (lo, hi) != (1, 6) else ""
            f = VFile(key, what + rows_note)
            for s in ALL_SHAPES:
                if lo <= s.r <= hi:
                    gen(f, s)
            files[key] = f
    out = {f"{name}.cairo": f.render() for name, f in files.items()}
    out["helpers.cairo"] = HEADER + HELPERS + EXTRA_HELPERS
    mods = ["helpers", *files]
    if package == BENCHES_IN:
        out["benches.cairo"] = render_benches()
        mods.append("benches")
    families = ", ".join(f"`{n}`" for n, _ in PACKAGES[package])
    out["lib.cairo"] = (HEADER + "//! Generated tests of the swizzles, rows, columns and blocks of "
                        "the static shapes\n//! (`tools/shapegen/tests_views.py`, WP 8.2c): Tier A "
                        "of `tools/shapegen/DESIGN.md` §3.3,\n//! one exact case per (shape, family) "
                        f"on the 36 shapes and the six points; families {families}.\n//! Test-only "
                        "package, not published.\n\n"
                        + "".join(f"#[cfg(test)]\nmod {m};\n" for m in sorted(mods)))
    return out


def outputs(tmp: Path) -> dict[Path, Path]:
    """Writes the packages' sources under `tmp/<package>/src`, formatted, and returns
    {committed: generated}."""
    out = {}
    for package in PACKAGES:
        pkg = tmp / package
        src = pkg / "src"
        src.mkdir(parents=True)
        (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
        for name, text in render(package).items():
            (src / name).write_text(text)
            out[ROOT / "crates" / package / "src" / name] = src / name
        subprocess.run(["scarb", "fmt"], cwd=pkg, check=True)
    return out
