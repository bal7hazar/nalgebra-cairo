def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true", help="fail if a committed output is stale")
    args = p.parse_args()
    files = outputs()
    with tempfile.TemporaryDirectory() as tmp:
        pkg = Path(tmp)
        (pkg / "Scarb.toml").write_text(FMT_MANIFEST)
        src = pkg / "src"
        src.mkdir()
        (src / "lib.cairo").write_text("")
        for rel, text in files.items():
            # Only the Cairo sources go through `scarb fmt`; manifests are written as they are.
            path = src / rel if rel.endswith(".cairo") else pkg / "raw" / rel
            path.parent.mkdir(parents=True, exist_ok=True)
