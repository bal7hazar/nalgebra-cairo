def svd_packages() -> dict[str, str]:
    out = {}
    for pkg, (what, keep) in SVD_PACKAGES.items():
        base = f"crates/{pkg}/"
        shapes = [(r, c) for r in range(1, 7) for c in range(1, 7) if keep(r, c)]
        out[base + "Scarb.toml"] = TEST_MANIFEST.format(
            name=pkg, features='"eigen", "svd"',
            description=f"Tests and gas benchmarks of the SVD of the {what}: "
                                  "singular values, rank, pseudo-inverse, polar decomposition "
                                  "(WP 8.5-P14b; not published).")
        if pkg == "tests_linalg_svd":
            # `Svd2PartialEq` / `Svd3PartialEq` (`ordered.cairo`) are behind the helper's `svd`.
            out[base + "Scarb.toml"] = out[base + "Scarb.toml"].replace(
                'nalgebra_tests_utils = { path = "../tests_utils" }',
                'nalgebra_tests_utils = { path = "../tests_utils", features = ["svd"] }')
        need, vecs = set(), set()
        for r, c in shapes:
            k = min(r, c)
            need |= {(r, c), (c, r), (r, r), (r, k), (k, c)}
            vecs |= {k, r}
        eq = [(svd_name(r, c), ("u", "singular_values", "v_t")) for r, c in shapes
              if (r, c) not in SVD_EXISTING]
        out[base + "src/builders.cairo"] = render_builders(need, vecs, eq)
        mods = ["builders", "oracle_svd"]
        if pkg == "tests_linalg_svd":
            mods += ["ordered", "alt", "oracle_svd23"]
            out[base + "src/ordered.cairo"] = SVD_ORDERED
            out[base + "src/alt.cairo"] = render_alt_one_sided(4).replace(
                "ALT_MEASURED", repr(ALT_MEASURED))
        for r, c in shapes:
            m = f"svd{svd_suffix(r, c)}"
            mods.append(m)
            out[base + f"src/{m}.cairo"] = render_svd_tests(r, c, SVD_BOUNDS, "oracle_svd")
